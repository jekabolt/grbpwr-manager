// КАЛИБРОВКА КОЭФФИЦИЕНТА РАСКРОЯ ПО ФАКТУ НАСТИЛОВ (Ф5б.3, решение Р4) — §4.2 спеки.
//
//	дрейф_настила = actual_qty / planned_lay_qty − 1
//	предложение   = МЕДИАНА дрейфов настилов этого артикула, где есть И план, И факт
//
// Чистая арифметика: ни базы, ни провода, ни часов. Настилы приезжают ЗНАЧЕНИЯМИ, потому что отбор
// «настилы этого артикула» — вопрос к store, а не к правилу.
//
// ─────────────────────────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЗДЕСЬ НЕТ КРУГА. ЭТО САМОЕ НЕОЧЕВИДНОЕ МЕСТО ФАЗЫ, И ЕГО НАДО ПРОЧИТАТЬ ДО ПЕРВОЙ ПРАВКИ.
// ─────────────────────────────────────────────────────────────────────────────────────────────────
//
// Решение Р4 фазы Ф4 постановило: КОЭФФИЦИЕНТ РАСКРОЯ НА ПУТИ НАСТИЛОВ НЕ ПРИМЕНЯЕТСЯ. План настила —
// чистая геометрия: длина маркера × слои + концевые потери, и больше ничего. Коэффициент же покрывает
// ровно то, чего геометрия настила НЕ ВИДИТ: усадку, обход пороков, сращивание, оттеночные полосы.
// Два непересекающихся множества причин.
//
// Отсюда и берётся право делить одно на другое: отношение факт/план — ЧЕСТНАЯ ОЦЕНКА ТОГО, ЧТО
// КОЭФФИЦИЕНТ ОБЯЗАН ПОКРЫТЬ, именно потому, что план настила коэффициента не содержит.
//
// ЕСЛИ БЫ КОЭФФИЦИЕНТ ПРИМЕНЯЛСЯ К НАСТИЛУ, КАЛИБРОВКА СТАЛА БЫ КРУГОВОЙ: коэффициент правил бы
// план, план правил бы коэффициент, и величина сходилась бы к произвольной точке, зависящей от
// того, сколько раз её пересчитали, а не от того, сколько ткани ушло. Первый же пересчёт дал бы
// «дрейф ≈ 0» на артикуле, который на самом деле садится на 6%: коэффициент уже был бы зашит в
// знаменатель, и измерение подтвердило бы само себя. Поэтому НЕ ПРИМЕНЯТЬ коэффициент к настилу —
// не только вопрос двойного счёта в потребности, но и УСЛОВИЕ ТОГО, ЧТО КАЛИБРОВКА ВООБЩЕ ИМЕЕТ
// СМЫСЛ. Тот, кто соберётся «для единообразия» умножить план настила на коэффициент, ломает не
// потребность, а вот эту функцию, и сломает её молча: числа продолжат считаться.
//
// ─────────────────────────────────────────────────────────────────────────────────────────────────
//
// МЕДИАНА, А НЕ СРЕДНЕЕ. Один настил с ошибкой ввода («ввели 500 вместо 50») сдвигает среднее
// непоправимо — и сдвигает НАВСЕГДА, потому что средним артикул считается заново каждый раз, а
// опечатку никто не ищет, пока предложение не станет абсурдным. Медиана переживает такую строку без
// единого изменения ответа. Это не вкусовая статистика: замеры цеха делают руками, в спешке, на
// рулоне, и одна цифра из десяти будет неверной.
//
// МЕНЬШЕ ТРЁХ НАСТИЛОВ — ПРЕДЛОЖЕНИЯ НЕТ ВОВСЕ, а говорится «фактов пока мало». Коэффициент,
// выведенный из одного замера, — это ровно та «догадка в одежде числа», которую Р4 уже отвергла у
// самого коэффициента; выдать её обратно под именем «предложение, основанное на факте» было бы хуже
// исходной догадки, потому что у неё появилась бы ложная опора. И число настилов отдаётся ВМЕСТЕ с
// предложением: предложение без своей опоры нечем взвесить — «1.06 по трём настилам» и «1.06 по
// сорока» это два разных утверждения, и решает по ним человек по-разному.
//
// ПРЕДЛОЖЕНИЕ, А НЕ ПРИМЕНЕНИЕ. Здесь нет и не будет писателя. Автоприменение подменило бы решение
// владельца артикула числом, которого он не выбирал, — та же дисциплина, что у нормы в Ф3 и у
// пер-размерного расхода в Ф2.4. Функция возвращает предложение; принимает его рука.

// MinLaysForCoefficientSuggestion — порог §4.2: НИЖЕ ТРЁХ НАСТИЛОВ ПРЕДЛОЖЕНИЯ НЕТ.
//
// Именованная константа, а не тройка в условии, потому что порог — это утверждение о том, сколько
// замеров превращают наблюдение в основание, и его должно быть видно из вызывающего кода и из теста.
const MinLaysForCoefficientSuggestion = 3

// coefficientScale — знаков после запятой у material.cutting_coefficient (DECIMAL(6,4), 0270), и
// ровно столько же принимает валидация провода (dto.MaterialFromPb, scale 4).
//
// Предложение ОКРУГЛЯЕТСЯ до этой точности здесь, а не на клиенте: медиана дрейфов — результат
// деления и приходит с шестнадцатью знаками, а поле такое число не примет. Предложение, которое
// нельзя сохранить одним нажатием, — это не предложение.
const coefficientScale = 4

// Границы, в которых коэффициент вообще хранится: chk_material_cutting_coefficient (0270) держит
// [1, 3], и entity.Material.EffectiveCuttingCoefficient читает всё, что меньше единицы, как «не
// задано». Предложение за этими границами не отдаётся числом — см. CoefficientSuggestionOutOfRange.
var (
	coefficientOne = decimal.NewFromInt(1)
	coefficientMin = decimal.NewFromInt(1)
	coefficientMax = decimal.NewFromInt(3)
	coefficientTwo = decimal.NewFromInt(2)
)

// CoefficientSuggestionStatus is the answer to «есть ли что предложить».
//
// НУЛЕВОЕ ЗНАЧЕНИЕ — «ФАКТОВ МАЛО», И ЭТО ЕДИНСТВЕННОЕ, ЧЕМ ОНО МОЖЕТ БЫТЬ. Забытое поле обязано
// читаться как отсутствие предложения: `MaterialCoefficientSuggestion{}` — честный ответ про артикул,
// у которого фактов нет вовсе, и он же — ответ того, кто структуру не заполнил. Ready стоит последним
// и никогда не выпадает по умолчанию: число нельзя получить, забыв его посчитать. Та же дисциплина,
// что у LayCheckStatus двумя файлами раньше.
type CoefficientSuggestionStatus int

const (
	// CoefficientSuggestionTooFewFacts — настилов с планом И фактом меньше MinLaysForCoefficientSuggestion.
	CoefficientSuggestionTooFewFacts CoefficientSuggestionStatus = iota
	// CoefficientSuggestionOutOfRange — медиана посчитана, но коэффициент из неё поле не примет
	// (вне [1, 3]). Измерение отдаётся, число-предложение — нет.
	CoefficientSuggestionOutOfRange
	// CoefficientSuggestionReady — предложение есть, и его можно сохранить как есть.
	CoefficientSuggestionReady
)

func (s CoefficientSuggestionStatus) String() string {
	switch s {
	case CoefficientSuggestionTooFewFacts:
		return "TOO_FEW_FACTS"
	case CoefficientSuggestionOutOfRange:
		return "OUT_OF_RANGE"
	case CoefficientSuggestionReady:
		return "READY"
	}
	return fmt.Sprintf("CoefficientSuggestionStatus(%d)", int(s))
}

// LayFactObservation is ONE настил's pair of numbers: what its geometry planned and what the shop
// measured. Both NullDecimal, and both absences are real states of a live row — планов без факта
// большинство, а факт без плана бывает у настила, чей слот BOM удалён.
type LayFactObservation struct {
	LayId  int
	LayKey string
	// PlannedQty is потребность ЭТОГО настила по геометрии — длина маркера × слои + концевые потери,
	// в единице артикула. БЕЗ КОЭФФИЦИЕНТА (Р4): см. шапку файла, это и есть условие некруговости.
	PlannedQty decimal.NullDecimal
	// ActualQty is production_run_lay.actual_qty (0285) — сколько РЕАЛЬНО ушло, замерено рулоном
	// до/после либо взвешиванием, в единице артикула (Р3).
	ActualQty decimal.NullDecimal
	// ActualUom is production_run_lay.actual_uom — единица, В КОТОРОЙ замеряли. Р3 говорит, что факт
	// приходит в единице артикула, и эта колонка лишь называет её; расхождение с единицей артикула —
	// признак того, что Р3 нарушен, и такой настил в медиану не идёт. Пусто с любой стороны — не
	// улика, а отсутствие улики: настил считается.
	ActualUom string
}

// LayFactDrift is ONE настил's вклад в калибровку, С ТРЕТЬИМ ОТВЕТОМ В ТИПЕ.
//
// Отдаётся наружу целиком и в порядке входа, потому что 06-materials-reality требует, чтобы дрейф
// план-факт был ВИДЕН НА АРТИКУЛЕ. Медиана по построению прячет выброс — а выброс это, скорее всего,
// опечатка, и увидеть её должен человек. Отдать только медиану значило бы починить арифметику и
// оставить неверную строку в базе навсегда.
type LayFactDrift struct {
	LayId  int
	LayKey string
	// Drift is факт/план − 1. INVALID = настил в медиану НЕ ВХОДИТ, и тогда Skipped говорит почему.
	Drift decimal.NullDecimal
	// Skipped is причина невхождения. ПУСТО ТОЛЬКО У ВОШЕДШИХ — та же дисциплина, что у
	// LayCheck.Detail: строка без числа и без объяснения неотличима от бага.
	Skipped string
}

// Counted reports whether this настил stood under the median.
func (d LayFactDrift) Counted() bool { return d.Drift.Valid }

// MaterialCoefficientSuggestion is the whole answer about ONE артикул.
type MaterialCoefficientSuggestion struct {
	Status CoefficientSuggestionStatus
	// MedianDrift is медиана дрейфов — ИЗМЕРЕНИЕ, в долях (0.06 = «уходит на 6% больше плана»).
	// VALID всегда, когда настилов хватило, ДАЖЕ при OUT_OF_RANGE: измерение остаётся фактом, когда
	// поле его не принимает, и человеку показывают именно его.
	MedianDrift decimal.NullDecimal
	// Suggested is МНОЖИТЕЛЬ для material.cutting_coefficient — MedianDrift + 1, округлённый до
	// coefficientScale. ЕДИНИЦА ИЗМЕРЕНИЯ РАЗНАЯ У ЭТИХ ДВУХ ЧИСЕЛ, И ЭТО НЕ ИЗБЫТОЧНОСТЬ: 0270
	// хранит коэффициент МНОЖИТЕЛЕМ (1.0300), «потому что путь потребности на него умножает, а
	// процент требовал бы +1, который никто не вспомнит написать». Спека §4.2 формулирует
	// предложение как медиану ДРЕЙФОВ; отдать наружу только её значило бы поставить этот забытый +1
	// на вызывающего — и получить артикул с коэффициентом 0.06, то есть с «не задано» после
	// EffectiveCuttingCoefficient. Поэтому наружу едут ОБА числа, и Suggested — то, которое
	// сохраняется.
	//
	// INVALID при TOO_FEW_FACTS и при OUT_OF_RANGE. Ни в одном случае это не «1.0»: коэффициент,
	// которого нет, и коэффициент, равный единице, — разные утверждения об артикуле.
	Suggested decimal.NullDecimal
	// LayCount is сколько настилов стоит под медианой. Едет ВСЕГДА, в том числе при TOO_FEW_FACTS,
	// где оно и есть содержание ответа («фактов пока 2 из 3»).
	LayCount int
	// Drifts is каждое наблюдение В ПОРЯДКЕ ВХОДА, вошедшее и невошедшее.
	Drifts []LayFactDrift
	// Detail is фраза для человека. НЕПУСТА ВСЕГДА, включая READY: предложение без числа настилов,
	// на которых оно стоит, — половина утверждения (§4.2).
	Detail string
}

// LayFactDriftOf считает дрейф ОДНОГО настила и НАЗЫВАЕТ причину, если настил в расчёт не идёт.
//
// articleUom — единица артикула; пустая строка означает «единица артикула неизвестна», и тогда
// сверка единиц не производится вовсе. Придумывать расхождение из отсутствующих данных нельзя: это
// молча выбросило бы настилы из медианы и опустило бы артикул ниже порога трёх, а на экране это
// выглядело бы как «фактов мало» при полном журнале замеров.
func LayFactDriftOf(o LayFactObservation, articleUom string) LayFactDrift {
	d := LayFactDrift{LayId: o.LayId, LayKey: o.LayKey}
	switch {
	case !o.PlannedQty.Valid || !o.PlannedQty.Decimal.IsPositive():
		// План настила есть у каждого настила по построению, поэтому его отсутствие — это не «настил
		// без плана», а настил, чей план посчитать не удалось (слот BOM удалён, маркер отвязан). В
		// медиану он не идёт: делить на него нечего, а подставить 1 значило бы объявить дрейфом весь
		// факт целиком.
		d.Skipped = "у настила нет посчитанного плана — делить факт не на что"
	case !o.ActualQty.Valid:
		// Обычное состояние: настил спланирован, ткань ещё не мерили. Это НЕ дрейф 0 — настил без
		// факта, посчитанный за «сошлось», притянул бы медиану к нулю тем сильнее, чем меньше в цехе
		// меряют, то есть ровно тогда, когда калибровке верить нельзя.
		d.Skipped = "факт расхода по настилу не введён"
	case !o.ActualQty.Decimal.IsPositive():
		// chk_prlay_actual_qty (0285) такую строку не пропустит; вход берётся значениями, поэтому
		// проверка здесь своя. Ноль — это не «ушло нисколько», это незаполненная форма.
		d.Skipped = fmt.Sprintf("факт расхода не положителен (%s)", o.ActualQty.Decimal.String())
	default:
		if u, a := normaliseUom(o.ActualUom), normaliseUom(articleUom); u != "" && a != "" && u != a {
			// Метры, делённые на килограммы, дают число, которое выглядит как дрейф. Ровно этот класс
			// молча-неверных сложений Ф5а закрыла перечнем единиц; здесь он закрывается тем же
			// способом — настил, чей замер не в единице артикула, НАЗЫВАЕТСЯ и не считается.
			d.Skipped = fmt.Sprintf("факт замерен в %q, а артикул считается в %q — делить нельзя", u, a)
			return d
		}
		d.Drift = decimal.NullDecimal{
			Decimal: o.ActualQty.Decimal.Div(o.PlannedQty.Decimal).Sub(coefficientOne),
			Valid:   true,
		}
	}
	return d
}

// MaterialCoefficientSuggestionOf — предложение коэффициента для ОДНОГО артикула по его настилам.
//
// Вызывающий обязан передать настилы ОДНОГО артикула: смешать два артикула здесь нечем — у функции
// нет ни идентификатора материала, ни права его спрашивать, — и медиана по смеси была бы числом ни о
// чём. Отбор — работа store; правило — работа этой функции.
func MaterialCoefficientSuggestionOf(lays []LayFactObservation, articleUom string) MaterialCoefficientSuggestion {
	out := MaterialCoefficientSuggestion{Drifts: make([]LayFactDrift, 0, len(lays))}
	counted := make([]decimal.Decimal, 0, len(lays))
	for _, o := range lays {
		d := LayFactDriftOf(o, articleUom)
		out.Drifts = append(out.Drifts, d)
		if d.Counted() {
			counted = append(counted, d.Drift.Decimal)
		}
	}
	out.LayCount = len(counted)

	if out.LayCount < MinLaysForCoefficientSuggestion {
		out.Status = CoefficientSuggestionTooFewFacts
		out.Detail = fmt.Sprintf("фактов пока мало: настилов с планом и фактом %d, нужно %d — коэффициент, выведенный из одного-двух замеров, это догадка в одежде числа",
			out.LayCount, MinLaysForCoefficientSuggestion)
		return out
	}

	// Медиана считается в полной точности, а округляется ОДИН РАЗ и уже на множителе: округли мы
	// дрейф отдельно, два числа на экране могли бы разойтись в последнем знаке, и владелец увидел бы
	// «дрейф 3.33%, предложение 1.0334». Поэтому дрейф выводится ОБРАТНО из округлённого множителя —
	// Suggested − 1 — и совпадение с ним гарантировано арифметически, а не дисциплиной.
	suggested := medianDecimal(counted).Add(coefficientOne).Round(coefficientScale)
	out.MedianDrift = decimal.NullDecimal{Decimal: suggested.Sub(coefficientOne), Valid: true}

	if suggested.LessThan(coefficientMin) || suggested.GreaterThan(coefficientMax) {
		// Число за границами поля не отдаётся числом и НЕ ПРИЖИМАЕТСЯ к границе. Зажать медиану −12%
		// в 1.0 значило бы сказать владельцу «поставьте единицу» там, где измерение говорит «ваш план
		// систематически завышен» — подменить измерение ближайшим сохраняемым значением. Измерение
		// остаётся видимым, предложения нет, и это ровно тот случай, когда смотреть надо в замеры.
		out.Status = CoefficientSuggestionOutOfRange
		out.Detail = fmt.Sprintf("медианный дрейф по %d настилам даёт коэффициент %s, а поле принимает от %s до %s — проверьте замеры: скорее всего, среди них есть ошибка ввода",
			out.LayCount, suggested.String(), coefficientMin.String(), coefficientMax.String())
		return out
	}

	out.Status = CoefficientSuggestionReady
	out.Suggested = decimal.NullDecimal{Decimal: suggested, Valid: true}
	out.Detail = fmt.Sprintf("предложение %s — медиана дрейфа план-факт по %d настилам; применяется рукой, не автоматом",
		suggested.String(), out.LayCount)
	return out
}

// medianDecimal — медиана непустой выборки. Чётная длина ⇒ полусумма двух средних.
//
// Сортируется КОПИЯ: порядок Drifts — это порядок входа, по которому человек ищет свой настил, и
// перестановка его ради арифметики сломала бы экран, не сломав ни одного числа.
func medianDecimal(vs []decimal.Decimal) decimal.Decimal {
	sorted := append([]decimal.Decimal(nil), vs...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].LessThan(sorted[j]) })
	n := len(sorted)
	if n%2 == 1 {
		return sorted[n/2]
	}
	return sorted[n/2-1].Add(sorted[n/2]).Div(coefficientTwo)
}

func normaliseUom(s string) string { return strings.ToLower(strings.TrimSpace(s)) }
