// TestThreedReservationCoversWhatTheRouteActuallyCHARGES — ШОВ МЕЖДУ ДВЕРЬЮ И СПИСАНИЕМ, и он
// единственное место, где две половины одной цены встречаются.
//
// ЧТО БЫЛО. Таблица двери держала литерал $0.60 — цену ушедшего hitem3d, — а пакет fal с переездом
// на meshy v7 стал считать сборку по $1.20. Пять поворотных столов в полёте показывали $3.00
// обязательств против $6.00 настоящего списания.
//
// ⚠ ЧЕМ ЭТО ВРЕДНО НА САМОМ ДЕЛЕ — ПОПРАВЛЕНО ПОСЛЕ РЕВЬЮ. Здесь стояло «резерв сверяется с дневным
// потолком ВНУТРИ транзакции», и это УЖЕ НЕВЕРНО: потолок снят как понятие миграцией 0358, никакой
// прогон им не отказывается. Число живёт в `design_run.price_estimate` и `design_budget_day.reserved`
// — то есть в учёте и на панели. Значит расхождение — это неверная бухгалтерия и неверное число
// рядом с настоящей ценой, а НЕ обход ворот. Меньший вред, но настоящий, и проба обязана называть
// его тем, что он есть.
//
// ⚠ СРАВНИВАЕТСЯ НЕ КОНСТАНТА С КОНСТАНТОЙ, А РЕЗЕРВ С ТЕМ, ЧТО РЕАЛЬНО НАПИШЕТ В СТРОКУ ПОПЫТКИ
// ПУТЬ СПИСАНИЯ. Проба, сверяющая два литерала, зеленела бы и в том мире, где считающий код давно
// ушёл от обоих.
//
// МУТАЦИЯ, КОТОРУЮ ЭТО КРАСИТ: вернуть в designPriceEstimate литерал «0.60» — или любое другое
// число ниже цены маршрута; так же краснеет подъём цены в пакете fal без подъёма резерва. ИГЛА
// УНИКАЛЬНА: ни один другой род не читает fal, и сообщение о падении называет оба числа.
func TestThreedReservationCoversWhatTheRouteActuallyCHARGES(t *testing.T) {
	reserve, ok := designPriceEstimate[entity.DesignRunKindThreed]
	require.True(t, ok, "у поворотного стола обязана быть оценка: без неё в учёте нет обязательства")

	// ЦЕНА СБОРКИ ТЕМ ЖЕ ВЫРАЖЕНИЕМ, КОТОРЫМ ЕЁ ПИШЕТ ПОПЫТКА. Тариф не задан — это и есть
	// сегодняшнее развёртывание, и именно тогда пакет отвечает своей оценкой ЗА ЗАПРОС.
	noTariff := fal.New(fal.Config{APIKey: "k"})
	charge := noTariff.CostUSD(1)
	require.True(t, charge.IsPositive(), "положительный контроль: путь списания вообще называет число")
	require.Truef(t, reserve.GreaterThanOrEqual(charge),
		"резерв поворотного стола %s ниже списания маршрута fal %s: в учёте и на панели окажется не та цифра",
		reserve, charge)

	// ⚠ И ПОКРЫТИЕ НЕ ЗАВИСИТ ОТ ЧИСЛА ЕДИНИЦ — ВОТ ЧТО ИМЕННО ОБЕЩАЕТ ЭТОТ РЕЗЕРВ. Без тарифа
	// цена ПЛОСКАЯ: провайдер честно называет число единиц, но чем он их меряет, знает только его
	// прайс. Это и есть починка прогона 17 (сто единиц × доллар = $100 при оценке $0.60), и здесь
	// она сторожится со стороны двери.
	//
	// МУТАЦИЯ, КОТОРУЮ ЭТО КРАСИТ: вернуть умножение на единицы в безтарифную ветку CostUSDFor.
	// ИГЛА УНИКАЛЬНА: предыдущее require зелено при любой такой мутации, потому что берёт одну
	// единицу.
	for _, units := range []float64{1, 3, 100} {
		require.Truef(t, reserve.GreaterThanOrEqual(noTariff.CostUSD(units)),
			"резерв %s не покрыл списание за %v единиц (%s): без тарифа цена обязана быть плоской",
			reserve, units, noTariff.CostUSD(units))
	}

	// И ОПУБЛИКОВАННАЯ ОЦЕНКА МАРШРУТА — ТО ЖЕ САМОЕ ЧИСЛО, что и его списание без тарифа. Без
	// этой строки дверь могла бы читать одно поле пакета, а попытка писать другое.
	require.True(t, charge.Equal(fal.EstimatedRequestUSD()),
		"оценка маршрута и его же списание без тарифа обязаны быть одним выражением")

	// И РЕЗЕРВ ПОКРЫВАЕТ ВТОРОЙ МАРШРУТ ТОЖЕ, потому что дверь не знает, какой из двух включён:
	// DESIGN_THREED_PROVIDER читает воркер, а второй читатель настройки — это второе число.
	require.Truef(t, reserve.GreaterThanOrEqual(designMeshyTaskCeilingUSD),
		"резерв %s ниже потолка прямого Meshy %s", reserve, designMeshyTaskCeilingUSD)
}

// TestAConfiguredTariffIsNOT_BOUNDED_BY_THE_ESTIMATE_AND_THE_COMMENT_SAYS_SO — ЗАМЕР ГРАНИЦЫ
// ОБЕЩАНИЯ, а не сторож инварианта.
//
// ⚠ ЗАЧЕМ ПРОБА НА ТО, ЧТО НЕ ГАРАНТИРУЕТСЯ. Ревью нашло, что max() покрывает только БЕЗТАРИФНЫЕ
// оценки: с FAL_UNIT_USD=0.50 и тремя единицами списание $1.50 против резерва $1.20. Чинить это
// «поднятием числа» нельзя — число единиц до сборки не знает и сам провайдер (прогон 17 вернул
// сто), поэтому СТАТИЧЕСКОЙ верхней границы там не существует. Единственный честный ход —
// назвать границу вслух и не давать ей тихо зарасти обратно в «резерв покрывает всё».
//
// ЧТО СЛУЧИТСЯ, ЕСЛИ КТО-ТО СДЕЛАЕТ РЕЗЕРВ ТАРИФО-ЗАВИСИМЫМ: эта проба покраснеет и приведёт его
// к комментарию designThreedCeilingUSD, где сказано, почему дверь не читает FAL_UNIT_USD. Это её
// работа — она сторожит ДОГОВОРЁННОСТЬ, а не арифметику.
func TestAConfiguredTariffIsNOT_BOUNDED_BY_THE_ESTIMATE_AND_THE_COMMENT_SAYS_SO(t *testing.T) {
	reserve := designPriceEstimate[entity.DesignRunKindThreed]
	withTariff := fal.New(fal.Config{APIKey: "k", UnitUSD: 0.50})

	require.True(t, withTariff.CostUSD(3).GreaterThan(reserve),
		"замер ревью: 3 единицы по $0.50 — это %s против резерва %s", withTariff.CostUSD(3), reserve)
	require.True(t, withTariff.CostUSD(2).LessThanOrEqual(reserve),
		"положительный контроль: обычная сборка в резерв укладывается, то есть оценка не абсурдна")
}
