// ОСЬ «РАБОТА» В ЧЕРНОВИКЕ ИИ (0329–0331).
//
// ЧТО БЫЛО СЛОМАНО. Генератор шагов не знал ни оси работы, ни каталога: промпт о работах не говорил
// ни слова, а маппер не писал поле `Work` НИКОГДА. Владелец диктует «стачать боковые, подогнуть низ
// московским» — и каждый возвращённый шаг ложился строкой с work = NULL. Вся фаза затеяна ровно
// потому, что сто прод-строк из ста двадцати шести сидят в неразличимой свалке; ИИ-путь эту свалку
// ВОСПРОИЗВОДИЛ на каждом использовании — причём ровно там, где каталог с его 254 цеховыми словами
// сильнее всего, потому что вход и есть речь технолога.
//
// СВОЙ ФАЙЛ, А НЕ ХВОСТ techcard_ai.go, НАМЕРЕННО — тем же доводом, которым ось «работа» отделена в
// разборе payload'а (internal/dto/techcard_operation_work.go): соседний файл правят параллельные
// фазы, и дописка в его середину — ровно тот шов, на котором ловятся дефекты параллельных агентов.
// Там остаётся одна строка вызова, здесь — вся мысль.
//
// ⚠️ РАБОТА РЕШАЕТСЯ ДО МАППИНГА, А НЕ ПОСЛЕ, И ЭТО НЕ СТИЛЬ. Глагол шага выбирает, КАКОЙ БЛОК
// НАСТРОЕК заполнит aiOperationToPb (машинный или ВТО). Проставь мы работу постфактум — шаг, у
// которого модель назвала работу и промолчала о глаголе, получил бы глагол от работы уже ПОСЛЕ
// того, как switch прошёл мимо его блока, и названные моделью обороты, игла и натяжение исчезли бы
// молча. Поэтому aiResolveWork правит КОПИЮ ответа модели (её же словарём, каноническим написанием
// токена), а разрешает токены в перечисления по-прежнему ОДИН маппер: второго ответа на вопрос «что
// значит слово overlock» здесь не заводится.
//
// ЧЕТЫРЕ ИСХОДА, И НИ ОДИН ИЗ НИХ НЕ УБИВАЕТ ШАГ:
//
//  1. Токен из каталога, когерентный шагу → `Work` записан, глагол и машинка подтянуты к работе.
//  2. Токен, которого в каталоге нет → `Work` пуст, ШАГ ЦЕЛ. Выдуманный токен хуже пустого поля:
//     сохранить его нельзя (внешний ключ 0330 и правило `unknown_work` в разборе), а технолог,
//     прочитавший его в черновике, пошёл бы искать работу, которой не существует.
//  3. Токен СНЯТОЙ работы → `Work` пуст, шаг цел. Снятый пункт не предлагается в пикере, и щит
//     operationWorkRetiredGate отвергает НОВУЮ разметку им; черновик — это всегда новая разметка,
//     так что сохранить такой шаг было бы нельзя.
//  4. Токен есть, но шаг с ним спорит (чужой глагол; при machine_mode = ask — машинка вне списка
//     работы) → `Work` пуст, ОСТАЛЬНЫЕ ПОЛЯ ШАГА НЕТРОНУТЫ.
//
// ПОЧЕМУ В СПОРЕ СНИМАЕТСЯ ИМЕННО РАБОТА. Оба ответа исправить нельзя, а выбрать надо: правила
// когерентности 0330 иначе отвергнут сохранение целиком. Снять работу — МОЛЧАНИЕ (пустое поле, то
// самое состояние, в котором сегодня живёт каждая строка обеих баз, и технолог заполняет его одним
// кликом из пикера). Переписать глагол или машинку под работу — ВЫДУМКА: это стёрло бы ответ,
// который модель дала явно, а вместе с глаголом — и весь его блок настроек. Молчание дешевле.
//
// ⚠️ ПРИ machine_mode = fixed МАШИНКА, НАЗВАННАЯ МОДЕЛЬЮ, НЕ ПЕРЕПИСЫВАЕТСЯ И НЕ СПОРИТ. Правило 4
// задаёт вопрос «на чём» ТОЛЬКО в режиме ask (при fixed машинка следует из работы, при none ось не
// машинная вовсе), то есть сохранение такой шаг ПРИНИМАЕТ. Маппер обязан зеркалить сохранение: он
// не имеет права отказать в том, что сохранение примет, — иначе черновик молча беднее, чем правка
// руками. Пустая машинка при этом ЗАПОЛНЯЕТСЯ работой (см. ниже) — это не спор, а ответ на вопрос,
// который работа уже содержит.

// aiWorkContexts projects the stored catalog into the prompt's vocabulary, dropping the retired
// works.
//
// СНЯТЫЕ ПУНКТЫ НЕ ПОКАЗЫВАЮТСЯ, И ЭТО ТА ЖЕ МЫСЛЬ, ЧТО У ПИКЕРА: снятие (retire) означает «больше
// не предлагать», а промпт — это и есть предложение. Показать снятую работу значило бы уговаривать
// модель назвать ровно тот токен, который щит потом отвергнет.
//
// ⚠️ ФИЛЬТР ЗДЕСЬ НЕ ЗАМЕНЯЕТ ПРОВЕРКИ НА ПРИЁМЕ. Модель отвечает не только тем, что ей показали:
// снятый токен может приехать из её собственной памяти о цехе. Поэтому «не предлагать» стоит в
// этой функции, а «не записывать» — в aiResolveWork, и одно другим не подменяется.
func aiWorkContexts(works []entity.OperationWork) []openrouter.WorkContext {
	out := make([]openrouter.WorkContext, 0, len(works))
	for i := range works {
		w := &works[i]
		if w.Retired() {
			continue
		}
		out = append(out, openrouter.WorkContext{
			Token:    w.Token,
			Label:    w.Label,
			Verb:     w.Verb,
			Machines: append([]string(nil), w.Machines...),
			Syn:      append([]string(nil), w.Syn...),
		})
	}
	if len(out) == 0 {
		// Ноль работ — не пустой список, а «каталога нет»: промпт тогда о работах не говорит вовсе.
		return nil
	}
	return out
}

// aiDraftOperation maps one drafted operation onto the stored step shape WITH its work axis.
//
// Ровно две строки поверх маппера: работа решается на копии ответа модели (она может дописать
// глагол и машинку, которые работа уже содержит), и только потом ответ раскладывается по полям.
//
// ПОРЯДОК С ПАРКОМ ОБОРУДОВАНИЯ ТОЖЕ НЕСУЩИЙ, и в вызывающем он именно такой: сначала работа,
// потом park.attach. Машинка, дописанная работой («московский» = прямострочка), — такой же ответ
// на вопрос «на чём», как названная моделью, и профиль единственной прямострочки карточки обязан
// прицепиться к ней ровно так же. Привяжи мы профиль раньше — шаг, у которого машинка пришла от
// работы, остался бы без профиля и без единого слова об этом.
func aiDraftOperation(o openrouter.Operation, catalog *entity.OperationWorkCatalog) *pb_common.TechCardOperation {
	work := aiResolveWork(&o, catalog)
	op := aiOperationToPb(o)
	op.Work = work
	return op
}

// aiResolveWork resolves the model's work token against the catalog and returns the token to store,
// or "" when the draft must carry no work at all. On success it completes the copy of the model's
// answer with what the work already implies — the verb it carries and, where the step named none,
// the machine it runs on.
//
// ⚠️ nil-КАТАЛОГ = «ЭТОТ СЕРВЕР КАТАЛОГА НЕ ЗНАЕТ», И ТОГДА РАБОТА НЕ ПИШЕТСЯ НИКОГДА. Lookup у
// nil отвечает «нет такой работы», и это ровно тот исход, который нужен: разбор payload'а при
// пустом снимке отказывает непустой работе поимённо (`catalog_unavailable`), так что черновик с
// работой был бы черновиком, который нельзя сохранить. Промпт в этом случае о работах молчит —
// значит и назвать их модели неоткуда, — но исход закрыт с обеих сторон.
func aiResolveWork(o *openrouter.Operation, catalog *entity.OperationWorkCatalog) string {
	token := normalizeToken(o.Work)
	if token == "" {
		return ""
	}
	work, ok := catalog.Lookup(token)
	if !ok {
		// Исход 2: выдуманный токен стоит ровно одно поле.
		return ""
	}
	if work.Retired() {
		// Исход 3: снятую работу не предлагают заново — ни пикер, ни черновик.
		return ""
	}

	// ⚠️ ПРАВИЛА СВЕРЯЮТСЯ В ТОКЕНАХ, А НЕ В ПЕРЕЧИСЛЕНИЯХ, И ЭТО ДОСЛОВНОЕ ЗЕРКАЛО РАЗБОРА
	// (internal/dto/techcard_operation_work.go): там правило 3 сравнивает `string(opType)` с
	// `work.Verb`, а правило 4 спрашивает `work.AllowsMachine(<токен машинки>)`. Каталог хранит
	// ТОКЕНЫ, и перевод их в члены enum ради сравнения завёл бы второй словарь там, где уже есть
	// один: работа, чей глагол этот бинарь ещё не знает (каталог новее кода), молча превратилась бы
	// в UNKNOWN и «не совпала» бы с любым шагом вместо честного сравнения строк.
	//
	// А вот СЛОВО МОДЕЛИ канонизируется перед сравнением, и той же функцией, что в маппере: модель
	// отвечает «overlock» там, где хранится (machine, overlock), и сверять работу с сырым словом
	// значило бы объявить спором совпадение.
	opType, machine := aiOperationType(o.OperationType, o.MachineType)
	stepVerb := ""
	if opType != pb_common.TechCardOperationType_TECH_CARD_OPERATION_TYPE_UNKNOWN {
		stepVerb = aiOperationTypeNames[opType]
	}
	stepMachine := aiMachineTypeNames[machine] // "" — «шаг машинки не назвал»

	// Правило когерентности 3. Пустой глагол — не спор, а молчание: работа его и заполняет.
	if stepVerb != "" && stepVerb != work.Verb {
		return ""
	}

	switch work.MachineMode {
	case entity.OperationWorkMachineModeFixed, entity.OperationWorkMachineModeAsk:
		// Машинка, которой шаг не назвал, берётся у работы. При fixed она из работы и СЛЕДУЕТ
		// («московский» уже содержит прямострочку, и вслух её не произносят), при ask — это дефолт
		// пункта, то есть ответ каталога на «а какая обычно». Оставить пусто нельзя: при ask
		// правило 4 отвергает шаг без машинки, а машинный шаг без машинки не сохраняется вовсе.
		if stepMachine == "" {
			stepMachine = work.DefaultMachine.String
		}
		// Правило когерентности 4 — ТОЛЬКО при ask, дословно как в разборе payload'а.
		if work.MachineMode == entity.OperationWorkMachineModeAsk && !work.AllowsMachine(stepMachine) {
			return ""
		}
		if stepMachine != "" {
			o.MachineType = stepMachine
		}
	}

	// Работа говорит СВОИМ словом, а разрешает его в член перечисления по-прежнему один маппер:
	// «machine» из каталога и «machine» из ответа модели проходят ровно один и тот же словарь.
	o.OperationType = work.Verb
	return token
}
