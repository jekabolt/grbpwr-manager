// ─────────────────────── ПРОЗАИЧЕСКАЯ БАЗА: ЧИСЛО ТО ЖЕ, ИСТОЧНИК ДРУГОЙ ───────────────────────

// УСПЕШНОЕ ПРОЗАИЧЕСКОЕ НАЖАТИЕ СТОИТ РОВНО СТОЛЬКО ЖЕ, СКОЛЬКО ВЧЕРА.
//
// База перестала быть литералом и стала выражением над теми же двумя тарифами, что у структурной
// (довод целиком — у designDraftIdeaProseBaseUSD). Такая правка обязана быть НУЛЕВОЙ по деньгам,
// иначе она молча передвинула бы цену каждого прозаического прогона в регистре.
//
// ⚠ ВТОРАЯ ПОЛОВИНА — ТО, РАДИ ЧЕГО ВСЁ И ДЕЛАЛОСЬ: база обязана ДВИГАТЬСЯ ЗА ТАРИФОМ. Литерал не
// двигался, и в тот день, когда слуг сменит класс и тарифы переедут (комментарий над ними просит
// об этом дословно), структурная база поехала бы одна, а прозаическая осталась бы молча на месте.
//
// ⚠ ЧЕГО ЭТА ПРОБА НЕ УМЕЕТ, СКАЗАНО ЗАМЕРОМ, А НЕ НАДЕЖДОЙ. Мутация «вернуть литерал 0.03» при
// СЕГОДНЯШНЕМ тарифе остаётся ЗЕЛЁНОЙ, и иначе быть не может: литерал численно равен выводу, а
// проба по значению их не различает в принципе. Различает их ПАРА, и она замерена:
//
//	· сдвинуть тариф 15 → 30 при выведенной базе  → краснеет ПЕРВОЕ утверждение (цена уехала —
//	  ровно та новость, ради которой оно и стоит);
//	· сдвинуть тариф 15 → 30 ПРИ ЛИТЕРАЛЕ         → краснеет ВТОРОЕ («0.054» против «0.03»), то
//	  есть проба ловит ровно ту гниль, о которой всё это: тариф поехал, база осталась.
//
// ⚠ И ПОЭТОМУ ПЕРВОЕ УТВЕРЖДЕНИЕ — ПИН ЭТОЙ ПРАВКИ, А НЕ ВЕЧНАЯ ИСТИНА. Оно говорит «вывод базы не
// передвинул цену НИ НА ЦЕНТ»; в день, когда тариф законно переедет, оно покраснеет — и это
// правильно: цену каждого прозаического нажатия нельзя менять молча. Тогда его двигают ВМЕСТЕ с
// тарифом, а не «чинят», подставив новое число.
func TestProseBaseStillCostsWhatTheLiteralDid(t *testing.T) {
	require.Equal(t, "0.03", designDraftIdeaProseBaseUSD.String(),
		"вывод базы не имеет права передвинуть цену успешного нажатия")

	// ЧТО ЗНАЧИТ «ВЫВЕДЕНА»: число обязано быть суммой ровно тех двух слагаемых, из которых
	// собрана и соседняя база, — по тем же тарифам, а не рядом с ними.
	require.Equal(t,
		designTokensUSD(designProseInputTokens, designChatUSDPerMTokIn).
			Add(designTokensUSD(designProseAnswerTokens, designChatUSDPerMTokOut)).String(),
		designDraftIdeaProseBaseUSD.String())

	// И ОНА ОБЯЗАНА ОСТАТЬСЯ МЕНЬШЕ СТРУКТУРНОЙ: прозаическая ветка не покупает ни словаря цвета
	// во входных, ни целого потолка в выходных. Равенство здесь означало бы, что одна из двух
	// снова считается не из своего.
	require.True(t, designDraftIdeaProseBaseUSD.LessThan(designDraftIdeaConstructionBaseUSD))
	require.True(t, designDraftIdeaBaseUSD.Equal(designDraftIdeaConstructionBaseUSD),
		"в таблицу родов идёт БОЛЬШАЯ из двух: designEstimateFor отвечает до выбора формы")

	// ПРОЗАИЧЕСКАЯ БАЗА — НЕ ГРАНИЦА, И ЭТО СКАЗАНО ЧИСЛОМ, А НЕ ТОЛЬКО ПРОЗОЙ: ветка не кладёт
	// на провод НИ ОДНОГО потолка, поэтому выводить границу не из чего (см. довод у переменной).
	require.Zero(t, entity.DesignDraftAnswerCeiling(false),
		"как только у прозы появится потолок, база обязана считаться из НЕГО, как у соседа")
	require.Equal(t, designConstructionMaxTokens, entity.DesignDraftAnswerCeiling(true),
		"и зеркало: структурная база уже выведена ровно из этого числа")
}
