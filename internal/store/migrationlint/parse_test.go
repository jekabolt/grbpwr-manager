package migrationlint

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/rubenv/sql-migrate/sqlparse"
)

// КАЖДАЯ МИГРАЦИЯ ОБЯЗАНА РАЗБИРАТЬСЯ ТЕМ ЖЕ ПАРСЕРОМ, ЧТО И ПРИЛОЖЕНИЕ НА СТАРТЕ.
//
// Это не про синтаксис SQL — про синтаксис sql-migrate, и он ловится ТОЛЬКО так. Остальные
// проверки этого пакета читают файлы как текст и о разборе не знают ничего.
//
// ПОЧЕМУ ЭТО ВАЖНО СИЛЬНЕЕ, ЧЕМ КАЖЕТСЯ: на старте парсятся ВСЕ файлы, включая давно применённые.
// Ошибка разбора в миграции пятилетней давности роняет запуск так же надёжно, как ошибка в
// сегодняшней, — и правка КОММЕНТАРИЯ в применённом файле этого достаточна.
//
// Ровно так и случилось (2026-08-16): из 0306 убрали последний оператор Up, оставив под ним блок
// пояснений с голыми «--». Парсер пропускает комментарий, только когда строка начинается с «-- »
// (с пробелом); голая «--» попадает в буфер оператора. Пока за блоком шёл оператор, буфер
// сбрасывался — и 582 таких строки по всем миграциям жили годами. Без оператора буфер дожил до
// «-- +migrate Down», разбор упал, приложение не поднялось, DO откатился. Файл при этом был
// применён на бете месяц назад, а тесты и сборка были зелёными.
func TestEveryMigrationParses(t *testing.T) {
	dir := filepath.Join("..", "sql")
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("can't read migrations dir: %v", err)
	}
	seen := 0
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		seen++
		f, err := os.Open(filepath.Join(dir, e.Name()))
		if err != nil {
			t.Fatalf("%s: %v", e.Name(), err)
		}
		parsed, err := sqlparse.ParseMigration(f)
		f.Close()
		if err != nil {
			t.Errorf("%s НЕ РАЗБИРАЕТСЯ — приложение не поднимется: %v", e.Name(), err)
			continue
		}
		// Пустая миграция — почти всегда опечатка в директиве: файл есть, а операторов нет, и
		// sql-migrate молча запишет её как применённую.
		if len(parsed.UpStatements) == 0 {
			t.Errorf("%s: в Up нет ни одного оператора — проверьте «-- +migrate Up»", e.Name())
		}
	}
	if seen == 0 {
		t.Fatal("не найдено ни одной миграции — тест бесполезен, проверьте путь")
	}
}
