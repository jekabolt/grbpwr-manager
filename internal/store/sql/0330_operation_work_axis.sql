-- +migrate Up

-- ОСЬ «РАБОТА» СТАНОВИТСЯ ХРАНИМЫМ ФАКТОМ СТРОКИ ШАГА. Одна колонка и один внешний ключ.
--
-- ЧТО БЫЛО. Вид операции существовал ровно одним способом — экран каждый раз ВЫВОДИЛ его из пары
-- (глагол, машинка). Из-за этого сто строк прода из ста двадцати шести неразличимы между собой
-- (`machine` + `lockstitch`, перепись 2026-08-21), сервер не может ни проверить «такая работа
-- существует», ни повесить на работу правило поля, ни отдать поиск по русскому слову технолога.
-- 0329 завёл каталог работ; этот файл даёт строке шага место, где сказать, КАКАЯ это работа.
--
-- ⚠️ КОЛОНКА НЕСЁТ НАБОР СИМВОЛОВ И СОРТИРОВКУ ЯВНО, И ЭТО НЕ ПЕДАНТИЗМ. `operation_work.token`
-- объявлен `VARCHAR(32) COLLATE utf8mb4_bin`; MySQL требует от сторон внешнего ключа СОВПАДЕНИЯ
-- набора символов и сортировки, а `tech_card_operation` на проде живёт в utf8mb3 (память
-- store-tests-utf8mb4-vs-prod-utf8mb3: тесты идут в utf8mb4, прод в utf8mb3, и расхождение
-- маскируется ровно до прод-деплоя). Колонка, унаследовавшая сортировку таблицы, дала бы на проде
-- ошибку 3780 на шаге 2 — то есть остановленный старт прода. Поэтому CHARACTER SET и COLLATE
-- выписаны здесь дословно, а не оставлены дефолту таблицы.
--
-- СЛОВАРЬ ЗАКРЫВАЕТ ВНЕШНИЙ КЛЮЧ, А НЕ CHECK REGEXP, И ЭТО РЕШЕНИЕ ФАЗЫ. `ADD CONSTRAINT CHECK` в
-- MySQL 8 копирует таблицу ЦЕЛИКОМ (алгоритм COPY), а потолок на ВЕСЬ прогон миграций зашит пятью
-- минутами в internal/store/store.go. FK — INPLACE, и валидировать ему нечего: колонка рождается
-- NULL на каждой из 126 строк. Вдобавок список работ РАСТЁТ отдельными INSERT-миграциями (0331 и
-- далее), а REGEXP пришлось бы пересоздавать копией таблицы на каждую новую работу.
--
-- ИМЯ КОЛОНКИ НЕ ЭКРАНИРУЕТСЯ НИГДЕ, И ЭТО ПРОВЕРЕНО, А НЕ ПОВЕЗЛО. `WORK` в MySQL 8 — КЛЮЧЕВОЕ, НО
-- НЕ ЗАРЕЗЕРВИРОВАННОЕ слово (оно живёт в `COMMIT WORK` / `ROLLBACK WORK`), поэтому голое `work`
-- законно и в DDL, и в списке колонок INSERT'а. Это важно именно здесь: storeutil.BulkInsert
-- собирает `INSERT INTO ... (col, col, …)` СКЛЕЙКОЙ ИМЁН БЕЗ ОБРАТНЫХ КАВЫЧЕК, то есть
-- зарезервированное имя уронило бы вставку каждой операции, а не только эту миграцию. В схеме уже
-- живут колонки того же класса — `value`, `status`, `state`, `source`, `comment`, `size`.
--
-- NULL = «ВИД НЕ НАЗНАЧЕН», И ЭТО ЗАКОННОЕ СОСТОЯНИЕ НАДОЛГО. Сто lockstitch-строк прода НЕ
-- переписываются автоматически ни в какой вид — отмывание свалки запрещено ограничением владельца
-- («сломаться можно, исчезнуть нельзя»); их размечает человек. DEFAULT здесь стёр бы разницу между
-- «технолог назвал работу» и «за него назвали».
--
-- НУЛЕВАЯ ВОЛНА ПРОТУХШИХ ПОДПИСЕЙ — ДОКАЗУЕМАЯ, А НЕ ОБЕЩАННАЯ. Колонка рождается NULL на каждой
-- существующей строке; хвост дайджеста "work" условный (парная форма, как одиннадцать хвостов
-- волны), поэтому при NULL он НЕ РОЖДАЕТСЯ и байты кортежа существующего шага не двигаются.
-- Замороженные golden-хексы в internal/dto это и проверяют — они обязаны остаться байт-в-байт.
-- Окно открыто: tech_card_signoff = 0 на обеих базах (замер 2026-08-21). Закроется первой подписью.
--
-- ОТКАТ БИНАРЯ НА ДО-0330 БЕЗОПАСЕН: колонка остаётся, данные целы, старый код её просто не
-- читает. Опаснее обратное — откат прод-бинаря при живом НОВОМ клиенте, — и он закрыт волной
-- «перестать терять данные»: строгий маршалер admin-мукса отвечает 400 с именем поля `work`,
-- а не глотает его молча.
--
-- ИДЕМПОТЕНТНОСТЬ: MySQL 8 автокоммитит DDL, поэтому падение в середине оставляет схему
-- полуприменённой БЕЗ строки в gorp_migrations, и следующий старт перезапускает файл С ВЕРХА.
-- Каждый шаг — под собственным гейтом information_schema, PREPARE / EXECUTE / DEALLOCATE ПО ОДНОМУ
-- оператору на строку (multiStatements=true контейнерных тестов иначе маскирует поломку, которая
-- на проде валит старт). Комментарии `--` пишутся строго с пробелом после дефисов: без пробела
-- парсер sql-migrate уводит их в тело оператора.
--
-- ДВА ШАГА, А НЕ ОДИН ALTER, И ЭТО ТОЖЕ ПРО ИДЕМПОТЕНТНОСТЬ. Слитый ALTER пришлось бы гейтить
-- ОДНИМ условием на два разных изменения, и повтор после падения между ними (колонка есть, ключа
-- нет) прошёл бы мимо ключа навсегда. Раздельные гейты отвечают каждый за своё.

-- 1. КОЛОНКА. ADD COLUMN nullable без DEFAULT — операция INSTANT: таблица не копируется, история не
--    читается. Ширина 32 = ширина `operation_work.token` (обе стороны ключа обязаны совпасть и по
--    ней). Гейт — сама колонка.
SET @work_col := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tech_card_operation'
      AND COLUMN_NAME = 'work');
SET @ddl := IF(@work_col = 0,
    'ALTER TABLE tech_card_operation
        ADD COLUMN work VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL COMMENT ''КАКАЯ это работа: токен operation_work.token (0329). NULL = вид не назначен — законное состояние, размечает человек. Набор символов и сортировка выписаны явно: их обязан повторить внешний ключ''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- 2. ВНЕШНИЙ КЛЮЧ. Валидация истории пуста — все строки NULL, — поэтому ALGORITHM INPLACE и никакой
--    копии. БЕЗ КАСКАДА НАМЕРЕННО (RESTRICT по умолчанию, как у трёх детей каталога в 0329):
--    попытка удалить работу, на которую ссылается шаг, обязана падать громко. Работы не удаляют
--    вовсе — их снимают через retired_at, — и каскад был бы механизмом под запрещённое действие.
--    ON UPDATE тоже нет: token неизменяем, менять его задним числом значит раздваивать отпечаток.
--    Гейт — само имя ограничения. Индекс под ключ MySQL заводит сама, отдельного не нужно.
SET @work_fk := (SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tech_card_operation'
      AND CONSTRAINT_NAME = 'fk_op_work' AND CONSTRAINT_TYPE = 'FOREIGN KEY');
SET @ddl := IF(@work_fk = 0,
    'ALTER TABLE tech_card_operation
        ADD CONSTRAINT fk_op_work FOREIGN KEY (work) REFERENCES operation_work (token)',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down
--
-- Down снимает ровно то, что добавил Up, обратным порядком: ключ, потом колонку. Обратим полностью
-- — здесь нет ни сужения словаря, ни переписанных данных, поэтому оговорок вида 0325 не требуется.
-- Разметка work при откате ТЕРЯЕТСЯ вместе с колонкой; Down — инструмент разработки (up → down → up
-- на одноразовой базе), а не машина времени для прода.

-- D1. Внешний ключ. Гейт — он сам.
SET @work_fk_back := (SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tech_card_operation'
      AND CONSTRAINT_NAME = 'fk_op_work' AND CONSTRAINT_TYPE = 'FOREIGN KEY');
SET @ddl := IF(@work_fk_back = 1,
    'ALTER TABLE tech_card_operation DROP FOREIGN KEY fk_op_work',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- D2. Колонка. Гейт — она сама. Индекс, заведённый под ключ, уходит вместе с колонкой.
SET @work_col_back := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tech_card_operation'
      AND COLUMN_NAME = 'work');
SET @ddl := IF(@work_col_back = 1,
    'ALTER TABLE tech_card_operation DROP COLUMN work',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
