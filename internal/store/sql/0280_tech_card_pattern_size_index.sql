-- ИНДЕКС РАЗМЕРОВ ВЫКРОЕК (Ф6.3): единственный источник серверного ответа на вопрос
-- «есть ли выкройка на этот размер».
--
-- ЗАЧЕМ ВООБЩЕ. Сегодня у сервера нет НИКАКОГО честного ответа, и это не «неточно», а «не про то».
-- Клиент кладёт КАЖДЫЙ лист выкройки под НАИМЕНЬШИЙ размер ряда — сам называет это артефактом
-- хранения (patterns-field.tsx: «Берём наименьший размер ряда — и это АРТЕФАКТ ХРАНЕНИЯ, а не
-- смысл: файл несёт весь ряд»). Существующая проверка готовности карточки считает именно этот
-- столбец (COUNT(DISTINCT sp.size_id) в readiness.go) и сравнивает с числом размеров — то есть на
-- каждой градуированной карточке она ВРЁТ: один градуированный DXF на пять размеров читается как
-- «1 из 5».
--
-- Разбор имён блоков DXF живёт в браузере и на сервер НЕ ПЕРЕЕЗЖАЕТ: сервер файлы не парсит и
-- парсить не будет. Значит либо индекс, либо серверный гейт не узнает про выкройки НИКОГДА — не
-- «пока», а в принципе. Отсюда эта таблица.
--
-- ЕДИНИЦА ХРАНЕНИЯ — СКОУП ТКАНИ, А НЕ ЛИСТ, и это следствие самого разбора, а не вкус.
-- deriveBlockSizes некомпозиционна: она объявляет токен размером только если у ОДНОЙ основы имени
-- таких хвостов не меньше двух И частота токена не ниже max(2, max/2) по всем основам. Токены,
-- посчитанные по файлу A и по файлу B по отдельности, НЕ дают набора по A+B, а односоразмерный файл
-- не даёт ни одного токена вовсе. Хранение по листу дало бы ДРУГОЙ ответ, чем кнопка «⌕ размеры в
-- файлах», и разошлось бы молча.
--
-- ПУСТОЙ НАБОР ТОКЕНОВ — ЗАКОННОЕ ЗНАЧЕНИЕ и значит «файлы не несут размерного кодирования»
-- (один размер на файл). Читается как ВЕРДИКТА НЕТ (UNKNOWN), НИКОГДА как «размеров нет»: последнее
-- было бы ложным блокером на всех размерах сразу, и клиент от него уже защищается (missingIn
-- возвращает пустой список при found.size === 0).
--
-- БЭКФИЛЛА НЕТ И БЫТЬ НЕ МОЖЕТ: разбор живёт в браузере. Пустая таблица = «никто ещё не проверял»,
-- и это ровно тот UNKNOWN, который гейт обязан показать вместо молчания.
--
-- БЕЗ КЛАУЗЫ CHARSET (прецедент 0252/0257/0272): прод и бета крутятся на серверном дефолте utf8mb3,
-- локальные контейнерные тесты подключаются utf8mb4, и явная клауза развела бы их незаметно.

CREATE TABLE IF NOT EXISTS tech_card_pattern_size_index (
    tech_card_id INT NOT NULL,
    -- Скоуп ткани: COALESCE(fabric_purpose, bom_line_key) — ТОТ ЖЕ ключ, что считает
    -- entity.FabricScopeKey и что MySQL генерирует в tech_card_piece_dxf_block.scope_key (0267).
    -- Одна функция на обеих сторонах, поэтому индекс и привязки согласованы по построению, а не по
    -- договорённости.
    scope_key VARCHAR(64) NOT NULL,
    -- Отпечаток НАБОРА ЛИСТОВ, посчитанный СЕРВЕРОМ по своим строкам tech_card_size_pattern
    -- (line_key, url, version), отсортированным. Клиент его не присылает и прислать не может — это
    -- и есть то, что делает индекс неподделываемым в ОПАСНУЮ сторону (заявить покрытие по файлам,
    -- которых нет). Перезаливка любого листа меняет url/version, отпечаток расходится, индекс
    -- читается как УСТАРЕВШИЙ и гейт отвечает UNKNOWN — сам, без чьего-либо участия.
    --
    -- Тот же приём, которым 0268 закрыла подделку освобождения по версии блоба: значение, дающее
    -- пропуск, пишет сервер и только своей константой.
    sheet_fingerprint CHAR(64) NOT NULL,
    -- JSON-МАССИВ нормализованных (только буквы/цифры, lowercase) размерных токенов.
    --
    -- JSON, а не дочерняя таблица, и это НЕ противоречит решению Ф2 Р1: там проекция обязана была
    -- ДЖОЙНИТЬСЯ при подсчёте покрытия по многим строкам; здесь гейт читает ОДНУ карточку и
    -- разбирает несколько коротких строк один раз. Читатель обязан отвергать всё, что не является
    -- JSON-массивом строк, и трактовать это как ОТСУТСТВИЕ индекса, а не как пустой набор.
    size_tokens JSON NOT NULL,
    parsed_by VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'admin username, который нажал разбор',
    parsed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (tech_card_id, scope_key),
    CONSTRAINT fk_tcpsi_card FOREIGN KEY (tech_card_id) REFERENCES tech_card(id) ON DELETE CASCADE
) ENGINE=InnoDB COMMENT 'Ф6.3: размерные токены имён блоков DXF по скоупу ткани — единственный источник серверного ответа «есть ли выкройка на этот размер»';

