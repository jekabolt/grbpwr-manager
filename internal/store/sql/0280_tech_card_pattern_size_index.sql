-- Дропается свободно, и это надо объяснить, потому что все соседние Down в этой серии гвардятся.
-- Здесь гвардить нечего: КАЖДАЯ строка этой таблицы — ПРОИЗВОДНЫЙ факт, целиком пересчитываемый
-- одним нажатием «⌕ размеры в файлах» на вкладке выкроек. Первоисточник — сами файлы DXF — эта
-- миграция не трогает и тронуть не может. Потеря индекса возвращает гейт в честный UNKNOWN
-- («размеры в файлах не проверялись»), то есть ровно в то состояние, из которого он начинал;
-- она не теряет ни одного факта, который кто-то ввёл руками.
DROP TABLE IF EXISTS tech_card_pattern_size_index;
