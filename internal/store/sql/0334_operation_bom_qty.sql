-- +migrate Up

-- СКОЛЬКО ЕДИНИЦ АРТИКУЛА ТРАТИТ ШАГ — четвёртое из четырёх чисел «сколько на изделие», и
-- единственное, у которого до этой миграции не было места вовсе. Карта владения (01-DECISIONS):
-- закупаемый материал — норма слота (0333), работа шага — placement_count, вспомогательное изделие —
-- style_assembly.qty (0174), а «этот шаг ставит 6 пуговиц» не хранилось нигде.
--
-- ПОЧЕМУ НА СВЯЗИ, А НЕ КОЛОНКОЙ НА ОПЕРАЦИИ. Шаг честно потребляет несколько артикулов сразу
-- («втачать молнию» берёт и молнию, и нитку), поэтому колонка на tech_card_operation ответила бы
-- только про один из них и молча приписала бы число не тому материалу. Считаемая сущность — ПАРА
-- (шаг × артикул), а строка tech_card_operation_bom и есть эта пара. Тот же довод, по которому
-- легаси-поля bom_item_id/bom_item_index уехали с 0289: одиночное поле было вторым ответом на
-- вопрос, на который уже отвечала связь.
--
-- NULL = «НЕ СКАЗАНО», И ИЗ placement_count ОНО НЕ ПОДСТАВЛЯЕТСЯ НИКОГДА. Это разные утверждения, и
-- вывод одного из другого врёт на живых примерах: «обметать 6 петель» — повторов 6, пуговиц
-- потрачено НОЛЬ (петля тратит нитку); «поставить 4 хольнитена» — повторов 4, а артикула два
-- (шляпка и ножка), у каждого своё число; «втачать молнию» — повторов нет вовсе, молния одна.
-- Умолчание из повторов заставило бы шаг обмётки петель заявлять, что съел шесть пуговиц. Ноль —
-- РЕАЛЬНОЕ утверждение («этот шаг артикула не тратит»), поэтому DEFAULT'а у колонки нет.
--
-- ГРАНИЦА «СЧЁТНОЕ / МЕРНОЕ» ЖИВЁТ В GO (entity.IsCountableSection), А НЕ В CHECK'Е — дословно тот
-- же довод, что в шапке 0333 и 0278: двухколоночный CHECK (секция слота ↔ количество на связи) здесь
-- вдобавок невыразим — секция лежит в ДРУГОЙ таблице, — а выстрелил бы он сырым MySQL 3819 на
-- UPDATE'е, который правит совсем другое поле. Схема закрывает ЗНАК (отрицательного количества не
-- бывает), пару «секция ↔ счётность» проверяет конвертер именованным FieldViolation с указанием
-- секции и способа выйти.
--
-- ИДЕМПОТЕНТНОСТЬ (CLAUDE.md): MySQL 8 автокоммитит DDL, поэтому падение в середине файла оставляет
-- схему полуприменённой без строки в gorp_migrations, и следующая загрузка перезапускает файл с
-- начала. Колонка и CHECK едут ОДНИМ ALTER под проверкой наличия колонки, поэтому повтор — no-op, а
-- не «duplicate column».
--
-- ГВАРД ПО КОЛОНКЕ ЗАКРЫВАЕТ И CHECK — ИМЕННО ПОТОМУ, ЧТО ALTER ОДИН. Состояние «колонка есть, чека
-- нет» этой миграцией недостижимо: одиночный ALTER в MySQL 8 атомарен, и падение второго пункта
-- откатывает первый (проверено на одноразовой базе 2026-08-25: ALTER с годным ADD COLUMN и
-- заведомо падающим ADD CONSTRAINT оставил таблицу без новой колонки). НЕ РАЗБИВАТЬ ЭТОТ ALTER НА
-- ДВА «ради читаемости»: два оператора теряют атомарность, и вот тогда гвард по колонке пропустит
-- файл, а CHECK не появится никогда — молча и навсегда. CHECK ИМЕНОВАН: авто-имя <table>_chk_<n> позиционно и дрейфует по истории
-- схемы, дропать его нельзя. PREPARE/EXECUTE/DEALLOCATE — ПО ОДНОМУ ОПЕРАТОРУ НА СТРОКУ: прод ходит
-- без multiStatements, и склеенная строка молча не выполнится. Бэкфилла нет: выводить число неоткуда.
--
-- ЗАМЕР, А НЕ ПАМЯТЬ: ADD CHECK копирует таблицу ЦЕЛИКОМ (правило «ADD CHECK = COPY»), и на этот
-- прогон захардкожен пятиминутный лимит. В tech_card_operation_bom 14 строк на бете и 3 на проде
-- (замерено 2026-08-25) — копия мгновенна, лимита эта миграция не касается даже на порядок.
--
-- НОМЕР ПРИМЕНИТСЯ ВНЕ ЧИСЛОВОГО ПОРЯДКА, И ЭТО НЕ ОШИБКА. 0334 был зарезервирован под эту задачу
-- РАНЬШЕ, чем уехали соседние 0333 и 0335, поэтому на бете и на проде он ляжет ПОСЛЕ них.
-- Безопасно по построению: файл трогает СВОЮ таблицу (tech_card_operation_bom), которой ни 0333
-- (tech_card_bom_item, две колонки норм), ни 0335 (словарь bom_item.kind) не касаются, и ни одного
-- объекта, заводимого ими, не читает. sql-migrate ведёт учёт по имени файла, а не по порядку, так
-- что переставлять номер задним числом нельзя и не нужно.

SET @col_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'tech_card_operation_bom'
      AND COLUMN_NAME = 'qty_per_garment'
);
SET @ddl := IF(@col_exists = 0,
    'ALTER TABLE tech_card_operation_bom ADD COLUMN qty_per_garment DECIMAL(10,3) NULL COMMENT ''сколько единиц ЭТОГО артикула шаг тратит на изделие; NULL = не сказано (никогда не выводится из placement_count: повторы шага и потраченные штуки — разные утверждения), ноль — реальное утверждение. Число законно только на связи со СЧЁТНЫМ слотом'' AFTER display_order, ADD CONSTRAINT chk_op_bom_qty CHECK (qty_per_garment IS NULL OR qty_per_garment >= 0)',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

