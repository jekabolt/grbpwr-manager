-- Симметричный откат под тем же гардом: сначала CHECK, затем колонка, ОДНИМ ALTER. Данные теряются, и
-- это честно — колонка единственное место, где количество на связи хранится, а восстановить его из
-- placement_count нельзя (ровно то, что запрещает шапка Up).
SET @col_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'tech_card_operation_bom'
      AND COLUMN_NAME = 'qty_per_garment'
);
SET @ddl := IF(@col_exists = 1,
    'ALTER TABLE tech_card_operation_bom DROP CONSTRAINT chk_op_bom_qty, DROP COLUMN qty_per_garment',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
