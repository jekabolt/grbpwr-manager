-- +migrate Up

-- СКОЛЬКО ШТУК НА ИЗДЕЛИИ — счётная норма СЛОТА спецификации, третья ось рядом с размером и
-- колорвеем. Ровно та же операция, что 0265 (purpose) и 0278 (kind) сделали с классификацией:
-- признак, который НЕ меняется по оси, переезжает на владельца, где он выражается один раз.
--
-- ПОЧЕМУ НА СЛОТЕ, А НЕ НА СТРОКЕ РЕЦЕПТА. Количество пуговиц не меняется ни по размеру, ни по
-- колорвею — а единственное место, где его можно записать до этой миграции, это
-- tech_card_colorway_usage.quantity (0079), то есть строка, зависящая от ОБОИХ. Инвариантность
-- выражалась копированием: на карточке с четырьмя колорвеями лежало четыре шестёрки, кнопки
-- «применить ко всем» в админке нет вовсе, а расхождение между копиями не проверялось нигде.
-- Копия — это то, что расходится. Прецедент оси уже стоит в схеме дважды: style_assembly.qty
-- (0174) — «количество на изделие, size_id NULL = все размеры», и пин артикула 0221 — слот
-- style-level, колорвей пинит только КАКОЙ артикул. По той же границе: «сколько» — факт стиля,
-- «какая пуговица» — факт колорвея.
--
-- ПОЧЕМУ ЗАПАС ОТДЕЛЬНОЙ КОЛОНКОЙ, А НЕ «НАБЕРИ 7 ВМЕСТО 6». Запасная пуговица в пакетике
-- покупается, но НЕ пришивается. Семёрка в одном поле чинит деньги и закупку и ломает три вещи:
-- сверку с маршрутом (шаги ставят 6 — необъяснимая единица), инструкцию цеху (сколько на планку,
-- сколько в пакетик) и САМО НАЛИЧИЕ запаса, от которого зависит существование пакетика. Две
-- колонки на одной строке — единственная форма, которая не может разойтись сама с собой: второй
-- строкой BOM «пуговица (запасная)» это был бы тот же артикул с ВТОРОЙ ценой и вторым пином
-- колорвея, обязанными совпадать с первыми навсегда.
--
-- ЕДИНИЦА СЧЁТА — ПАРА (КОЛОРВЕЙ × СЛОТ), А НЕ СТРОКА. Это несущее и записано здесь, потому что
-- схема разрешает ровно то, обо что разбивается наивное чтение: 0295 дословно оговаривает, что
-- строки «на изделие» (piece_id NULL) ЗАКОННО повторяют слот с разными placement («пуговицы —
-- планка» / «пуговицы — манжета»), потому что составной UNIQUE кортежи с NULL не ловит.
-- Построчное COALESCE(usage.quantity, bom.qty_per_garment) дало бы 6 + 6 = 12 пуговиц и прибавило
-- бы запас столько раз, сколько у пары строк. Правило, которое реализует entity (CountablePair*):
-- итог слота применяется ОДИН РАЗ на пару; если хоть одна строка пары несёт явное quantity, итог =
-- Σ явных, а значение слота не читается вовсе; запас прибавляется один раз на пару. Легаси-строки
-- без разрешённого bom_item_id в пару не группируются — тот же carve-out, что в шапке 0295.
--
-- ПОЧЕМУ НИЧЕГО НЕ БЭКФИЛЛИТСЯ. usage.quantity в слот НЕ переносится. Сегодня это число живёт на
-- паре, и на карточке с четырьмя колорвеями их четыре, возможно разные (замер 2 в
-- tmp/plans/countable-norms/MEASURE.sql считает ровно такие слоты). Механический выбор одного из
-- них — угадывание, которое читалось бы как утверждение. NULL значит «не задано», и существующие
-- строки продолжают считать деньги ровно как считали: явное quantity строки старше слота везде.
-- Ноль — РЕАЛЬНОЕ утверждение («ни одной»), поэтому DEFAULT'а нет ни у одной из колонок.
--
-- ГРАНИЦА СЕКЦИЙ ЖИВЁТ В GO, А НЕ В CHECK'Е. Счётные поля законны только на несчётной... точнее, на
-- НЕмерной секции (всё, кроме fabric/lining/interlining/insulation/thread/trim — trim намеренно
-- мерный: бейка, тесьма, кант и лента продаются метражом). Двухколоночный CHECK (section ↔
-- qty_per_garment) выстрелил бы сырым MySQL 3819 на UPDATE'е, который правит ОДНУ секцию, и назвал
-- бы оператору колонку, которой тот не касался, — дословно довод 0278. Здесь схема закрывает
-- ЗНАК (отрицательного количества не бывает), а пару «секция ↔ счётность» проверяет store рядом с
-- проверками назначения и вида, с указанием секции и способа выйти.
--
-- ИДЕМПОТЕНТНОСТЬ (CLAUDE.md): MySQL 8 автокоммитит DDL, поэтому падение в середине файла
-- оставляет схему полуприменённой без строки в gorp_migrations, и следующая загрузка перезапускает
-- файл с начала. Обе колонки и оба CHECK'а едут ОДНИМ ALTER (MySQL 8, атомарный DDL: всё или
-- ничего) под проверкой наличия qty_per_garment, поэтому повтор — no-op, а не «duplicate column».
-- CHECK'и ИМЕНОВАНЫ: авто-имя <table>_chk_<n> позиционно и дрейфует по истории схемы, дропать его
-- нельзя. PREPARE/EXECUTE/DEALLOCATE — ПО ОДНОМУ ОПЕРАТОРУ НА СТРОКУ: прод ходит без
-- multiStatements, и склеенная строка молча не выполнится.
--
-- БЕЗОПАСНОСТЬ ПРОТИВ ПРОДА: ADD COLUMN NULL ничего не переписывает (INSTANT в MySQL 8), а оба
-- CHECK'а валидируют существующие строки при добавлении и проходят ТРИВИАЛЬНО — на этот момент обе
-- колонки везде NULL, а предикат `IS NULL OR >= 0` на NULL истинен по построению. Ретроактивным
-- ADD CHECK, который копирует таблицу целиком (правило 0059/«ADD CHECK = COPY»), это НЕ является:
-- копирование заказывает не сам CHECK, а невыполнимость предиката на истории, и здесь он выполним
-- на любой строке, какой бы её ни завели. Масштаб таблицы — замер 1 в MEASURE.sql.

SET @col_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'tech_card_bom_item'
      AND COLUMN_NAME = 'qty_per_garment'
);
SET @ddl := IF(@col_exists = 0,
    'ALTER TABLE tech_card_bom_item ADD COLUMN qty_per_garment DECIMAL(10,3) NULL COMMENT ''сколько ШТУК этого артикула ПРИШИВАЕТСЯ на одно изделие: счётная норма слота, инвариантная по размеру и по колорвею. NULL = не задано (никогда не угадывается из строк рецепта); ноль — реальное утверждение. Итог применяется ОДИН РАЗ на пару (колорвей x слот); явное quantity строки рецепта старше'' AFTER wastage_applied_percent, ADD COLUMN spare_qty DECIMAL(10,3) NULL COMMENT ''сколько штук СВЕРХ пришитых закупается на изделие (запасная пуговица в пакетик): покупается, но не пришивается. NULL = запаса нет. Прибавляется один раз на пару (колорвей x слот), в деньги и в потребность входит, в сверку с маршрутом — нет'' AFTER qty_per_garment, ADD CONSTRAINT chk_bom_item_qty_per_garment CHECK (qty_per_garment IS NULL OR qty_per_garment >= 0), ADD CONSTRAINT chk_bom_item_spare_qty CHECK (spare_qty IS NULL OR spare_qty >= 0)',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down

-- Симметричный откат: сначала оба CHECK'а, затем обе колонки, ОДНИМ ALTER и под тем же гардом.
-- Данные при откате теряются, и это честно: колонки — единственное место, где счётная норма слота
-- хранится, восстановить её из строк рецепта нельзя (в них её и не было).
SET @col_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'tech_card_bom_item'
      AND COLUMN_NAME = 'qty_per_garment'
);
SET @ddl := IF(@col_exists = 1,
    'ALTER TABLE tech_card_bom_item DROP CONSTRAINT chk_bom_item_spare_qty, DROP CONSTRAINT chk_bom_item_qty_per_garment, DROP COLUMN spare_qty, DROP COLUMN qty_per_garment',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
