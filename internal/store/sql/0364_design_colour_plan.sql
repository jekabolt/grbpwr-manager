-- Цветовой план карточки: покрашенные флэты и то, какой цвет какой тканью оказался.
--
-- ЭКРАННЫЙ ФАКТ (Feature A). Перед рендером человек берёт флэт, заливает ведром тело в один
-- плоский цвет, кистью — манжеты в другой, и дальше в меню против КАЖДОГО использованного цвета
-- выбирает ткань, паттерн или просто цвет. Покрашенная картинка едет в прогон как «карта цветов»,
-- а список «цвет → ткань» превращается в те самые `fabrics[].parts` + `map_hex`, которые промпт
-- уже умеет читать.
--
-- ПОЧЕМУ ЭТО СОБСТВЕННАЯ ТАБЛИЦА, А НЕ ОДНА ИЗ ТРЁХ СОСЕДНИХ.
--
--   · НЕ `design_edit_layer`: там `uq_design_edit_layer_base (tech_card_id, base_media_id)` — одна
--     калька на подложку, — и покраска флэта столкнулась бы с его же обводкой. Плюс каждый читатель
--     слоёв (флэттен, бейдж устаревшей плиты, findLayerForMedia) получил бы шов «а этот слой не
--     считать»;
--   · НЕ `design_picture`: карта предлагалась бы в слоты верстака и попадала бы в выходы карточки
--     как рисунок изделия — а она рисунком изделия не является ни в каком смысле;
--   · НЕ `design_asset_placement`: ту UX владелец закрыл (J-21), и её форма — выноска на ассет, а
--     не область.
--
-- ОДНА СТРОКА НА КАРТОЧКУ, ДВА JSON-ДОКУМЕНТА, CAS ПО `rev`. Это ровно та же форма, которой
-- SaveDesignEditLayer заменяет документ целиком: план — это состояние ОДНОГО экрана, и перекраска
-- вида убирает цвета из палитры вместе с их назначениями. Патч по строкам заставил бы клиента
-- собирать это удаление из нескольких вызовов, каждый из которых умеет упасть отдельно.
--
-- ⚠ ИДЕНТИФИКАТОРЫ МЕДИА ВНУТРИ JSON НАМЕРЕННО НЕ ВНЕШНИЕ КЛЮЧИ. Удалённый файл делает карту
-- «пропавшей», и клиент читает это как `stale` — тем же чтением, что и `raster_deleted` у слоя.
-- FK потребовал бы либо RESTRICT (файл нельзя стереть из-за черновой покраски), либо отдельной
-- таблицы строк карты — второго документа о том же экране.
--
-- ⚠ CHECK-ОГРАНИЧЕНИЙ ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ. ADD CONSTRAINT … CHECK копирует таблицу целиком
-- и проверяется против ВСЕЙ истории; в этом проекте это однажды остановило старт прода. Форму
-- документа держит Go — SetDesignColourPlan, — и держит её ДО записи, называя человеку поле.

-- +migrate Up

CREATE TABLE IF NOT EXISTS design_colour_plan (
    tech_card_id INT NOT NULL PRIMARY KEY COMMENT 'план один на карточку: ключ и есть адрес',
    rev INT NOT NULL DEFAULT 0 COMMENT 'CAS-ревизия: SetDesignColourPlan требует expected_rev, 0 = плана ещё нет',
    maps JSON NOT NULL COMMENT 'покрашенные виды, [{view, media_id, base_media_id, palette:[{hex, px}]}]; не более одного на вид',
    cloths JSON NOT NULL COMMENT 'назначения палитры, [{hex, asset_id, colour_hex, words, parts}]; ключ — hex, а не ассет',
    updated_by VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'username из JWT последнего писателя',
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_design_colour_plan_card FOREIGN KEY (tech_card_id) REFERENCES tech_card(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT 'Цветовой план карточки: покрашенные флэты + какой цвет = какая ткань (до запуска)';

-- +migrate Down

DROP TABLE IF EXISTS design_colour_plan;
