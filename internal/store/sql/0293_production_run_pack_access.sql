-- ДОСТУП К ПУБЛИЧНОМУ НАРЯДУ НА ПАРТИЮ (/api/rp/{token}) — прогонный близнец
-- tech_card_pattern_viewer_access (0288). Печатный наряд несёт один QR со ссылкой-капабилити:
-- швея открывает её с телефона без JWT, а эта строка — единственное, чем такую бумагу можно
-- отозвать, не перепечатывая её. Токен несёт epoch, на котором был выпущен, поэтому epoch = epoch + 1
-- убивает все напечатанные до сих пор QR разом, не трогая ни прогон, ни его настилы.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА В tech_card_pattern_viewer_access И НЕ ОБЩАЯ СТРОКА.
-- Токен адресует объект ЧИСЛОМ, а id прогона, id тех-карты и id строки pattern_object_access живут
-- в одном числовом диапазоне и означают разные вещи. Пустили бы наряд по карточной строке — и
-- валидный токен на прогон №41 отдал бы манифест карточки №41: не «ошибка 500», а тихая выдача
-- чужого документа тому, кто предъявил настоящую подпись. Отдельная таблица + отдельный скоуп
-- токена ('r', internal/patterntoken) делают такую путаницу невыразимой: обработчик /api/rp
-- принимает только 'r' и резолвит его ТОЛЬКО здесь, обработчики /api/p и /api/pv отказывают 'r'
-- своим allowlist'ом.
--
-- ЧТО ОТЗЫВ ЗДЕСЬ НЕ ДОСТАЁТ, чтобы никто не планировал реакцию на утечку под обещание, которого
-- эта таблица не даёт: он закрывает МАНИФЕСТ наряда. Выкройки внутри наряда не раздаются — их
-- ссылки живут в карточном вьюере (0288) и отзываются там же. Отзыв наряда — это «новую бумагу не
-- получишь», а не «сборочный лист исчез из уже открытой вкладки».
--
-- expires_at — колонка, которую читает обработчик, а НЕ политика: наряд лежит в цехе на столе
-- неделями, и протухший в середине партии QR хуже долгоживущей ссылки. Строки создаются с NULL,
-- TTL по умолчанию не проставляет никто (то же решение, что в 0288). Отзыв — ручной: epoch + 1.
--
-- Строка заводится лениво при первом чтении прогона, которое минтит токен; у прогона без строки
-- просто нет выпущенных наружу токенов.

CREATE TABLE IF NOT EXISTS production_run_pack_access (
    run_id INT NOT NULL PRIMARY KEY,
    epoch INT NOT NULL DEFAULT 1,
    expires_at TIMESTAMP NULL DEFAULT NULL,
    revoked_at TIMESTAMP NULL DEFAULT NULL,
    last_access_at TIMESTAMP NULL DEFAULT NULL,
    access_count BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prpa_run FOREIGN KEY (run_id) REFERENCES production_run (id) ON DELETE CASCADE
);

