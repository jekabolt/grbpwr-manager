-- Полоса DESIGN, воркбенч FLAT (O-53 review, раунд 2) — ИЗ КАКОГО СЛОЯ РАСПЛЮЩЕН КАДР.
--
-- ЧТО БЫЛО НЕВЕРНО. Повтор флэттена по ключу (0370) сверял с кадром первой попытки глагол, ревизию
-- слоя, режим и место — но не САМ СЛОЙ, потому что кадр его не помнил: layer_rev есть, layer_id нет.
-- Два слоя одной карточки на одной ревизии (у каждого своя ревизия, и первая у всех — 1) делили
-- ключ: «save as new» слоя L2 под ключом, уже потраченным на L1, получал картинку L1 как свой успех,
-- и L2 не подавался вовсе.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ ВЫВОД ИЗ ИМЕЮЩИХСЯ. Слой с подложкой можно было бы узнать по родителю кадра
-- (один слой на пару карточка + base_media_id, uq_design_edit_layer_base), но слой, нарисованный с
-- чистого листа, родителя не имеет, и таких слоёв на карточке законно несколько (NULL в уникальном
-- индексе не конфликтует). Вывод работал бы для одних слоёв и молча не работал бы для других.
--
-- ЧТО ЭТО ЗА КОЛОНКА. Пара к layer_rev: «какой слой, какая ревизия» — слой, из которого
-- FlattenEditLayer растеризовал кадр. Писатель один (layer.go, FlattenEditLayer), пишет один раз, при
-- вставке. NULL у всего остального — у кадров прогона, загрузок и кропов (кроп копирует layer_rev
-- родителя, но его не расплющивали из слоя) — и у флэттенов до этой миграции: бэкфилла нет, доказать
-- слой старого флэттена нечем по той же причине, что и выше. Ключи повтора (0370) и эта колонка
-- пишутся одной вставкой, поэтому кадр с ключом и без слоя появиться не может.
--
-- INT UNSIGNED — ТОТ ЖЕ ТИП, ЧТО У design_edit_layer.id: колонка называет строку той таблицы.
--
-- FK НЕТ НАМЕРЕННО — по доводу derived_from (0340, FK-ПОЛИТИКА): обе таблицы принимают входящий
-- каскад удаления карточки, и второй путь каскада между ними — риск, который нельзя доказать на
-- бумаге, ради выигрыша, которого нет (слои не удаляются ничем, кроме удаления карточки). Целостность
-- держит Go. ИНДЕКСА НЕТ: ни один запрос не ищет ПО source_layer_id — колонка читается у строки, уже
-- найденной по ключу.
--
-- ЦЕНА. ADD COLUMN ... NULL в КОНЕЦ таблицы — INSTANT (MySQL 8.0.12+), строки не переписываются.
--
-- ОКНО «СТАРЫЙ БИНАРЬ × НОВАЯ СХЕМА» БЕЗОПАСНО: хендл стора — `d.Unsafe()`, лишняя колонка в
-- SELECT * читается в никуда, а INSERT'ы старого бинаря её не называют и оставляют NULL.

-- +migrate Up

SET @dp_source_layer := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_picture'
      AND COLUMN_NAME = 'source_layer_id');
SET @ddl := IF(@dp_source_layer = 0,
    'ALTER TABLE design_picture
        ADD COLUMN source_layer_id INT UNSIGNED NULL
            COMMENT ''design_edit_layer.id, из которого FlattenEditLayer растеризовал кадр (0371), пара к layer_rev: повтор по ключу (0370) отвечает только запросу того же слоя. NULL = кадр не расплющен из слоя (прогон, загрузка, кроп) либо флэттен до 0371. FK нет по доводу derived_from''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down
--
-- Откат теряет слои уже поданных флэттенов и откатывается только вместе с кодом: FlattenEditLayer
-- называет колонку во вставке, и без неё падал бы каждый флэттен. На проде и бете миграции идут
-- только вверх, Down здесь путь разработчика.

SET @dp_source_layer_down := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_picture'
      AND COLUMN_NAME = 'source_layer_id');
SET @ddl := IF(@dp_source_layer_down = 1,
    'ALTER TABLE design_picture DROP COLUMN source_layer_id',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
