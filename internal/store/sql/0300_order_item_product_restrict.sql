-- ИСТОРИЯ ЗАКАЗА НЕ КАСКАДИТСЯ ОТ ПРОДУКТА.
--
-- order_item.product_id объявлен ON DELETE CASCADE ещё в 0001 и таким и остался. Пока продукт
-- нельзя было удалить физически, это ничего не значило: единственный «delete» в системе был мягким
-- (DeleteProductById проставляет deleted_at), а DeleteColorwayByID вообще заменили на
-- ArchiveColorwayByID. С появлением настоящего DELETE FROM product (узкая дырка в
-- «архивируем, не удаляем» — только колорвей, который никогда не продавался и не производился)
-- строка внезапно стала значить буквально следующее: удаление продукта СНОСИТ ЕГО СТРОКИ ЗАКАЗОВ,
-- а вместе с ними — по каскадам от order_item — refunded_order_item и отзывы.
--
-- ПОЧЕМУ ЭТОГО НЕ ЛОВИТ 0153. Там order_item.variant_id → product_size(id) ON DELETE RESTRICT, и
-- product_size каскадится от продукта, поэтому кажется, что продажа заблокирует удаление по
-- цепочке. Это НЕ ГАРАНТИЯ: у продукта два ребёнка сразу, один RESTRICT-транзитом
-- (product_size → order_item.variant_id) и один прямым CASCADE (order_item.product_id), а порядок
-- обхода детских ограничений InnoDB не специфицирован. Если движок обойдёт прямой каскад первым,
-- строки заказа исчезнут ДО того, как RESTRICT найдёт кого защищать, и он пропустит удаление.
-- Опираться на порядок обхода в вопросе «переживёт ли история заказов удаление продукта» нельзя.
--
-- ТОТ ЖЕ ДОВОД, ЧТО В 0149. Там ровно так же перевернули size_id: удаление словарного размера не
-- должно каскадом уносить варианты, историю заказов и размерную таблицу стиля. Неизменяемая история
-- заказа несовместима с каскадом — независимо от того, с какой стороны каскад приходит.
--
-- ЧТО МЕНЯЕТСЯ НА ПРАКТИКЕ. Ничего для сегодняшних путей: физического удаления продукта в коде до
-- сих пор не было ни одного. Новый DeleteColorway отказывает по СВОЕМУ предикату (не продан, не в
-- партии, не в настиле, без остатка) и пере-проверяет его внутри транзакции — этот FK не рабочий
-- механизм отказа, а последний рубеж на случай, если предикат когда-нибудь ошибётся: тогда операция
-- упадёт с 1451, а не сотрёт заказы. Приложение переводит остаточный 1451 в читаемый отказ.
--
-- РЕТРОАКТИВНОЙ ПРОВЕРКИ НЕТ. ADD CONSTRAINT ... FOREIGN KEY валидирует существующие строки, но
-- этот FK уже стоит на таблице — просто с другим правилом удаления, — поэтому каждая строка ему
-- заведомо удовлетворяет, и валидация проходит вхолостую. Это не «новый потолок на старой колонке»
-- (см. 0292): множество допустимых значений не сузилось, сузилось поведение родителя при удалении.
--
-- Имя старого ограничения позиционное и авто-сгенерированное (order_item_ibfk_N), поэтому
-- находится в information_schema, а не зашивается. Идемпотентность (CLAUDE.md): блок работает
-- ТОЛЬКО пока FK ещё CASCADE, а DROP+ADD — один атомарный ALTER, так что повторный прогон после
-- падения не застаёт полусостояния. PREPARE/EXECUTE/DEALLOCATE по одному оператору на строку
-- (multiStatements=true в контейнерных тестах замаскировал бы баг, который прод не переживёт).
-- 0001 не редактируется.

SET @old_fk := (SELECT CONSTRAINT_NAME FROM information_schema.KEY_COLUMN_USAGE
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'order_item'
      AND COLUMN_NAME = 'product_id' AND REFERENCED_TABLE_NAME = 'product' LIMIT 1);
SET @is_cascade := (SELECT COUNT(*) FROM information_schema.REFERENTIAL_CONSTRAINTS
    WHERE CONSTRAINT_SCHEMA = DATABASE() AND TABLE_NAME = 'order_item'
      AND CONSTRAINT_NAME = @old_fk AND DELETE_RULE = 'CASCADE');
SET @sql := IF(@old_fk IS NOT NULL AND @is_cascade = 1,
    CONCAT('ALTER TABLE order_item DROP FOREIGN KEY ', @old_fk,
           ', ADD CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE RESTRICT'),
    'SELECT 1');
PREPARE s FROM @sql;
EXECUTE s;
DEALLOCATE PREPARE s;

