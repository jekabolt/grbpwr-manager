-- ОБСУЖДЕНИЕ ФАЙЛА: ПЛОСКАЯ ЛЕНТА РЕПЛИК.
--
-- ПОЧЕМУ ПЛОСКО, БЕЗ ВЕТОК. Ветка требует, чтобы человек в момент письма ВЫБРАЛ, к чему он
-- отвечает, — и этот выбор делается неправильно ровно в тех обсуждениях, ради которых ветки
-- заводят. Прецедент внутри этой же кодовой базы — комментарии задачи (`task_comment`, 0090):
-- плоский список живёт годами и никого не заставил жаловаться на потерянную нить. Поэтому
-- `parent_id` здесь нет ВООБЩЕ: колонка, которую никто не заполняет, хуже её отсутствия — она
-- обещает дерево, которого нет ни в одном запросе.
--
-- ДВА ПОЛЯ АВТОРА, И ЭТО ТОТ ЖЕ ДОВОД, ЧТО У ФАЙЛА (0314). `author` — строка-факт: «это написал
-- pasha», она обязана пережить удаление аккаунта, иначе лента задним числом теряет говорящих и
-- перестаёт быть перепиской. `author_id` — ЖИВАЯ ссылка: ею резолвятся аватар, инициалы и
-- специальность в шапке реплики, и она честно обнуляется вместе с аккаунтом (ON DELETE SET NULL).
-- Схлопывание их в одно поле означало бы выбор между «переписка стирается при увольнении» и
-- «в admins нельзя удалить строку».
--
-- ПРАВО ПРАВКИ НЕ В СХЕМЕ, А В ХЕНДЛЕРЕ. «Свою реплику правит автор, супер — любую» проверяется
-- по `author` (username из JWT), а не по `author_id`: у реплики уволенного `author_id` уже NULL, и
-- сравнение по ссылке молча открыло бы её всем. Констрейнтом это не выразить — здесь только факты.
--
-- `edited_at` NULL = не правилась ни разу. Отдельный флаг «изменено» не нужен: метка на реплике
-- рисуется по непустому времени, и это же время отвечает на вопрос «когда именно».
--
-- КАСКАД ОТ ФАЙЛА. Обсуждение существует только про живой файл; удалили файл — обсуждать нечего,
-- держать ленту не за что. Это не потеря истории, а её граница: журнал «кто выложил» и переписка
-- про содержимое умирают вместе с содержимым.
--
-- ИНДЕКС (file_id, id) — единственный способ, которым эту таблицу читают: лента одного файла в
-- порядке письма и счётчик реплик на страницу списка (сгруппированный запрос по file_id, не N+1).
-- `id` вторым столбцом даёт и сортировку, и покрытие счётчику, поэтому отдельного индекса по
-- file_id нет.
--
-- ИДЕМПОТЕНТНОСТЬ (CLAUDE.md): MySQL 8 автокоммитит DDL, поэтому падение в середине файла
-- оставляет схему полуприменённой БЕЗ строки в gorp_migrations, и следующая загрузка перезапускает
-- файл с начала. Здесь ровно один CREATE TABLE IF NOT EXISTS — повтор является no-op. ALTER'ов,
-- PREPARE/EXECUTE и ретроактивных CHECK (они проверяют ВСЮ историю и останавливают старт прода)
-- в этом файле нет.

CREATE TABLE IF NOT EXISTS library_file_comment (
  id INT PRIMARY KEY AUTO_INCREMENT,
  file_id INT NOT NULL,
  author VARCHAR(255) NOT NULL COMMENT 'username автора на момент письма, из JWT; факт-строка, переживает удаление аккаунта — по ней же проверяется право правки',
  author_id INT NULL COMMENT 'живая ссылка на аккаунт автора для аватара/специальности; NULL = аккаунта больше нет (строка author остаётся)',
  body TEXT NOT NULL COMMENT 'текст реплики как его набрали; @username хранится плоским текстом, серверной разметки нет',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  edited_at TIMESTAMP NULL DEFAULT NULL COMMENT 'время последней правки; NULL = не правилась (метка «изменено» рисуется по непустому значению)',
  INDEX idx_library_file_comment_file (file_id, id),
  CONSTRAINT fk_library_file_comment_file FOREIGN KEY (file_id)
    REFERENCES library_file (id) ON DELETE CASCADE,
  CONSTRAINT fk_library_file_comment_author FOREIGN KEY (author_id)
    REFERENCES admins (id) ON DELETE SET NULL
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT 'Обсуждение файла библиотеки: плоская лента реплик';

