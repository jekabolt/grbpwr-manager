-- Полоса DESIGN, круг 6, X-1: У СЛОЯ ПРАВКИ ПОЯВЛЯЕТСЯ ПИКСЕЛЬНЫЙ КАНАЛ.
--
-- ЧТО БЫЛО. `design_edit_layer` (0343) знает про слой ровно один способ что-то нарисовать —
-- `strokes`, вектор. Кисть, ластик и штамп поэтому работали ПО ШТРИХАМ: «ластик» дорисовывал
-- белый штрих поверх, «штамп» копировал кривые. Владелец потребовал настоящий растровый редактор
-- (V-9 круга 5, отложено; X-1..X-9 круга 6), и слово РАСТРОВЫЙ у слоя выразить было нечем.
--
-- ─── ЧТО ИМЕННО ХРАНИТ КОЛОНКА ─────────────────────────────────────────────────────────────────
--
-- ОДНО МЕДИА RGBA — ПОЛНОЕ СОСТОЯНИЕ ПИКСЕЛЕЙ СЛОЯ, А НЕ ДЕЛЬТА. Открывая редактор впервые, его
-- заводят копией подложки; дальше кисть красит по нему, ластик стирает до прозрачности. Дельта
-- («что дорисовали поверх базы») была бы вторым представлением того же факта и разошлась бы с ним
-- в первый же день: ластик по решению владельца ПРОГРЫЗАЕТ И ПОДЛОЖКУ, то есть результат вообще не
-- выражается как «база плюс что-то сверху».
--
-- ⚠ ИМЕННО ПОЭТОМУ ОТДЕЛЬНОЙ МАСКИ БАЗЫ ЗДЕСЬ НЕТ, и это решение, а не пропуск. Дырка, прогрызенная
-- в фотографии, выражается АЛЬФОЙ САМОЙ КАРТИНКИ; вторая колонка под маску была бы ещё одним
-- способом сказать то же самое и ещё одним каналом, который обязан не разъехаться с ревизией.
--
-- ПОДЛОЖКА (`base_media_id`) ОСТАЁТСЯ И НЕ ПОРТИТСЯ. Она отвечает на вопрос «что именно обводили» —
-- провенанс, — и дырки живут в другом медиа. Одна калька на одну картинку (ответ владельца
-- дословно: «Один. Как сейчас»), поэтому канал ОДИН, а не список слоёв краски: `uq_design_edit_layer_base`
-- уже держит это правило и трогать его незачем.
--
-- КАРТИНКУ РИСУЕТ КЛИЕНТ. Это не новость и не уступка, а уже действующее устройство полосы:
-- `FlattenDesignEditLayer` принимает `media_id` файла, который клиент растеризовал и загрузил через
-- `UploadContentImage` (Р-2). Растровый слой едет ТЕМ ЖЕ путём — иначе в процессе завёлся бы второй
-- растеризатор, а рисующий холст всё равно остаётся единственным честным производителем пикселей.
--
-- ─── РОД ВНЕШНЕГО КЛЮЧА: RESTRICT, И ЭТО СИЛЬНЕЙШИЙ СЛУЧАЙ ВО ВСЕЙ ТАБЛИЦЕ ──────────────────────
--
-- У `base_media_id` (0343) и `source_media_id` (0350) стоит RESTRICT, и довод у обоих один: без
-- файла слой неработоспособен. У растра он ещё прямее, потому что различие между двумя другими
-- колонками и этой — различие между «нечем открыть» и «НЕЧЕГО ПОКАЗАТЬ».
--
--   * подложка — ЧТО обводили; её исчезновение обрывает контекст правки;
--   * исходный SVG — ОТКУДА взялся вектор; его исчезновение обрывает происхождение;
--   * растр — САМА РАБОТА ЧЕЛОВЕКА. Мазки кистью, дырки от ластика, клоны штампа. Полное
--     состояние, а не производная: восстановить его не из чего вообще, потому что вторых
--     координат, как у штрихов, у пикселей нет.
--
-- Три рода рассматривались:
--   * SET NULL — ОТВЕРГНУТ, и это главный отвергнутый вариант. Он молча превратил бы закрашенный
--     слой обратно в голый векторный: следующее открытие редактора показало бы чистую подложку, а
--     следующий флэттен материализовал бы КАРТИНКУ, ОТЛИЧНУЮ ОТ ТОЙ, ЧТО ЧЕЛОВЕК ВИДЕЛ. Потеря
--     работы без единого сообщения — ровно то, ради чего в этой таблице вообще заведён CAS;
--   * ГОЛЫЙ KEY (как у `design_reference.media_id`, 0347) — хуже SET NULL: висящий id, по которому
--     клиент попросит у бакета несуществующий объект и получит битую картинку вместо честной пустоты;
--   * RESTRICT — принят. Отказ в удалении здесь не побочный эффект, а СООБЩЕНИЕ: файл держит
--     незавершённая правка. Это тот же ответ, который медиатека уже даёт про подложку.
--
-- Прецедент про `DeleteTechCard` действует без изменений: ограничение стоит на стороне `media`,
-- которая от `tech_card` не каскадится, поэтому удаление карточки сносит слой каскадом по
-- `tech_card_id`, слой отпускает медиа, и 1451 не возникает.
--
--   ⚠️ СЛЕДСТВИЕ, КОТОРОЕ ЗАКРЫВАЕТ КОД, А НЕ ЭТА МИГРАЦИЯ: новая ссылка ОБЯЗАНА получить строку в
--   `mediaRefRegistry` (`internal/store/content/media_usage.go`, рядом с `base_media_id` и
--   `source_media_id`). Без неё `GetMediaUsage` объявит файл СВОБОДНЫМ, человек нажмёт удалить и
--   получит сырой внешний ключ с именем таблицы, о которой никогда не слышал; а
--   `TestMediaUsageRegistryCoversSchema` (`internal/store/media_usage_integration_test.go`) диффит
--   реестр против ВСЕХ живых FK в `media(id)` и покраснеет. В этой правке строка добавлена.
--
-- ─── ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО ──────────────────────────────────────────────────────────────────
--
-- НИ ОДНОГО `ADD CONSTRAINT … CHECK`. Правило «растр обязан быть картинкой этой карточки»
-- выражается только запросом к другим таблицам, а `ADD CHECK` вдобавок КОПИРУЕТ таблицу целиком и
-- проверяет всю историю под пятиминутным потолком всего прогона (`internal/store/store.go`):
-- ретроактивная проверка — это способ остановить старт прода, а не способ описать правило.
-- Принадлежность проверяет Go (`refuseForeignMedia`), ровно как у `ImportVector`.
--
-- ОТДЕЛЬНОЙ РЕВИЗИИ У РАСТРА НЕТ, И ЭТО ТРЕБОВАНИЕ X-9, А НЕ ЭКОНОМИЯ. Пиксели и штрихи — ДВА
-- КАНАЛА ОДНОГО СЛОЯ, они лежат на ОДНОЙ строке и ходят под ОДНИМ `rev`. Вторая ревизия означала бы
-- две независимые гонки на одном экране: сохранение пикселей поверх чужой ревизии — та же потеря
-- работы, что и сохранение штрихов, и отвечать на неё обязан тот же CAS.
--
-- ─── ЦЕНА И ИДЕМПОТЕНТНОСТЬ ────────────────────────────────────────────────────────────────────
--
-- Колонка, её индекс и её ключ едут ОДНИМ оператором (приём 0350:2, до него — 0323): так не
-- возникает половинчатого состояния «колонка есть, ключа нет». Плата названа вслух: смешанный
-- оператор теряет INSTANT и идёт INPLACE с перестройкой таблицы. Здесь она мала — `design_edit_layer`
-- на проде ещё не существует (прод стоит до 0340), на бете таблица почти пуста.
--
-- Тип INT (ЗНАКОВЫЙ) согласован с `media(id)`, `base_media_id` (0343) и `source_media_id` (0350):
-- расхождение знаковости даёт 3780 на создании FK.
--
-- ИДЕМПОТЕНТНОСТЬ: MySQL авто-коммитит DDL пооператорно, поэтому падение посреди файла оставляет
-- схему полуприменённой БЕЗ строки в `gorp_migrations`, и следующий старт прогонит файл с начала.
-- Оператор — под гейтом `information_schema.COLUMNS`. `PREPARE` / `EXECUTE` / `DEALLOCATE` — каждый
-- СВОЕЙ СТРОКОЙ: прод ходит БЕЗ `multiStatements`, а контейнерный тест эту поломку маскирует.
--
-- ⚠ ГЕЙТ СТОИТ НА КОЛОНКЕ, А ПРОВЕРЯЕТ ТРИ ВЕЩИ (колонку, индекс и ключ), И ЭТО ЗАКОННО ИМЕННО
-- ПОТОМУ, ЧТО ВСЕ ТРИ РОЖДАЮТСЯ ОДНИМ `ALTER TABLE`: MySQL 8 выполняет его атомарно, поэтому
-- состояния «колонка есть, ключа нет» этот файл породить не может. Замерено на стенде: Up дважды —
-- no-op; Down дважды — no-op; Down→Up возвращает все три. Если такое расхождение всё же возникнет
-- (ключ снят руками), повторный Up его НЕ починит — чинить руками, и это цена приёма, названная
-- вслух. Тот же гейт и та же цена у 0350, шаг 2.
--
-- ОКНО «СТАРЫЙ БИНАРЬ × НОВАЯ СХЕМА» БЕЗОПАСНО: хендл стора — `d.Unsafe()`, лишние колонки в
-- `SELECT *` молча игнорируются сканером. Обратная сторона названа вслух: до появления поля в
-- `entity.DesignEditLayer` колонка читается как ноль МОЛЧА.

-- +migrate Up

SET @del_raster := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_edit_layer'
      AND COLUMN_NAME = 'raster_media_id');
SET @ddl := IF(@del_raster = 0,
    'ALTER TABLE design_edit_layer
        ADD COLUMN raster_media_id INT NULL
            COMMENT ''пиксельный канал слоя: ОДНО медиа RGBA, ПОЛНОЕ состояние пикселей, не дельта. Ластик прогрызает и подложку, поэтому дырка выражается альфой самой картинки и отдельная маска базы не нужна. Картинку рисует и грузит КЛИЕНТ, как у флэттена. FK RESTRICT: ссылка ВЛАДЕЮЩАЯ (это сама работа человека), обязана быть в mediaRefRegistry'',
        ADD KEY idx_design_edit_layer_raster_media (raster_media_id),
        ADD CONSTRAINT fk_design_edit_layer_raster_media FOREIGN KEY (raster_media_id)
            REFERENCES media(id) ON DELETE RESTRICT',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down
--
-- ВНЕШНИЙ КЛЮЧ СНИМАЕТСЯ ТЕМ ЖЕ ОПЕРАТОРОМ, ЧТО И КОЛОНКА, а текст оператора собирается ПО ФАКТУ:
-- если предыдущий откат успел упасть между шагами, ключа может уже не быть, и его безусловное
-- упоминание заклинило бы откат навсегда (приём и ловушка — 0323/0350, Down).
--
-- ОДНОКОЛОНОЧНЫЙ ИНДЕКС ЯВНО НЕ СНИМАЕТСЯ: MySQL уносит его вместе с колонкой, когда снимаются ВСЕ
-- его колонки. Ловушка 0323 (индекс переживает колонку, теряя её из состава) касается только
-- многоколоночных — здесь такого нет.
--
-- Откат ТЕРЯЕТ ВСЮ РАСТРОВУЮ РАБОТУ, оставляя файлы в медиатеке сиротами. Другого честного
-- поведения у DROP COLUMN нет, и это ещё одна причина, по которой ссылка владеющая.

SET @del_raster_down := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_edit_layer'
      AND COLUMN_NAME = 'raster_media_id');
SET @del_raster_fk := (SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE CONSTRAINT_SCHEMA = DATABASE() AND TABLE_NAME = 'design_edit_layer'
      AND CONSTRAINT_NAME = 'fk_design_edit_layer_raster_media' AND CONSTRAINT_TYPE = 'FOREIGN KEY');
SET @ddl_down := IF(@del_raster_down = 1,
    CONCAT('ALTER TABLE design_edit_layer',
        IF(@del_raster_fk > 0, ' DROP FOREIGN KEY fk_design_edit_layer_raster_media,', ''),
        ' DROP COLUMN raster_media_id'),
    'SELECT 1');
PREPARE stmt FROM @ddl_down;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
