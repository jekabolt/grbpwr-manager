-- ПЛОЩАДИ ДЕТАЛЕЙ КРОЯ (Ф0) — единственный источник серверного ответа на вопрос «сколько ткани
-- занимает изделие, если положить детали вплотную».
--
-- ЗАЧЕМ. Сегодня у карточки может быть заполнено ВСЁ: спецификация с ценами, разобранные выкройки,
-- назначение каждой детали кроя на ткань в рецепте колорвея — а себестоимость всё равно ноль.
-- Причина не в пробеле данных, а в том, что деньги умеет считать только СТРОКА РЕЦЕПТА с явно
-- вписанной нормой: сервер обходит usages (dto.colorwayCost), а строку, привязанную к детали,
-- пропускает целиком (T8: «расход — свойство изделия»). Геометрия, из которой норма выводится сама,
-- существует ТОЛЬКО в браузере: парсера DXF в Go нет и не будет (см. 0280, тот же довод).
--
-- Эта таблица — то самое недостающее звено: разобранная геометрия, положенная на сервер один раз,
-- чтобы норму можно было ВЫВЕСТИ, а не требовать её ввода.
--
-- ЕДИНИЦА ХРАНЕНИЯ — ПЛОЩАДЬ ОДНОГО ЭКЗЕМПЛЯРА КОНТУРА, а не изделия и не детали «со всеми
-- экземплярами». `pieces_per_garment` живёт на самой детали, меняется отдельной правкой карточки и
-- к геометрии файла отношения не имеет; вмножив его сюда, мы бы получили число, которое молча
-- врёт после каждой правки количества, причём ровно в ту сторону, которая обнаруживается на складе.
-- Умножение делает ЧИТАТЕЛЬ. (Клиентский dxf-consumption.ts сегодня умножает внутри себя — при
-- записи сюда обязана использоваться проекция ДО умножения, иначе двойной счёт.)
--
-- КЛЮЧ НЕСЁТ СКОУП ТКАНИ, и это не осторожность, а следствие T4: одна деталь законно кроится из
-- нескольких слоёв материала, подкладочная версия нарисована СВОИМ контуром и имеет СВОЮ площадь.
-- Тот же ключ, что у привязок блоков (0267: scope_key = COALESCE(fabric_purpose, bom_line_key)) и у
-- индекса размеров (0280) — одна функция entity.FabricScopeKey на всех.
--
-- ДЕТАЛЬ АДРЕСУЕТСЯ line_key, А НЕ id. Слепок релиза — это protojson контракта, а в контракте у
-- детали кроя id НЕТ, только line_key (production_cut_plan.go: «piece_id в строках наряда по релизу
-- будет нулём»). Ключ на id сделал бы площади невидимыми ровно там, где по ним считаются деньги
-- released-карточки.
--
-- size_id NULL — ЗАКОННОЕ ЗНАЧЕНИЕ и означает «деталь не градуируется»: она входит в комплект
-- КАЖДОГО размера целиком. Ровно то же правило уже считает entity.MarkerSizeAreasPerGarment и
-- клиентский size-areas-from-dxf.ts; второго правила не заводим.
--
-- ОТПЕЧАТОК ЛИСТОВ ПИШЕТ СЕРВЕР, клиент его не присылает и прислать не может (приём 0280/0268):
-- перезаливка любого листа двигает url/version, отпечаток расходится, площади читаются как
-- УСТАРЕВШИЕ — сами, без чьего-либо участия. Заявить покрытие по файлам, которых нет, нельзя.
--
-- УСЛОВИЯ ЗАМЕРА ХРАНЯТСЯ ВМЕСТЕ С ПЛОЩАДЬЮ, потому что без них площадь — не число, а мнение:
-- слой 14 несёт линию шва и его надо раздуть припуском, слой 1 несёт линию кроя, в которой припуск
-- уже есть. Ошибка здесь молча меняет норму на величину припуска по всему периметру каждой детали.
--
-- hulled И ambiguous_pick — РАЗНЫЕ состояния и сливать их нельзя: первое означает «контур при
-- раздутии припуском заменён выпуклой оболочкой» (площадь завышена, но детерминирована), второе —
-- «на слое было несколько совпадающих по площади кандидатов, взят первый» (число зависит от порядка
-- листов в пачке, и сверять его с чем-либо нельзя).
--
-- БЕЗ КЛАУЗЫ CHARSET (прецедент 0252/0257/0272/0280): прод и бета крутятся на серверном дефолте
-- utf8mb3, локальные контейнерные тесты подключаются utf8mb4, и явная клауза развела бы их незаметно.

CREATE TABLE IF NOT EXISTS tech_card_piece_area (
    id INT AUTO_INCREMENT PRIMARY KEY,
    tech_card_id INT NOT NULL,
    -- Скоуп ткани: COALESCE(fabric_purpose, bom_line_key), как в 0267 и 0280.
    scope_key VARCHAR(64) NOT NULL,
    -- Деталь кроя — по её стабильному line_key (см. шапку про слепок релиза).
    piece_line_key CHAR(26) NOT NULL,
    -- NULL = деталь не градуируется и входит в каждый размер целиком.
    size_id INT NULL,
    -- Генерируемый ключ: MySQL UNIQUE считает каждый NULL уникальным, поэтому «неградуируемая
    -- деталь» без этого столбца могла бы лечь в таблицу дважды и удвоить площадь изделия.
    size_key INT AS (COALESCE(size_id, 0)) STORED,
    -- Площадь ОДНОГО экземпляра контура, см², по условиям ниже.
    area_cm2 DECIMAL(12,2) NOT NULL,
    -- УСЛОВИЯ ЗАМЕРА.
    contour_layer VARCHAR(64) NOT NULL DEFAULT '',
    seam_allowance_mm DECIMAL(6,1) NOT NULL DEFAULT 0.0,
    hulled TINYINT(1) NOT NULL DEFAULT 0,
    ambiguous_pick TINYINT(1) NOT NULL DEFAULT 0,
    -- ПРОВЕНАНС.
    sheet_fingerprint CHAR(64) NOT NULL,
    parsed_by VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'admin username, который подтвердил замер',
    parsed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT uniq_tcpa_scope_piece_size UNIQUE (tech_card_id, scope_key, piece_line_key, size_key),
    CONSTRAINT chk_tcpa_area_positive CHECK (area_cm2 > 0),
    -- Размер либо НЕ ЗАДАН (деталь не градуируется), либо настоящий: ноль и отрицательное значение
    -- не бывают размерами, а через генерируемый size_key ноль означал бы «неградуируемая» и молча
    -- слил бы две разные детали в одну строку.
    CONSTRAINT chk_tcpa_size_positive CHECK (size_id IS NULL OR size_id > 0),
    CONSTRAINT fk_tcpa_tech_card FOREIGN KEY (tech_card_id) REFERENCES tech_card (id) ON DELETE CASCADE,
    INDEX idx_tcpa_card_scope (tech_card_id, scope_key)
) ENGINE=InnoDB;

