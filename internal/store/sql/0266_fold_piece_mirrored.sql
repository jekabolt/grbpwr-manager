-- Свернуть зеркальность в количество и погасить флаг.
--
-- Зеркальность отставлена: владелец говорит, что функцией не пользовались. Но правило считалось
-- НА ХРАНИМЫХ СТРОКАХ — total_per_garment был pieces_per_garment × 2 при mirrored=1, — и просто
-- перестать умножать значит вдвое уменьшить количество на КАЖДОЙ такой строке: в cut list, в
-- статистике «деталей кроить», в раскройном талоне семпла. А первое же сохранение карточки
-- обнуляет столбец, то есть стирает единственное свидетельство, что деталь была парной. Хуже
-- всего в тех-паке: он печатает pieces_per_garment (никогда не total), так что фабрика увидела бы
-- «1» у детали, которую физически кроят парой, и нигде ни слова об этом.
--
-- Проверять «а есть ли такие строки на проде» не нужно, если свернуть их явно: количество
-- удваивается ровно на том множителе, который убрали, флаг гасится. Строк нет — миграция
-- ничего не делает; строки есть — числа не меняются вообще, меняется только то, ГДЕ они
-- записаны. Это дешевле любой проверки и не зависит от того, чем окажется прод.
--
-- Идемпотентно по построению: условие WHERE mirrored = 1 после первого прохода пусто.
--
-- ПОРЯДОК ДЕПЛОЯ ВАЖЕН: бэкенд (эта миграция + снятое умножение) идёт ПЕРЕД клиентом. В обратном
-- порядке уже собранная карточка показала бы удвоенное сервером количество с уже убранной
-- колонкой, которая его объясняла.

UPDATE tech_card_piece
SET pieces_per_garment = pieces_per_garment * 2,
    mirrored = 0
WHERE mirrored = 1;

