-- +migrate Up

-- ДЕТАЛЬ БЕЗ ГРАДАЦИИ (UNI). Карман, шлёвка, обтачка одинаковы от XS до XL: контур у такой детали
-- ОДИН на весь ряд, и он входит в комплект каждого размера целиком. Сегодня сказать это карточке
-- нечем — безразмерность УГАДЫВАЕТСЯ на клиенте по тому, что в имени блока DXF не нашлось токена
-- размера.
--
-- ПОЧЕМУ УГАДЫВАНИЕ НАДО ЗАМЕНИТЬ ЗАЯВЛЕНИЕМ. Эвристика по имени ошибается в обе стороны и молчит
-- в обеих: деталь, названную без размера по небрежности, она читает как UNI (и та входит во все
-- размеры одним контуром, хотя контуров должно быть пять), а деталь, в чьё имя размер попал, она
-- НЕ ДАЁТ объявить безразмерной вообще. Имя блока — это то, как файл назвали, а не то, как деталь
-- кроится; спрашивать у него про градацию — то же самое, что определять парность по заметке
-- (см. заголовок 0275, там этот же довод уже оплачен).
--
-- КОЛОНКА НА ДЕТАЛИ, А НЕ НА ЗАМЕРЕ. Безразмерность — свойство САМОЙ детали (её геометрии), а не
-- одного измерения: она одинакова для всех тканей, всех раскладок и всех замеров этой детали.
-- Держать её на строке площади значило бы разрешить двум замерам одной детали противоречить друг
-- другу, и правым был бы тот, кто сохранился последним.
--
-- NOT NULL DEFAULT FALSE, А НЕ NULLABLE «не размечено» — в отличие от cut_symmetry (0275), где
-- незнание было опасным и обязано было читаться как незнание. Здесь FALSE не утверждение о
-- конструкции, а описание сегодняшнего поведения: карточка без флага ведёт себя ровно так, как
-- вела до этой миграции — деталь либо меряется по каждому размеру, либо один раз без размера, и
-- обе формы остаются законными. Бэкфилла нет намеренно: единственный сигнал в данных — та самая
-- эвристика по имени блока, и записать её вывод в колонку значило бы узаконить угадывание,
-- получив взамен алиби «так же в базе написано».
--
-- ИДЕМПОТЕНТНОСТЬ (CLAUDE.md): MySQL 8 автокоммитит DDL, поэтому падение в середине файла
-- оставляет схему полуприменённой без строки в gorp_migrations, и следующая загрузка перезапускает
-- файл с начала. Отсюда гард по information_schema и PREPARE/EXECUTE/DEALLOCATE — по одному
-- стейтменту на строку (иначе живой деплой падает; multiStatements в тестовом контейнере это
-- маскирует).
--
-- БЕЗОПАСНОСТЬ ПРОТИВ ПРОДА: ADD COLUMN с константным DEFAULT в MySQL 8 — операция над метаданными,
-- строки не переписываются; таблица к тому же мелкая (детали одной карточки). CHECK'ов не
-- добавляется, значит ретроактивной проверки всей истории таблицы тоже нет.

SET @col_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'tech_card_piece'
      AND COLUMN_NAME = 'ungraded'
);
SET @ddl := IF(@col_exists = 0,
    'ALTER TABLE tech_card_piece ADD COLUMN ungraded BOOLEAN NOT NULL DEFAULT FALSE COMMENT ''1 = деталь не градуируется (UNI): один и тот же контур входит в комплект КАЖДОГО размера целиком'' AFTER cut_symmetry',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down

SET @col_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'tech_card_piece'
      AND COLUMN_NAME = 'ungraded'
);
SET @ddl := IF(@col_exists > 0,
    'ALTER TABLE tech_card_piece DROP COLUMN ungraded',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
