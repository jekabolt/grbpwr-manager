-- Полоса DESIGN, волна 2, кусок 1 из 3: три места, где СЛОВА ЧЕЛОВЕКА обязаны доехать до модели и
-- остаться в истории. Ни одной новой таблицы, ни одного CHECK, ни одной копии таблицы.
--
-- ВСЕ ТРИ КОЛОНКИ ЗАКРЫВАЮТ ЗИЯНИЕ, КОТОРОЕ КОНТРАКТ УЖЕ ОБЕЩАЛ. Это не запас на будущее, а
-- дозаполнение: сегодня снапшот входов обещает то, чего в базе нет вовсе.
--   * `DesignInputRef.note` (`proto/common/common/design.proto:242`) — поле в снапшоте есть,
--     наполнить его нечем: у `design_reference` (0347) из человеческого только `role`;
--   * `DesignInputSnapshot.garment_note` (`design.proto:206`, дословно «the words that went to the
--     model») — поле есть, писателей НОЛЬ (`rg garment_note` по `*.go` не даёт ни одного попадания
--     вне `proto/gen`), потому что на карточке негде хранить эти слова.
-- Снапшот, обещающий поле, которое неоткуда взять, не «пустой» — он ЛЖИВЫЙ: история утверждает,
-- что модель ничего не читала, тогда как человек писал.
--
-- ─── 1. `design_reference.note` — «что ЭТА картинка добавляет» (W-3) ────────────────────────────
--
-- Записка живёт РЯДОМ С РОЛЬЮ, а не на `tech_card_media`, ровно по доводу шапки 0347: у строки
-- медиа тех-карты НЕТ КЛЮЧА СТРОКИ, и вся таблица переписывается целиком на каждом сейве карточки
-- (`internal/store/techcard/techcard.go:1852-1871`, `display_order` = индекс в payload). Перенести
-- сохранённый текст на пересланную строку было бы позиционным матчем — тем самым приёмом, который
-- в этом репо запрещён явно. У `design_reference` ключ честный: `(tech_card_id, media_id)`.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ РАСШИРЕНИЕ `role`. Роль отвечает на вопрос «какой стороне изделия
-- показывать эту картинку» и питает ПОРЯДОК в промпте; записка — свободный текст человека. Склейка
-- дала бы словарь, у которого половина значений — предложения.
--
-- ─── 2. `design_run.rerun_of` — что именно повторяем (W-7) ──────────────────────────────────────
--
-- Реран собирает СЕРВЕР по `rerun_of_run_id`, а не клиент своим снапшотом (решение разведки:
-- клиентский снапшот позволил бы истории утверждать входы, которых не было). Значит у строки-потомка
-- обязана быть колонка, называющая прогон-родитель, — иначе после перезагрузки экрана «повтор
-- прогона 7» неотличим от нового прогона с похожими входами.
--
-- ВНЕШНЕГО КЛЮЧА НЕТ, И ЭТО РЕШЕНО, А НЕ ЗАБЫТО. Прецедент дословный — `design_picture.derived_from`
-- (0340): самоссылка на таблице, которая САМА принимает входящий каскад от `tech_card`, —
-- единственная комбинация волны, которую нельзя доказать на бумаге, а риск 1451 приходится на
-- `DeleteTechCard`, то есть на ЕДИНСТВЕННЫЙ голый `DELETE FROM tech_card`
-- (`internal/store/techcard/techcard.go:697-733`), где человеку не покажут ничего, кроме «still
-- referenced by another record». Цена голого числа названа честно: удалённый родитель оставляет
-- потомка с номером, которого больше нет. Читатель обязан джойнить `design_run` и, не найдя строки,
-- говорить «прогон удалён», а не рисовать номер как живую ссылку.
--
-- ИНДЕКСА НА `rerun_of` ТОЖЕ НЕТ, И ЭТО ТОЖЕ РЕШЕНИЕ. Единственное названное чтение идёт от потомка
-- к родителю — по первичному ключу; обратного читателя («покажи все повторы прогона 7») в плане нет
-- ни одного. `design_run` — таблица ОЧЕРЕДИ: её UPDATE-ит claim-машина на каждой попытке, и каждый
-- лишний индекс платится на всех этих записях. Условие, при котором индекс заводить: появился
-- запрос с `WHERE rerun_of = …`. Добавление вторичного индекса на эту таблицу — INPLACE, отдельной
-- миграцией, без копии таблицы.
--
-- ТИП `INT UNSIGNED` СОГЛАСОВАН С `design_run.id` НАМЕРЕННО, хотя внешнего ключа нет: расхождение
-- знаковости однажды понадобится починить, а тогда `ADD FOREIGN KEY` ответит 3780 (0340 напоролась
-- бы на то же самое). Совпадение типа стоит ноль, несовпадение — миграцию.
--
-- ─── 3. `tech_card.garment_description` — общий коммент (W-3, центральное) ──────────────────────
--
-- Владелец сформулировал так: «пишется общий комментарий». Это слова про ИЗДЕЛИЕ, которые уходят в
-- КАЖДЫЙ прогон — флэт, рендер, 3D, — независимо от того, что сейчас лежит на доске референсов.
--
-- НА КАРТОЧКЕ УЖЕ ЧЕТЫРЕ ТЕКСТОВЫХ ПОЛЯ, И НИ ОДНО НЕ ГОДИТСЯ. Проверено поимённо, потому что
-- пятое поле «почти про то же» — это и есть ложное расщепление:
--   * `description` («short product description», 0067:46), `notes` (0067:55) и `concept` — поля
--     ДОКУМЕНТА: они печатаются на тех-карте и едут в продукт. Посадить туда промпт значит связать
--     две независимые правки намертво — редакторская правка печатного листа молча меняла бы то, что
--     читает модель, и наоборот. У `concept` вдобавок ЖИВАЯ болезнь двух писателей на одно поле
--     (два редактора на одном экране), и третий адресат сделал бы её неразрешимой;
--   * `mood_note` (0345) — слова про ДОСКУ («вот эта вайб, смотри на воротник в третьей»), а не про
--     изделие. Доска меняется от прогона к прогону, изделие — нет. Пустая доска не должна уносить
--     описание изделия, а смена описания не должна выглядеть правкой подписи к доске.
-- Общий признак четырёх соседей: у каждого свой АДРЕСАТ. Пятый адресат — модель — не выражается ни
-- одним из них, и это отличает настоящую вторую ось от расщепления.
--
-- ПРОТОКОЛ VERBATIM «absent = сохранить», тот же, что у `mood_note` (0345) и `cutting_coefficient`:
-- вкладка со старым бандлом, не знающая поля, НЕ ДОЛЖНА его стирать. Колонка этого не обеспечивает
-- — обеспечивает хендлер; здесь это записано, чтобы следующий читатель не принял NULL за «человек
-- очистил».
--
-- ─── ЦЕНА И БЕЗОПАСНОСТЬ ───────────────────────────────────────────────────────────────────────
--
-- Все три — `ADD COLUMN` уровня INSTANT (nullable, без DEFAULT-значения строкового типа, в конец
-- таблицы): ни одной копии таблицы, пятиминутный потолок ВСЕГО прогона миграций
-- (`internal/store/store.go:236`) не задевается. Две из трёх таблиц (`design_reference`,
-- `design_run`) на проде вообще отсутствуют — прод стоит на 0339.
--
-- НИ ОДНОГО `ADD CONSTRAINT … CHECK` — намеренно, по общему правилу полосы: в MySQL он копирует
-- таблицу целиком и проверяет ВСЮ историю, а лимит прогона захардкожен.
--
-- ОКНО «СТАРЫЙ БИНАРЬ × НОВАЯ СХЕМА» БЕЗОПАСНО, и это проверяемое утверждение, а не надежда: хендл
-- стора — `d.Unsafe()` (`internal/store/store.go:252,397`), поэтому лишняя колонка в `SELECT *`
-- молча игнорируется сканером, а не роняет чтение (сравни с 0323, где `storeutil` сканировал БЕЗ
-- Unsafe и окно стоило 500-ок). Обратная сторона названа вслух: до появления полей в
-- `entity.DesignReference` / `entity.DesignRun` / `entity.TechCard` колонки читаются как нули МОЛЧА.
-- Откат бинаря после этой миграции безопасен: старый стор эти колонки не именует нигде.
--
-- ИДЕМПОТЕНТНОСТЬ: MySQL авто-коммитит DDL пооператорно, поэтому падение посреди файла оставляет
-- схему полуприменённой БЕЗ строки в `gorp_migrations`, и следующий старт прогонит файл с начала.
-- `ADD COLUMN IF NOT EXISTS` в MySQL не существует, поэтому каждый ALTER стоит под собственным
-- гейтом по `information_schema.COLUMNS`. `PREPARE` / `EXECUTE` / `DEALLOCATE` — КАЖДЫЙ СВОЕЙ
-- СТРОКОЙ: прод ходит БЕЗ `multiStatements`, драйвер выполняет по одному запросу, и склеенные в одну
-- строку операторы падают ТОЛЬКО на проде — контейнерный тест эту поломку маскирует.

-- +migrate Up

-- 1. Записка референса.
SET @dr_note := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_reference'
      AND COLUMN_NAME = 'note');
SET @ddl := IF(@dr_note = 0,
    'ALTER TABLE design_reference
        ADD COLUMN note TEXT NULL COMMENT ''что ЭТА картинка добавляет; свободный текст человека, уезжает в DesignInputRef.note снапшота''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- 2. Родитель рерана. Тип согласован с design_run.id (INT UNSIGNED); внешнего ключа нет — см. шапку.
SET @drun_rerun := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_run'
      AND COLUMN_NAME = 'rerun_of');
SET @ddl := IF(@drun_rerun = 0,
    'ALTER TABLE design_run
        ADD COLUMN rerun_of INT UNSIGNED NULL COMMENT ''прогон, который повторяем; FK НЕТ намеренно (прецедент design_picture.derived_from, 0340) — читатель джойнит design_run и на пустоту говорит «прогон удалён»''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- 3. Общее описание изделия. ЖИВАЯ ПРОД-ТАБЛИЦА: nullable TEXT в конец — INSTANT, копии нет.
SET @tc_garment := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tech_card'
      AND COLUMN_NAME = 'garment_description');
SET @ddl := IF(@tc_garment = 0,
    'ALTER TABLE tech_card
        ADD COLUMN garment_description TEXT NULL COMMENT ''общий коммент про ИЗДЕЛИЕ, уходит в КАЖДЫЙ прогон (DesignInputSnapshot.garment_note); не mood_note (та про доску) и не concept/description (те про документ). Verbatim-протокол: отсутствие поля в payload = сохранить прежнее''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down
--
-- Порядок обратный Up, гейты симметричные: падение посреди отката оставляет состояние, с которого
-- повтор продолжает. Откат ТЕРЯЕТ ТЕКСТ — другого честного поведения у DROP COLUMN нет; поэтому
-- Down здесь путь разработчика, а не сценарий прода (на проде и бете миграции идут только вверх).
-- Ни один индекс не задет: ни одна из трёх колонок ни в одном ключе не состоит.

SET @tc_garment_down := (SELECT COUNT(*) FROM information_schema.COLUMNS
