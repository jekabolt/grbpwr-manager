    'ALTER TABLE tech_card DROP COLUMN garment_description',
    'SELECT 1');
PREPARE stmt FROM @ddl_down;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

SET @drun_rerun_down := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_run'
      AND COLUMN_NAME = 'rerun_of');
SET @ddl_down := IF(@drun_rerun_down = 1,
    'ALTER TABLE design_run DROP COLUMN rerun_of',
    'SELECT 1');
PREPARE stmt FROM @ddl_down;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

SET @dr_note_down := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_reference'
      AND COLUMN_NAME = 'note');
SET @ddl_down := IF(@dr_note_down = 1,
    'ALTER TABLE design_reference DROP COLUMN note',
