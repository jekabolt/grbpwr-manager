-- РАСХОД ПО ПЛОЩАДИ (Ф2.4). Ф2 (0273) сделала маркер СОСТАВОМ и честно отказалась выдавать
-- скалярный расход на изделие для смешанного настила: used_length_cm / total_units — это СРЕДНЕЕ по
-- составу, оно завышает мелкие размеры и занижает крупные ровно на тот перекос, ради устранения
-- которого состав и заводился. Эта миграция кладёт основание, на котором отказ снимается по-честному:
-- у каждого размера появляется СВОЙ расход.
--
-- ФОРМУЛА (03-composition.md, «Размеры, которых нет в составе нормы»):
--
--     расход(размер) = площадь его деталей × (длина настила / суммарная площадь состава)
--
-- В обозначениях строки: a_s = area_per_garment_cm2, q_s = quantity, L = used_length_cm,
-- A = SUM(q_s × a_s), расход(s) = a_s × L / A. Сходимость — тождество, а не пожелание:
-- SUM(q_s × расход(s)) = L. Это и есть критерий приёмки фазы.
--
-- ПОЧЕМУ ХРАНИТСЯ ПЛОЩАДЬ, А НЕ РАСХОД. Расход — ПРОИЗВОДНОЕ от used_length_cm, а производное,
-- записанное в колонку, расходится со своими входами в тот день, когда один из них поправят: ровно
-- поэтому consumption_per_unit_cm никогда не был колонкой и вычисляется на чтении. Площадь ничего не
-- производит — это ИЗМЕРЕНИЕ геометрии, того же класса, что used_length_cm, placed_count и
-- efficiency_pct, которые эта же строка уже снимает с того же блоба.
--
-- ПОЧЕМУ ЭТО ВООБЩЕ КОЛОНКА, А НЕ ЧТЕНИЕ БЛОБА. Список раскладок карточки ездит БЕЗ блоба (60-100 КБ
-- на маркер, комментарий к entity.TechCardMarkerSummary), а применяет норму в рецепт именно экран,
-- который держит этот список. Считать пер-размерный расход только там, где блоб есть
-- (GetTechCardMarker), значит завести поле, чьё значение зависит от того, каким RPC спросили, —
-- ошибка, которую store/techcard/markers.go уже называет вслух на piece_set_status. Таблица
-- tech_card_marker_size существует ровно для этого: она ПРОЕКЦИЯ блоба для читателей без блоба.
--
-- ПОЧЕМУ NULLABLE. Три законных источника NULL, и ни один не ошибка: маркеры, снятые до Ф2.4
-- (площади им никто не писал); блоб, в деталях которого нет пригодной площади; и окно выкатки, где
-- старый контейнер ещё пишет INSERT без этой колонки. NULL читается как «площади не записаны» —
-- пер-размерный расход тогда НЕ выдаётся, и отказ рядом объясняет, что делать. Подстановка среднего
-- на этом месте вернула бы ровно тот дефект, который Ф2.4 убирает, только молча.
--
-- ПОЧЕМУ DECIMAL(14,2), А НЕ DOUBLE. Площадь приезжает из движка как float64, но живёт рядом с
-- деньгами и с длиной, и весь этот стор считает такое в decimal. Масштаб 2 (сотые см²) избыточен для
-- цифры порядка десятков тысяч см²; на сходимость округление входа не влияет вовсе — одно и то же
-- a_s стоит и в числителе, и внутри общего знаменателя.
--
-- ИДЕМПОТЕНТНОСТЬ (CLAUDE.md): DDL в MySQL 8 автокоммитится, поэтому падение в середине файла
-- оставляет схему полуприменённой без строки в gorp_migrations и следующая загрузка перезапускает
-- файл с начала. Каждый шаг под своей проверкой в information_schema, PREPARE/EXECUTE/DEALLOCATE по
-- одному оператору на строку (иначе multiStatements=true в контейнерных тестах замаскировал бы баг,
-- который прод не переживёт).

-- 1. Площадь одного изделия этого размера, см². «На изделие», а не «на все изделия размера»: это
--    базис ПЕР-РАЗМЕРНОЙ нормы, и умножение на quantity делает читатель, собирая знаменатель.
SET @col_exists := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tech_card_marker_size'
      AND COLUMN_NAME = 'area_per_garment_cm2');
SET @ddl := IF(@col_exists = 0,
    'ALTER TABLE tech_card_marker_size ADD COLUMN area_per_garment_cm2 DECIMAL(14,2) NULL COMMENT ''площадь деталей ОДНОГО изделия этого размера, см² (градуированные детали размера + полный набор безразмерных); NULL = не записано, пер-размерный расход не выдаётся''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- 2. Отрицательная площадь невыразима физически и сломала бы распределение молча (уменьшила бы
--    знаменатель и завысила бы норму всем остальным размерам). Ноль запрещён по той же причине:
--    «деталь без протяжённости» — это разбор, из которого ничего выводить нельзя, и такой размер
--    обязан остаться NULL, а не притвориться измеренным. Имя явное — домовое правило запрещает
--    авто-именованные <table>_chk_N.
SET @chk_exists := (SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tech_card_marker_size'
      AND CONSTRAINT_NAME = 'chk_tcms_area_pos');
SET @ddl := IF(@chk_exists = 0,
    'ALTER TABLE tech_card_marker_size ADD CONSTRAINT chk_tcms_area_pos CHECK (area_per_garment_cm2 IS NULL OR area_per_garment_cm2 > 0)',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- БЭКФИЛЛА НЕТ, И ЭТО РЕШЕНИЕ, А НЕ ЗАБЫВЧИВОСТЬ. Площадь деталей по размерам лежит только в блобе
-- раскладки, а стор блоб не разбирает (0257/0268: геометрия непрозрачна для хранения, и второй
-- разборщик здесь стал бы вторым определением формата). Снять её SQL-ом нечем — JSON_TABLE по
-- layout.pieces с суммой по size_id воспроизвёл бы формулу экземпляров в диалекте, где её никто не
-- тестирует. Существующие маркеры остаются с NULL и без пер-размерной нормы, пока их не пересохранят
-- из модалки; отказ на них называет именно это. Молчаливо посчитать им среднее — единственный
-- вариант, который здесь недопустим.

