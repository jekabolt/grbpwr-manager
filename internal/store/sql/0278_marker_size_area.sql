-- Откат безопасен и не требует гварда: колонка ничего не порождает, кроме производной цифры на
-- проводе. Её исчезновение читается как «площади не записаны» — то самое состояние, в котором
-- находятся все маркеры до Ф2.4, и пер-размерный расход просто перестаёт выдаваться. Ни одна
-- сохранённая величина при этом не теряется: длина настила, состав и total_units на месте, а площадь
-- восстанавливается пересохранением раскладки из того же блоба.
SET @chk_exists := (SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tech_card_marker_size'
      AND CONSTRAINT_NAME = 'chk_tcms_area_pos');
SET @ddl := IF(@chk_exists > 0,
    'ALTER TABLE tech_card_marker_size DROP CHECK chk_tcms_area_pos',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

SET @col_exists := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tech_card_marker_size'
      AND COLUMN_NAME = 'area_per_garment_cm2');
SET @ddl := IF(@col_exists > 0,
    'ALTER TABLE tech_card_marker_size DROP COLUMN area_per_garment_cm2',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
