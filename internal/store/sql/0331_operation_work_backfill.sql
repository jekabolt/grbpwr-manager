-- назначения. Guard-тест (internal/store/migrationlint/operation_work_backfill_test.go) читает
-- ТЕКСТ этого файла и краснеет на любой попытке дописать универсальную машинку в вайтлист.
--
-- ЗАМЕР ПРОДА 2026-08-22 (только чтение), от которого считан вайтлист. Он же — причина, по которой
-- вайтлист УЖЕ вайтлиста, чем ожидал план фазы:
--
--   всего 126 операций на 7 карточках; пары (глагол, машинка):
--     machine + lockstitch 100 · press 11 · press_open 5 · machine + button_attach 3 ·
--     machine + buttonhole 3 · machine + overlock 2 · machine + embroidery 1 · machine + zigzag 1
--   ВТО по под-глаголу:
--     press БЕЗ приёма 8 · press_open 5 · press + press_flat 3
--
-- То есть ВОСЕМЬ из одиннадцати ВТО-строк приёма не несут ВОВСЕ, и «press с приёмом» — не основная
-- масса, а три строки. Приём не записан — работа не выводится: честное «action not recorded» уже
-- стоит на экране, и подменять его догадкой нельзя.
--
-- ИТОГО РАЗМЕЧАЕТСЯ 15 СТРОК ИЗ 126: 5 разутюжек + 3 приутюживания + 3 петли + 3 пуговицы +
-- 1 вышивка. Остальные 111 — человеку.
--
-- ⚠️ БЭКФИЛЛ ОТБИРАЕТ СТРОКИ УСЛОВИЕМ, А НЕ СПИСКОМ id, И ЭТО НЕ СТИЛЬ. База растёт под руками:
-- 99 → 105 → 115 → 126 операций за считанные дни. Список id, снятый вчера, разметил бы вчерашние
-- строки и молча прошёл мимо сегодняшних; условие размечает всё, что подходит, в момент прогона.
-- Числа выше — ожидание для сверки после прогона (замер №0b дня выкатки), а не источник отбора.
--
-- НИ ОДНА СТРОКА НЕ ТЕРЯЕТСЯ И НИ ОДНО ЗАПОЛНЕННОЕ ЗНАЧЕНИЕ НЕ ПЕРЕЗАПИСЫВАЕТСЯ. Все пять UPDATE'ов
-- несут `work IS NULL`: они умеют ровно один переход, NULL → токен. Ограничение владельца
-- («сломаться можно, исчезнуть нельзя») выполняется по построению, а не по обещанию.
--
-- КОГЕРЕНТНОСТЬ 0330 ВЫПОЛНЕНА ПО ПОСТРОЕНИЮ. Правило 3 требует «глагол шага = глагол работы»:
-- у каждого UPDATE'а глагол стоит в условии и равен глаголу присваиваемой работы. Правило 4
-- (машинка из списка работы) касается только режима ask — среди присваиваемых работ таких нет, но
-- машинка в условии всё равно совпадает с машинкой работы. Guard-тест проверяет оба соответствия
-- по тексту, а не по памяти: строка, которую бэкфилл сделал бы несохраняемой, — это карточка,
-- которую владелец не сможет открыть и починить.
--
-- ОТПЕЧАТОК. У пятнадцати размеченных строк рождается двенадцатый хвост проекции ("work"), то есть
-- их подпись МЕНЯЕТСЯ — это цена разметки, и она заплачена осознанно. Подписей (tech_card_signoff)
-- на обеих базах НОЛЬ, так что протухать нечему. Релизы (замер №16, 2026-08-22): на бете ДВА
-- релизных снапшота, карточки 16 и 39, и строк вайтлиста в них НЕТ; на проде релизов НОЛЬ. Релиз —
-- замороженный protojson-блоб, он не пересчитывается и не ломается, так что сегодня живой отпечаток
-- ни одного релиза не разойдётся. ОГОВОРКА НА СЛУЧАЙ, ЕСЛИ ДАННЫЕ ИЗМЕНЯТСЯ ДО ВЫКАТКИ: появись в
-- релизной карточке строка вайтлиста — бэкфилл её разметит, и это осознанно, а не упущение (условие
-- отбора релиза не видит; исключение спрятало бы строку от разметки навсегда, а запрет редактировать
-- released — правило API про руки человека, не про миграцию данных). Живой отпечаток CONSTRUCTION
-- такой карточки разойдётся с блобом, и ловит это смоук «сравнение релиза с живой карточкой» в день
-- выкатки (R9-п.4ж) вместе с повтором замера №0b/№16.
--
-- ИДЕМПОТЕНТНОСТЬ. MySQL 8 автокоммитит DDL, и хотя DDL здесь нет вовсе, правило то же: падение в
-- середине файла оставляет часть операторов применёнными БЕЗ строки в gorp_migrations, и следующий
-- старт перечитывает файл С ВЕРХА. Поэтому вставки идут с `ON DUPLICATE KEY UPDATE <ключ> = <ключ>`
-- (повтор = ноль изменённых строк), снятие — с `WHERE retired_at IS NULL`, переименование — с
-- проверкой СТАРОГО ярлыка в условии (повтор не тронет ярлык, который человек успел поправить
-- своей рукой), бэкфилл — с `WHERE work IS NULL`. INSERT IGNORE не используется намеренно: он
-- проглотил бы и нарушение внешнего ключа, то есть синоним с опечаткой в токене исчез бы молча.
--
-- ПУСТЫЕ СТРОКИ ЭТОЙ ШАПКИ — «-- » С ПРОБЕЛОМ, А НЕ ГОЛОЕ «--»: sqlparse считает строку
-- комментарием только с пробелом после дефисов, а голое «--» попадает в буфер оператора и живёт
-- там до ближайшего «;» (инцидент 2026-08-16, когда из 0306 убрали последний оператор Up).
