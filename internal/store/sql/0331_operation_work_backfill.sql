--   5. ТОЧЕЧНЫЙ БЭКФИЛЛ пятнадцати строк, у которых работа следует из записи ОДНОЗНАЧНО.
--
-- ⚠️ ОТМЫВАНИЕ СВАЛКИ ЗАПРЕЩЕНО, И ЗАПРЕТ МЕХАНИЧЕСКИЙ. Сто строк прода `machine + lockstitch`,
