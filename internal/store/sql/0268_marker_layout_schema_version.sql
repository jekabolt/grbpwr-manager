-- +migrate Up

-- ВЕРСИЯ ФОРМАТА РАСКЛАДКИ СТАНОВИТСЯ ХРАНИМЫМ ФАКТОМ, А НЕ ПОЛЕМ ПЭЙЛОАДА.
--
-- ЗАЧЕМ. Ф1 запрещает класть деталь вверх ногами (180° или зеркало) на направленную ткань, но
-- освобождает от этого запрета СТАРЫЕ маркеры: ручной редактор сохранял фактический поворот детали
-- даже вне политики, поэтому 90° при allow_cross_grain=false лежит в базе, и 180° вместе с ним.
-- Судить такую раскладку новым правилом значит перечеркнуть измерение, которое нельзя переснять без
-- повторного прогона движка.
--
-- Первая реализация брала версию ИЗ ПРИСЛАННОГО БЛОБА — то есть освобождение выдавалось по полю,
-- которое пишет клиент. Зеркало подделать нельзя (поля не существовало до 3), а 180° выразим в любой
-- версии, значит «объяви schema_version 1» было рабочим способом обойти запрет ровно для той
-- геометрии, ради которой запрет и заводился. Проверено на контейнере: новый маркер со 180° на
-- one_way сохранялся, стоило заявить единицу. Гейт, обходимый меньшим числом, — не гейт.
--
-- Поэтому версия переезжает в колонку: её пишет сервер при сохранении, и вызывающий подделать её не
-- может. Освобождение теперь выдаётся по СТРОКЕ, которая уже лежит в базе; у нового маркера
-- (id = 0) истории нет и освобождения нет.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ РАЗБОР БЛОБА. Стор блоб не парсит принципиально (идиома 0257: геометрия
-- ездит непрозрачной), и это не стилистика — путь чтения СОЗНАТЕЛЬНО переживает нечитаемый блоб
-- (GetTechCardMarker отдаёт сводку и предупреждение). JSON_EXTRACT в запросе сохранения уронил бы
-- сохранение на той самой строке, которую чтение умеет пережить, и уронил бы её ошибкой 3141 про
-- невалидный JSON — про которую оператору нечего сделать.
--
-- ПОЧЕМУ БЭКФИЛЛ РАВЕН 1 И ПОЧЕМУ ЭТО ДОКАЗУЕМО. Схему 3 умеет принимать только код Ф1, а миграции
-- на обоих окружениях применяются на старте ДО того, как процесс начинает обслуживать запросы.
-- Значит в момент этой миграции ни одной строки версии 3 существовать не может: всё, что лежит в
-- таблице, — это 1 или 2, и обе меньше 3. Для правила разница между ними не значит ничего (обе дают
-- освобождение), поэтому точное значение старых строк выяснять не нужно — и не нужно ради этого
-- парсить JSON в миграции, где невалидный блоб точно так же остановил бы деплой.
--
-- ИДЕМПОТЕНТНОСТЬ (CLAUDE.md): MySQL 8 автокоммитит DDL, поэтому падение в середине файла оставляет
-- схему полуприменённой без строки в gorp_migrations, и следующая загрузка перезапускает файл с
-- начала. Шаг один, под своей проверкой в information_schema, PREPARE/EXECUTE/DEALLOCATE по строке.

SET @col_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'tech_card_marker'
      AND COLUMN_NAME = 'layout_schema_version'
);
SET @ddl := IF(@col_exists = 0,
    'ALTER TABLE tech_card_marker ADD COLUMN layout_schema_version SMALLINT UNSIGNED NOT NULL DEFAULT 1 COMMENT ''версия формата блоба layout, пишется сервером; освобождение от политики переворота выдаётся ТОЛЬКО по этому значению (Ф1)'' AFTER layout',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down

SET @col_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'tech_card_marker'
      AND COLUMN_NAME = 'layout_schema_version'
);
SET @ddl := IF(@col_exists > 0,
    'ALTER TABLE tech_card_marker DROP COLUMN layout_schema_version',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
