-- ПОКОЛЕНИЕ ПОЛИТИКИ, ПОД КОТОРЫМ ГЕОМЕТРИЮ СТРОКИ УЖЕ СУДИЛИ. Не версия байтов в layout.
--
-- ЗАЧЕМ. Ф1 запрещает класть деталь вверх ногами (180° или зеркало) на направленную ткань, но
-- освобождает от запрета СТАРЫЕ маркеры: ручной редактор сохранял фактический поворот детали даже
-- вне политики, поэтому 90° при allow_cross_grain=false лежит в базе, и 180° вместе с ним. Судить
-- такую раскладку новым правилом значит перечеркнуть измерение, которое нельзя переснять без
-- повторного прогона движка.
--
-- ПОЧЕМУ НЕ ВЕРСИЯ ИЗ БЛОБА. Первая попытка брала версию из присланного блоба — то есть выдавала
-- освобождение по полю, которое пишет клиент. Зеркало подделать нельзя (поля не существовало до 3),
-- а 180° выразим в любой версии, значит «объяви schema_version 1» обходило запрет ровно для той
-- геометрии, ради которой он и заводился. Вторая попытка перенесла значение в эту колонку, но
-- продолжала писать в неё то же число из пэйлоада — и дыра просто переехала на один запрос вперёд:
-- создай маркер без поворотов, объявив 1 (принимается — отвергать нечего), затем обнови его со 180°,
-- и хранимая единица покупает освобождение. В окне между деплоем бэка и деплоем клиента то же самое
-- делала двойка, которую шлёт текущий клиент.
--
-- ПОЭТОМУ ЗНАЧЕНИЕ ПИШЕТ СЕРВЕР И ТОЛЬКО СВОЕЙ КОНСТАНТОЙ. Вставка ставит текущее поколение; правка
-- ставит текущее поколение, ЕСЛИ сохранение не воспользовалось освобождением, и не трогает колонку,
-- если воспользовалось (иначе пропуск был бы одноразовым: строку клеймила бы та самая правка, ради
-- которой пропуск и выдан, и второе переименование легаси-раскладки отвергалось бы навсегда).
-- Храповик крутится в одну сторону и крутится почти для всех: легаси-строка с чистой геометрией
-- теряет пропуск при первом же сохранении, пропуск остаётся только у тех, кто реально несёт
-- запрещённую геометрию.
--
-- ЧТО ЭТО ЗНАЧИТ ДЛЯ ЧТЕНИЯ: ничего. Колонку не парсит никто, читатели ветвятся по ПОЛЮ в блобе
-- (домашнее правило), поэтому блоб версии 3 за хранимой единицей читается ровно так же.
--
-- ПОЧЕМУ БЭКФИЛЛ РАВЕН 1 И ПОЧЕМУ ЭТО ДОКАЗУЕМО. Всё, что лежит в таблице на момент миграции,
-- написано кодом ДО Ф1: миграции применяются на старте до обслуживания запросов, а судить геометрию
-- по направлению ткани до Ф1 было некому. Значит ни одна существующая строка под текущим поколением
-- не судилась, и 1 — честное значение «досудебное»; отличать 1 от 2 правилу незачем.
--
-- ИДЕМПОТЕНТНОСТЬ (CLAUDE.md): MySQL 8 автокоммитит DDL, поэтому падение в середине файла оставляет
-- схему полуприменённой без строки в gorp_migrations, и следующая загрузка перезапускает файл с
-- начала. Шаг один, под своей проверкой в information_schema, PREPARE/EXECUTE/DEALLOCATE по строке.

SET @col_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'tech_card_marker'
      AND COLUMN_NAME = 'layout_schema_version'
);
SET @ddl := IF(@col_exists = 0,
    'ALTER TABLE tech_card_marker ADD COLUMN layout_schema_version SMALLINT UNSIGNED NOT NULL DEFAULT 1 COMMENT ''поколение политики, под которым геометрию этой строки уже судили (не версия блоба): 1 = до Ф1, 3 = судили по Ф1. Пишет только сервер; освобождение от запрета переворота выдаётся ТОЛЬКО по этому значению'' AFTER layout',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

