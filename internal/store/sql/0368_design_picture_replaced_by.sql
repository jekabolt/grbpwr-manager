-- Полоса DESIGN, воркбенч FLAT (O-53) — «ПЕРЕЗАПИСАТЬ ИЛИ СОХРАНИТЬ КАК НОВУЮ».
--
-- Владелец: после правки в воркбенче последней генерации спрашивать «overwrite или save as new».
--
-- ЧТО ЗНАЧИТ «ПЕРЕЗАПИСАТЬ», И ЧЕГО ОНО НЕ ЗНАЧИТ. Пиксели оригинала НЕ подменяются, и оригинал НЕ
-- прячется. Подмена медиа на месте фальсифицировала бы оплаченный прогон: кропы (derived_from)
-- указали бы на чужие пиксели, реплей отдал бы подделку, роли референсов по медиа молча поменяли бы
-- промпт. Прятанье упёрлось бы в сторожей HidePicture (in_slot, live_crop_parent) и воскресило бы
-- скрытие по картинке, снятое T-14. Перезапись — это ТОТ ЖЕ флэттен (FlattenDesignEditLayer с
-- replace_picture_id): правка файлится сиблингом под той же строкой прогона, а в той же транзакции
-- слот верстака, где стоял оригинал, переезжает на правку (slot_rev + 1, через setBenchSlotTx со
-- всеми сторожами постановки) и оригинал получает replaced_by = id правки.
--
-- ЧТО ЭТО ЗА КОЛОНКА. Указатель ВПЕРЁД по цепочке замен: у оригинала — id правки, занявшей его
-- место. Правку можно перезаписать в свою очередь, и ГОЛОВА цепочки — кадр с NULL. Все звенья лежат
-- под одной строкой прогона (или пачки) — флэттен наследует run_id и batch_id родителя, — поэтому
-- цепочка целиком приезжает в одной строке полосы. Писатель ровно один (layer.go, FlattenEditLayer),
-- и пишет он ОДИН РАЗ: `replaced_by IS NULL` стоит в WHERE самого UPDATE вторым поясом к чтению в
-- той же SERIALIZABLE-транзакции, и слепой повтор перезаписи получает already_replaced. Очищающего
-- глагола нет — восстановления заменённого в v1 нет, его можно заново поставить в слот.
--
-- INT UNSIGNED — ТОТ ЖЕ ТИП, ЧТО У design_picture.id И derived_from: колонка называет строку этой же
-- таблицы, и знаковость у имени строки одна.
--
-- FK НЕТ НАМЕРЕННО — по доводу derived_from (0340, FK-ПОЛИТИКА): самоссылка на таблице, которая
-- сама принимает входящий каскад удаления карточки, — комбинация, которую нельзя доказать на бумаге,
-- и выигрыш от FK меньше риска 1451 в DeleteTechCard. Целостность держит Go. CHECK нет по общему
-- правилу волны (ретроактивный ADD CONSTRAINT CHECK копирует таблицу целиком и упирается в
-- пятиминутный потолок старта). ИНДЕКСА НЕТ: ни один запрос не ищет ПО replaced_by — колонка
-- читается у строк, уже найденных по id или по derived_from.
--
-- ЦЕНА. ADD COLUMN ... NULL в КОНЕЦ таблицы — INSTANT (MySQL 8.0.12+), строки не переписываются.
-- Бэкфилла нет — до этой миграции заменить кадр было нечем, и NULL у всех есть правда.
--
-- ОКНО «СТАРЫЙ БИНАРЬ × НОВАЯ СХЕМА» БЕЗОПАСНО: хендл стора — `d.Unsafe()` (store.go), лишняя
-- колонка в SELECT * читается в никуда, а INSERT'ы старого бинаря её не называют и оставляют NULL.

-- +migrate Up

SET @dp_replaced_by := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_picture'
      AND COLUMN_NAME = 'replaced_by');
SET @ddl := IF(@dp_replaced_by = 0,
    'ALTER TABLE design_picture
        ADD COLUMN replaced_by INT UNSIGNED NULL
            COMMENT ''id правки, занявшей место этого кадра (O-53, overwrite) — указатель вперёд по цепочке замен, голова цепочки = NULL. Пиксели, кропы и видимость кадра не тронуты, на правку переехал только слот. Пишется один раз (WHERE replaced_by IS NULL), FK нет по доводу derived_from''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down
--
-- Откат теряет указатели замен, и это осознанно. Слоты при этом уже стоят на правках — это обычные
-- плиты, и прежний бинарь читает их как есть; заменённые оригиналы становятся обычными кадрами
-- истории, ровно тем, чем они и были для бинаря, не знающего замены.

SET @dp_replaced_by_down := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_picture'
      AND COLUMN_NAME = 'replaced_by');
SET @ddl := IF(@dp_replaced_by_down = 1,
    'ALTER TABLE design_picture DROP COLUMN replaced_by',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
