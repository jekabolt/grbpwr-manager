-- Операционные картинки с выносками: у шага появляются свои фотографии, а на них — указания.
--
-- Выноска отвечает швее на два вопроса, которые не помещаются в текст шага: ЧТО тут делать и ПО
-- КАКОМУ РАЗМЕРУ. До сих пор такие указания жили только на КАРТОЧНОМ эскизе (tech_card_callout),
-- а шаг ссылался на них номером. Номер позиционный, пересортировка шагов рвёт ссылку, и
-- «callout_number = 0» неотличим от «не привязано» — ловушка, известная по своим последствиям.
-- Здесь картинка принадлежит ШАГУ, и невалидная ссылка становится невыразимой: нет номера — нет
-- и чего рвать.
--
-- ПОЧЕМУ ВЫНОСКИ JSON-КОЛОНКОЙ, А НЕ ТРЕТЬЕЙ ТАБЛИЦЕЙ. У выноски нет внешних ссылок: она читается
-- и пишется только целиком со своей картинкой. Отдельные строки дали бы на неё сослаться — ровно
-- то, из-за чего эта фича и переехала в шаг. Форму JSON проверяет Go рядом с читаемым сообщением,
-- до стора; SQL-CHECK стрелял бы сырым 3819 и называл не ту колонку (довод шапки 0289).
--
-- FK НА МЕДИА — CASCADE, А НЕ SET NULL. Операционная картинка без картинки не значит ничего: у
-- карточной выноски текст живёт и без пина, здесь же весь смысл строки — снимок и указания
-- поверх него. Удалили медиа — строка уходит вместе с ним.
--
-- ЭТА МИГРАЦИЯ ИНЕРТНА для существующих карточек: таблица пустая, ни одна старая карточка её не
-- читает и не пишет. Окно «схема новая, стор старый» безопасно — полная замена операций сносит
-- строки каскадом через fk_op_media_operation, как сносит все прочие связи шага.

-- +migrate Up

CREATE TABLE IF NOT EXISTS tech_card_operation_media (
  id INT AUTO_INCREMENT PRIMARY KEY,
  tech_card_operation_id INT NOT NULL,
  media_id INT NOT NULL,
  caption VARCHAR(255) NULL,
  -- Позиция в филмстрипе и на печати. Уникален внутри шага: два снимка на одном месте — это
  -- неоднозначный порядок показа, который база обязана запретить, а не Go пообещать.
  display_order INT NOT NULL DEFAULT 0,
  -- Выноски одной картинки. NOT NULL: «нет выносок» это пустой массив, а не отсутствие поля —
  -- различать их было бы различением без разницы.
  annotations JSON NOT NULL,
  CONSTRAINT fk_op_media_operation FOREIGN KEY (tech_card_operation_id)
    REFERENCES tech_card_operation (id) ON DELETE CASCADE,
  CONSTRAINT fk_op_media_media FOREIGN KEY (media_id)
    REFERENCES media (id) ON DELETE CASCADE,
  CONSTRAINT uq_op_media_order UNIQUE (tech_card_operation_id, display_order)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

