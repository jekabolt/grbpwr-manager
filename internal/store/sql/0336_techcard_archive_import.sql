-- +migrate Up

-- ПРИЁМНАЯ ЗАГРУЖЕННОГО АРХИВА + ОТПЕЧАТОК СОДЕРЖИМОГО МЕДИА. Это ЕДИНСТВЕННАЯ миграция фичи
-- «экспорт/импорт тех-карты ZIP-архивом»: всё, что фича хочет от схемы, едет одним файлом, и
-- второго файла не будет. Любой поздний аппетит до схемы обязан прийти к координатору, а не
-- завести себе 0337 в своей ветке: номер, взятый параллельно, — это ровно тот дубль, который потом
-- приходится узаконивать навсегда (knownDuplicateMigrationNumbers: 0003, 0195, 0278 — переименовать
-- уже применённый файл нельзя, sql-migrate держит Id = ИМЯ ФАЙЛА).
--
-- ==== 1. tech_card_import ====
--
-- ИМПОРТ — ДВА ВЫЗОВА, А НЕ ОДИН, и между ними обязано где-то жить состояние. Сначала архив
-- кладётся в бакет и разбирается: что в нём есть, чего не хватает, во что упрётся создание
-- карточки. Потом человек читает отчёт и ЛИБО подтверждает, ЛИБО уходит. Держать разобранный
-- манифест в памяти процесса нельзя: инстансов несколько, они перезапускаются, и «подтвердить»
-- законно приходит на другой — состояние в памяти означало бы «загрузите архив ещё раз», причём
-- непредсказуемо и только под нагрузкой.
--
-- tech_card_id ЗАПОЛНЯЕТСЯ НА КОММИТЕ, поэтому до него NULL, и это не «ещё не проставили», а
-- утверждение: «карточки из этого архива пока не существует». ON DELETE SET NULL, а не CASCADE:
-- строка переживает удаление карточки НАМЕРЕННО — она ещё и журнал («карточка приехала архивом
-- такого-то числа, вот отчёт с дырами»), и удалять журнал вместе с предметом значит терять
-- единственный ответ на вопрос «почему в карточке пусто».
--
-- ТРИ JSON-КОЛОНКИ — ТРИ РАЗНЫХ МОМЕНТА, и они не сливаются в одну:
--   * archive_manifest  — что было в ZIP на загрузке (NOT NULL: строки без манифеста не бывает);
--   * colorways_payload — тело colorways.json, которое читает отдельный поздний шаг (NULL, когда
--                         колорвеев в архиве нет вовсе);
--   * report            — итог коммита с дырами (NULL до коммита).
-- JSON-колонке в MySQL нельзя дать простой DEFAULT, поэтому NOT NULL здесь означает ровно
-- «писатель обязан прислать» — то, что и требуется.
--
-- CHECK НА status НЕ ДОБАВЛЯЕТСЯ, и это осознанный отказ, а не забывчивость. Довод тот же, что в
-- шапках 0333/0334: словарный CHECK стоит КОПИИ таблицы при каждом будущем расширении (правило
-- «ADD CHECK = COPY»), а выстреливает сырым MySQL 3819 из середины UPDATE'а, который правит совсем
-- другое поле. Набор значений (uploaded|committed|failed|expired) держит Go — единственный писатель
-- этой таблицы: сюда не ходит ни импорт данных, ни ручные правки, ни бэкфилл.
--
-- ==== 2. media.content_hash ====
--
-- ЗАЧЕМ. Импорт кладёт файлы архива в бакет и обязан отвечать на вопрос «этот файл у нас уже
-- есть?» — иначе повторный импорт той же карточки плодит копии одного и того же JPEG'а. Ответить
-- по URL нельзя (URL наш, у пришедшего архива он чужой), по имени файла — тем более (имя файла API
-- медиа вообще не хранит). Отвечает отпечаток СОДЕРЖИМОГО.
--
-- CHAR(64) = hex SHA-256; NULL = «не считан». И NULL здесь читается как «не знаем», а не как
-- «уникальный»: медиа, залитое до этой миграции, хеша не имеет и обязано считаться НЕ совпадающим
-- ни с чем — сравнение с NULL в SQL и так не даёт истины, что для дедупликации ровно правильно.
--
-- БЭКФИЛЛА НЕТ, и это не «на потом»: посчитать хеш существующих медиа = скачать весь бакет, а это
-- работа сервиса с ретраями и лимитами, а не миграции, у которой пять минут на ВСЮ цепочку.
--
-- UNIQUE НА КОЛОНКЕ БЫЛО БЫ ОШИБКОЙ ДВАЖДЫ: (а) один и тот же файл законно лежит в media несколько
-- раз — историю никто не чистил, а ADD UNIQUE проверяется РЕТРОАКТИВНО и упал бы на первой же паре
-- дублей, остановив старт прода (прецедент «ретроактивный CHECK роняет деплой»); (б) дедупликация —
-- политика импорта, а не инвариант хранилища: два одинаковых байта в media — не порча данных.
--
-- CHECK НА ФОРМАТ ХЕША ПО ТОЙ ЖЕ ПРИЧИНЕ НЕ ДОБАВЛЯЕТСЯ: он ретроактивен и копирует media целиком.
-- ADD COLUMN NULL — INSTANT, и это единственная форма, цена которой не зависит от размера таблицы.
--
-- ЦЕНА ЭТОГО ALTER'А — НЕ КОЛОНКА, А ИНДЕКС, и об этом честно. ADD COLUMN NULL сам по себе INSTANT,
-- но ADD INDEX в том же операторе заставляет MySQL выбрать INPLACE на ВЕСЬ ALTER: индекс строится
-- проходом по media. Это не COPY (таблица не переписывается) и не блокирует DML, но линейно по
-- числу строк. Ориентир, замеренный в 0324 на одноразовом MySQL 8.0.46: 400 тыс. строк — около 1 с
-- wall-clock на ПОЛНУЮ КОПИЮ таблицы; построение одного вторичного индекса дешевле копии, поэтому
-- запас до пятиминутного потолка трёхзначный при любом правдоподобном размере media. ЗАМЕР ВСЁ
-- РАВНО СНЯТЬ ПЕРЕД ВЫКАТКОЙ, всегда с ЯВНОЙ базой (бета — grbpwr_beta, прод — grbpwr, и прод
-- обновляется вручную):
--     SELECT COUNT(*) AS media_rows FROM media;
-- Если счёт покажет миллионы — мерить ALTER на копии, а не выкатывать вслепую.
--
-- ИНДЕКС ОБЯЗАТЕЛЕН, И ОН НЕ «НА ВСЯКИЙ СЛУЧАЙ»: весь смысл колонки — точечный поиск «есть ли медиа
-- с таким хешем» на КАЖДЫЙ файл архива. Без индекса это полный скан media на файл, то есть импорт с
-- тридцатью картинками = тридцать сканов.
--
-- FK ИЗ media НИКУДА НЕ ДОБАВЛЯЕТСЯ и никакая другая таблица этим файлом не трогается: media —
-- общий корень схемы (на media(id) ссылаются 22 колонки), и любая новая связь ОТТУДА
-- меняет правила удаления для всех.
--
-- ==== 3. Идемпотентность ====
--
-- MySQL 8 автокоммитит DDL, поэтому падение в середине файла оставляет схему полуприменённой БЕЗ
-- строки в gorp_migrations, и следующая загрузка перезапускает файл с начала (инцидент 0079).
-- Отсюда: CREATE TABLE IF NOT EXISTS (этого требует и TestNewMigrationsAreIdempotent), а ALTER на
-- media — под information_schema-гардом.
--
-- ГВАРД ПО КОЛОНКЕ ЗАКРЫВАЕТ И ИНДЕКС — ИМЕННО ПОТОМУ, ЧТО ALTER ОДИН: одиночный ALTER в MySQL 8
-- атомарен, поэтому состояние «колонка есть, индекса нет» этим файлом недостижимо (тот же довод и
-- прямой замер — в шапке 0334). НЕ РАЗБИВАТЬ ЭТОТ ALTER НА ДВА «ради читаемости»: два оператора
-- теряют атомарность, и вот тогда гвард по колонке пропустит файл, а индекс не появится никогда —
-- молча и навсегда.
--
-- PREPARE / EXECUTE / DEALLOCATE — ПО ОДНОМУ ОПЕРАТОРУ НА СТРОКУ: прод ходит без multiStatements,
-- склеенная строка молча не выполнится, а контейнерный прогон с multiStatements=true эту ошибку
-- маскирует.

-- 1. Приёмная импорта. tech_card(id) — INT AUTO_INCREMENT (0067), поэтому tech_card_id тоже INT.
--    idx_tci_card объявлен явно; FK на ту же колонку переиспользует его и второго индекса не
--    заводит. Ни одной колонки с DEFAULT-выражением: TIMESTAMP-колонки объявлены явно, поэтому
--    неявное «первая TIMESTAMP получает ON UPDATE CURRENT_TIMESTAMP» здесь не срабатывает и
--    created_at не переписывается при каждом UPDATE статуса.
CREATE TABLE IF NOT EXISTS tech_card_import (
    id INT PRIMARY KEY AUTO_INCREMENT,
    import_id CHAR(26) NOT NULL COMMENT 'ключ диалога загрузка -> коммит: 26 символов base32 от 128 случайных бит, без временной компоненты (форма ULID, но не ULID: порядка в нём нет)',
    tech_card_id INT NULL COMMENT 'создаётся на коммите; NULL = карточки из этого архива ещё нет',
    object_key VARCHAR(512) NOT NULL COMMENT 'ключ архива в бакете (techcard-imports/...)',
    archive_manifest JSON NOT NULL COMMENT 'что было в ZIP на загрузке',
    colorways_payload JSON NULL COMMENT 'тело colorways.json; NULL = колорвеев в архиве нет',
    report JSON NULL COMMENT 'итоговый отчёт коммита с дырами; NULL до коммита',
    status VARCHAR(16) NOT NULL DEFAULT 'uploaded'
        COMMENT 'uploaded|committed|failed|expired; словарь держит Go, CHECK намеренно не заводится',
    imported_by VARCHAR(255) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    committed_at TIMESTAMP NULL,
    acknowledged_at TIMESTAMP NULL,
    CONSTRAINT uniq_tci_import_id UNIQUE (import_id),
    CONSTRAINT fk_tci_card FOREIGN KEY (tech_card_id) REFERENCES tech_card(id) ON DELETE SET NULL,
    INDEX idx_tci_card (tech_card_id)
) ENGINE=InnoDB;

-- 2. Отпечаток содержимого медиа: колонка и индекс ОДНИМ атомарным ALTER под гардом по колонке.
SET @media_content_hash_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'media'
      AND COLUMN_NAME = 'content_hash'
);
SET @ddl := IF(@media_content_hash_exists = 0,
    'ALTER TABLE media ADD COLUMN content_hash CHAR(64) NULL COMMENT ''hex SHA-256 содержимого файла; NULL = не считан (историческое медиа), НЕ бэкфиллится и НЕ уникально'', ADD INDEX idx_media_content_hash (content_hash)',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down
--
-- Откат симметричен и полон: обе вещи заводятся ЭТИМ файлом, ни одна не расширяет чужой словарь и
-- ни одна не переписывает существующих строк, поэтому сузить обратно можно без ретроактивной
-- проверки — того самого, что запрещает откат словарным миграциям (0335).
--
-- Данные tech_card_import теряются, и это честно: журнал импортов живёт только здесь. Объекты
-- архивов в бакете откат не трогает — их убирает отдельная уборка по возрасту.
--
-- Индекс дропается ЯВНО, хотя MySQL снёс бы его и вместе с последней колонкой: явная форма не
-- зависит от того, останется ли колонка в каком-нибудь другом индексе завтра. Оба пункта — ОДИН
-- ALTER, тем же доводом об атомарности, что и в Up.

DROP TABLE IF EXISTS tech_card_import;

SET @media_content_hash_exists := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'media'
      AND COLUMN_NAME = 'content_hash'
);
SET @ddl := IF(@media_content_hash_exists = 1,
    'ALTER TABLE media DROP INDEX idx_media_content_hash, DROP COLUMN content_hash',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
