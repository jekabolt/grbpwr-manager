-- Указания на вложенных картинках карточки канбана: у task_media появляются свои выноски.
--
-- «Тут шов кривой», «вот эту молнию», «отсюда досюда» — сказанное стрелкой на самом снимке, а не
-- пересказанное словами в описании. До сих пор так умели говорить только эскиз тех-карты (0309) и
-- снимок шага сборки (0308), а карточка — то самое место, где обсуждение и происходит, — заставляла
-- переписывать картинку текстом. Примитив указания берётся ТОТ ЖЕ (TechCardAnnotation, с его видами,
-- точками, цветом и пунктиром): человек рисует одним и тем же жестом, и второй набор видов со второй
-- проверкой разошёлся бы с первым на первой же правке, а читателю пришлось бы смотреть в две системы.
--
-- ПОЧЕМУ JSON-КОЛОНКОЙ РЯДОМ С КАРТИНКОЙ, А НЕ ТРЕТЬЕЙ ТАБЛИЦЕЙ — довод 0308 целиком: у выноски нет
-- внешних ссылок, она читается и пишется только целиком со своей картинкой, а отдельные строки дали
-- бы на неё сослаться номером — ровно та ловушка, из-за которой указания и переехали к снимку.
-- Форму JSON проверяет Go рядом с читаемым сообщением, до стора.
--
-- NULL, А НЕ NOT NULL. В 0308 колонка выносок объявлена NOT NULL, потому что таблица рождалась
-- пустой и писать её мог только новый стор. Здесь task_media ЖИВАЯ и полна строк, а у JSON в MySQL 8
-- нет литерального DEFAULT — NOT NULL пришлось бы дозаполнять UPDATE'ом по всей истории. NULL здесь
-- означает ровно то, что случилось: «указаний никто не рисовал». Новый стор пишет пустой массив, так
-- что различать два способа сказать одно придётся ровно на строках, записанных до этой миграции.
--
-- CHECK намеренно НЕ ставится: ретроактивный CHECK проверяет ВСЮ историю и роняет старт прода, а
-- словарь видов, число точек и границы координат всё равно проверяются в Go, где отказ называет
-- карточку, картинку и выноску — вместо сырого 3819 с именем колонки.
--
-- Идемпотентно: MySQL не знает ADD COLUMN IF NOT EXISTS, поэтому ALTER охраняется по
-- information_schema.COLUMNS. PREPARE/EXECUTE/DEALLOCATE — КАЖДЫЙ СВОЕЙ СТРОКОЙ: драйвер без
-- multiStatements выполняет по одному запросу, и склеенные вместе они падают на проде.
--
-- ЭТА МИГРАЦИЯ ИНЕРТНА для живых карточек: старый стор колонку не читает и не пишет, а полная замена
-- медиа карточки сносит строку вместе с её выносками — окно «схема новая, стор старый» ничего не
-- теряет, потому что терять там ещё нечего.

-- +migrate Up

SET @task_media_ann := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'task_media'
      AND COLUMN_NAME = 'annotations');
SET @ddl := IF(@task_media_ann = 0,
    'ALTER TABLE task_media
        ADD COLUMN annotations JSON NULL COMMENT ''указания на этой картинке (TechCardAnnotation[]); [] = не рисовали, NULL = строка старше 0313''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down

SET @task_media_ann_down := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'task_media'
      AND COLUMN_NAME = 'annotations');
SET @ddl_down := IF(@task_media_ann_down = 1,
    'ALTER TABLE task_media DROP COLUMN annotations',
    'SELECT 1');
PREPARE stmt FROM @ddl_down;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
