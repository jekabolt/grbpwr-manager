-- ПОНИЖЕНИЕ ПРОВЕНАНСА ПРОЦЕНТА РАСКРОЯ ПОСЛЕ СМЕНЫ ЛИНЕЙКИ (W3).
--
-- ЭТА МИГРАЦИЯ НЕ МЕНЯЕТ НИ ОДНОГО ЧИСЛА. Она снимает ЗАЯВЛЕНИЕ о том, чем это число подтверждено.
-- Разница несущая, и её надо прочитать до первой правки здесь.
--
-- ЧТО ПРОИЗОШЛО. До W3 tech_card_bom_item.wastage_percent оплачивал ВСЁ, чего нет в netto:
-- межлекальные выпады + концы настила + усадку/пороки/сращивание. Предложение к нему считалось как
-- медиана «факт ÷ netto − 1», то есть по ТОЙ ЖЕ широкой линейке, и строка со wastage_source='lays'
-- честно утверждала: «это число — медиана по N раскроям».
--
-- W3 сузил смысл поля: процент теперь оплачивает ТОЛЬКО геометрию настила (выпады + концы), а
-- усадку/пороки/сращивание оплачивает material.cutting_coefficient — и с W3 коэффициент входит в
-- ТЕ ЖЕ деньги нормы (entity.TechCardColorwayUsage.NormGrossUp). Знаменатель предложения переехал
-- следом: медиана считается над netto × коэффициент.
--
-- ПОЧЕМУ БЕЗДЕЙСТВИЕ БЫЛО БЫ ХУЖЕ. У артикула с заданным коэффициентом старое значение процента
-- содержит усадку внутри себя, а коэффициент теперь начисляет её ВТОРОЙ раз — строка оплачивает
-- усадку дважды. При этом бейдж продолжает говорить «медиана по N раскроям», хотя такой медианы
-- больше не существует: линейка, которой её мерили, снята. Самопроверка EffectiveBomWastageProvenance
-- этого поймать НЕ МОЖЕТ по построению — она сверяет applied_percent с wastage_percent, а значение
-- не менялось; изменился его СМЫСЛ, которого в схеме нет.
--
-- ПОЧЕМУ НЕ ПЕРЕСЧИТАТЬ ЧИСЛО ЗДЕСЬ. Потому что система никогда не меняет цифры молча — та же
-- дисциплина, что у самой калибровки («предложение, а не применение»: функция возвращает
-- предложение, принимает его рука). Пересчёт разделил бы процент на коэффициент за оператора и на
-- данных, которых миграция не видит (медиана живёт в настилах, а не в строке). Поэтому число
-- остаётся ровно таким, каким его вписали, а уезжает только заявление, что оно подтверждено
-- калибровкой. Оператор увидит «введено руками» и сможет переприменить предложение по новой
-- линейке — уже осознанно.
--
-- ПОЧЕМУ ВСЕ СТРОКИ, А НЕ ТОЛЬКО У АРТИКУЛОВ С КОЭФФИЦИЕНТОМ. Заявление 'lays' — это утверждение о
-- ЛИНЕЙКЕ, а не о величине. Медиана по чистому netto снята для всех: артикул, у которого
-- коэффициента нет СЕГОДНЯ, завтра его получит, и тогда переживший бейдж стал бы враньём задним
-- числом, найти которое было бы уже нечем. Дешевле снять заявление один раз у всех, чем оставить
-- срок годности, о котором никто не помнит.
--
-- ИДЕМПОТЕНТНО: повторный прогон не находит строк с 'lays' и не делает ничего. Ретроактивного CHECK
-- здесь нет намеренно — он проверял бы ВСЮ историю и останавливал бы старт прода.

UPDATE tech_card_bom_item
SET wastage_source   = 'manual',
    wastage_lay_count = NULL
WHERE wastage_source = 'lays';

-- wastage_applied_at / wastage_applied_percent НЕ трогаем: они описывают, ЧТО и КОГДА было
-- применено, и остаются верным следом события. Читатель (EffectiveBomWastageProvenance) всё равно
-- отдаёт их наружу только вместе с источником 'lays', то есть после этой миграции — ни с чем;
-- обнулять их значило бы стирать историю ради косметики строки, которую никто не читает.

