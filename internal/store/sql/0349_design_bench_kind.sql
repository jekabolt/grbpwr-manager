-- Полоса DESIGN, волна 2, кусок 2 из 3: ВЕРСТАК СТАНОВИТСЯ ДВУХОСНЫМ — вид × род.
--
-- ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ЧАСТЬЮ 0348. Это единственная в волне ПЕРЕСТРОЙКА КЛЮЧА, а не
-- аддитивная колонка. У неё своя цена (построение вторичного индекса), свой откат (заведомо
-- разрушительный, см. ниже) и своя ловушка порядка. Отделённый файл вынимается из волны одним
-- движением — ни 0348, ни 0350 его не читают и от него не зависят. Приём и довод — те же, что у
-- 0346, отделённой от 0345.
--
-- ─── ЧТО СЛОМАНО ───────────────────────────────────────────────────────────────────────────────
--
-- У слота ОДНА ось: `uq_design_bench_view (tech_card_id, exclusive_key)` (0341) читается как «на
-- карточке ровно один слот на адрес», где адрес для стороны — это `view_key` (`front`, `back`,
-- `side_l`, `side_r`), а для детали — собственный ключ слота. Пока верстак держал только флэты, это
-- была правда.
--
-- W-11 («когда флэты готовы — генерится FABRIC RENDER») делает её ложью. Рендер фронта и флэт
-- фронта — это ОДИН адрес `front`. Первое же принятие рендера ВЫТЕСНЯЕТ флэт: upsert
-- (`internal/store/design/bench.go:31-41`) находит строку по тому же ключу и переписывает
-- `picture_id`. Дальше беда идёт вниз по течению: минт версии собирает плиты из слотов, значит на
-- ТЕХНИЧЕСКИЙ ЛИСТ уезжает рендер вместо чертежа — молча, без единого отказа, и человек видит
-- правдоподобную бумагу с неверным содержимым.
--
-- ЛЕЧИТЬ ЭТО НА ОСИ `view_key` НЕЛЬЗЯ. Значение вроде `front_render` — ровно то «ложное
-- расщепление», от которого репо отказывалось уже дважды: два члена словаря, различающиеся ОДНИМ
-- заданным признаком, это не два вида, а один вид и признак. Каждый читатель, спрашивающий «какая
-- сторона», был бы обязан знать разбор строки, а каждый новый род (3D) удваивал бы словарь.
-- Род кадра — настоящая ВТОРАЯ ОСЬ: `design_picture.kind` (0340) её уже несёт (`flat|render|threed`),
-- и слот обязан говорить на том же словаре.
--
-- ─── ЧТО ДЕЛАЕТСЯ ──────────────────────────────────────────────────────────────────────────────
--
-- 1. `kind` со значением по умолчанию `flat`;
-- 2. `uq_design_bench_view` пересобирается на `(tech_card_id, kind, exclusive_key)`.
--
-- `DEFAULT 'flat'` — НЕ ОСТОРОЖНОСТЬ, А СОХРАНЕНИЕ ПОВЕДЕНИЯ, и это проверяемо: `benchSlotUpsert`
-- (`bench.go:31-41`) не именует `kind` ни в списке колонок, ни в `ON DUPLICATE KEY UPDATE`, поэтому
-- вставка получает `flat` по умолчанию и разрешается на ТЕХ ЖЕ строках, что до миграции. Старый
-- бинарь на новой схеме продолжает работать ровно как прежде — он живёт целиком во флэтовой
-- плоскости и другой не видит.
--
-- РАСШИРЕНИЕ UNIQUE НИКОГДА НЕ ПАДАЕТ НА ЖИВЫХ ДАННЫХ: множество ключей только дробится. Обратное
-- (сужение) — падает, и потому Down в этом файле разрушителен; см. его собственную шапку.
--
-- ПОРЯДОК КОЛОНОК В КЛЮЧЕ — `(tech_card_id, kind, exclusive_key)`, как в плане. `tech_card_id`
-- обязан остаться СЛЕВА: на нём висит `fk_design_bench_slot_card`, а InnoDB не даёт остаться
-- внешнему ключу без покрывающего индекса (1553). `kind` перед `exclusive_key`, а не после, потому
-- что живой предикат чтения — «покажи флэтовые слоты карточки» (`composeMintPlates` обязан
-- фильтровать `kind='flat'`), и такой префикс он использует; обратный порядок дал бы индекс,
-- полезный только для точечного поиска.
--
-- DROP И ADD — ОДНИМ ОПЕРАТОРОМ. Не ради краткости: между двумя раздельными ALTER существует
-- мгновение, когда старого ключа уже нет, а нового ещё нет, и в этот момент таблица принимает
-- дубликат адреса. Здесь второй индекс (`uq_design_bench_picture`) тоже начинается с
-- `tech_card_id`, поэтому 1553 не грозит и раздельные шаги ФОРМАЛЬНО прошли бы — окно
-- рассогласования всё равно не нужно, а MySQL внутри одного ALTER выполняет DROP раньше ADD, что
-- позволяет переиспользовать ТО ЖЕ ИМЯ индекса. Имя сохранено намеренно: `bench.go:230-245,290,334`
-- и `design_shape_test.go:79-80` разбирают текст ошибки 1062 ПО ИМЕНИ КЛЮЧА, различая «кто-то
-- тронул этот слот» (`uq_design_bench_view`) и «плита уже занята» (`uq_design_bench_picture`).
-- Переименование индекса тихо сломало бы этот разбор и превратило бы понятный отказ в сырую 1062.
--
-- ВТОРОЙ КЛЮЧ, `uq_design_bench_picture (tech_card_id, picture_id)`, НЕ ТРОГАЕТСЯ, и это тоже
-- решение. Он говорит «одна плита максимум в одном слоте»; с появлением рода это утверждение не
-- изменилось: конкретная картинка — либо флэт, либо рендер, и стоять она может ровно в одном месте.
--
-- ─── ЦЕНА ──────────────────────────────────────────────────────────────────────────────────────
--
-- `ADD COLUMN … NOT NULL DEFAULT` в конец таблицы — INSTANT (MySQL 8.0.12+): копии нет. Перестройка
-- вторичного индекса — INPLACE, таблица не перестраивается. Отдельными ALTER они идут не только
-- ради гейтов: смешивать INSTANT ADD COLUMN и ADD INDEX в одном операторе нельзя — MySQL выберет
-- один алгоритм на весь оператор и потеряет INSTANT.
--
-- Таблицы `design_bench_slot` на проде НЕТ ВООБЩЕ (прод стоит на 0339), на бете она заведена 0341 и
-- почти пуста. Пятиминутный потолок всего прогона (`internal/store/store.go:236`) не рядом.
--
-- НИ ОДНОГО `ADD CONSTRAINT … CHECK`. `kind` — VARCHAR без проверки, по общему правилу полосы:
-- словари растут, а поздний ADD CHECK на потолстевшей таблице копирует её целиком и проверяет ВСЮ
-- историю. Словарь стережёт Go, где отказ называет карточку и значение.
--
-- ─── ЧТО ЭТА МИГРАЦИЯ НЕ ЧИНИТ (и обязано быть починено кодом) ─────────────────────────────────
--
-- `slotByKey` (`internal/store/design/bench.go:366-376`) ищет слот по `(tech_card_id,
-- exclusive_key)` и возвращает `rows[0]`. До этой миграции такая строка была ровно одна; после —
-- их станет столько, сколько родов занято на адресе, и `rows[0]` начнёт выбирать произвольную.
-- Пока НИ ОДИН писатель не кладёт `kind <> 'flat'`, множество остаётся одноэлементным и поведение
-- не меняется, поэтому файл ИНЕРТЕН сам по себе. Но первый же писатель рендера обязан приехать
-- ВМЕСТЕ с `kind` в предикате этого запроса — иначе двухосность станет источником тихой путаницы
-- вместо лекарства от неё.
--
-- ─── ИДЕМПОТЕНТНОСТЬ ───────────────────────────────────────────────────────────────────────────
--
-- MySQL авто-коммитит DDL пооператорно: падение посреди файла оставляет схему полуприменённой БЕЗ
-- строки в `gorp_migrations`, и следующий старт прогонит файл с начала. Гейт колонки — по
-- `information_schema.COLUMNS`; гейт ключа — по `information_schema.STATISTICS`, причём НЕ по
-- наличию индекса (он существует и до, и после), а ПО НАЛИЧИЮ В НЁМ КОЛОНКИ `kind`. Предусмотрена и
-- третья ветка — «индекса нет вовсе»: тогда он просто создаётся. `PREPARE` / `EXECUTE` /
-- `DEALLOCATE` — каждый своей строкой: прод ходит БЕЗ `multiStatements`, а контейнерный тест эту
-- поломку маскирует.

-- +migrate Up

-- 1. Род слота. INSTANT: nullable-ность не нужна, потому что у значения есть честный дефолт.
SET @dbs_kind := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_bench_slot'
      AND COLUMN_NAME = 'kind');
SET @ddl := IF(@dbs_kind = 0,
    'ALTER TABLE design_bench_slot
        ADD COLUMN kind VARCHAR(16) NOT NULL DEFAULT ''flat''
            COMMENT ''flat|render|threed — РОД кадра, вторая ось верстака; тот же словарь, что у design_picture.kind. DEFAULT flat сохраняет поведение старого писателя, который kind не именует. Словарь растёт, CHECK намеренно нет''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- 2. Пересборка адресного ключа. Гейт — по наличию `kind` В САМОМ ИНДЕКСЕ, а не по наличию индекса.
SET @dbs_view_has_kind := (SELECT COUNT(*) FROM information_schema.STATISTICS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_bench_slot'
      AND INDEX_NAME = 'uq_design_bench_view' AND COLUMN_NAME = 'kind');
SET @dbs_view_exists := (SELECT COUNT(*) FROM information_schema.STATISTICS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_bench_slot'
      AND INDEX_NAME = 'uq_design_bench_view');
SET @ddl := IF(@dbs_view_has_kind = 1,
    'SELECT 1',
    IF(@dbs_view_exists > 0,
        'ALTER TABLE design_bench_slot
            DROP INDEX uq_design_bench_view,
            ADD UNIQUE KEY uq_design_bench_view (tech_card_id, kind, exclusive_key)',
        'ALTER TABLE design_bench_slot
            ADD UNIQUE KEY uq_design_bench_view (tech_card_id, kind, exclusive_key)'));
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down
--
-- DOWN ЗАВЕДОМО ТЕРЯЕТ ДАННЫЕ, И ЭТО ОСОЗНАННО — тот же выбор и тот же довод, что в 0346.
--
-- Одноосная схема НЕ СПОСОБНА ВЫРАЗИТЬ слот рода `render` или `threed`: два таких слота на одном
-- адресе — законное состояние после Up и невозможное до него. Сужение UNIQUE о них упало бы 1062 и
-- ЗАКЛИНИЛО БЫ ОТКАТ НАВСЕГДА, а заклинивший откат стоит дороже потерянных строк верстака. Поэтому
-- Down СНАЧАЛА удаляет всё, что не `flat`.
--
-- Что теряется: постановки рендеров и 3D по слотам. Что НЕ теряется: сами картинки
-- (`design_picture` не тронута — слот это адрес, а не владение) и уже сминтованные листы
-- (`design_sheet_version_plate.slot_id` — ON DELETE SET NULL, 0342:80: бумага остаётся читаемой,
-- теряется лишь обратная ссылка на слот).
--
-- После удаления дублей на паре `(tech_card_id, exclusive_key)` не остаётся ПО ПОСТРОЕНИЮ: среди
-- строк одного рода эта пара уникальна благодаря самому ключу, который Up поставил.
--
-- Порядок обратный Up: сперва DELETE, потом сужение ключа ОДНИМ оператором, и только затем
-- DROP COLUMN. Снимать колонку раньше нельзя — и это не эстетика: MySQL удаляет индекс вместе с
-- колонкой ТОЛЬКО когда снимаются ВСЕ его колонки, а из многоколоночного просто ВЫЧЁРКИВАЕТ
-- снятую. `DROP COLUMN kind` тихо превратил бы трёхколоночный ключ в двухколоночный — то есть сделал
-- бы сужение НЕЯВНО и без всякого гейта, ровно там, где оно способно упасть 1062 (ловушка описана
-- в 0323).
--
-- DELETE ТОЖЕ ПОД ГЕЙТОМ, и это не перестраховка: он именует колонку, которую этот же файл ниже
-- снимает. Повтор отката, упавшего после DROP COLUMN, наткнулся бы на «Unknown column 'kind'» и
-- заклинил бы — то самое, чего вся идемпотентность и добивается.

SET @dbs_kind_pre_down := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_bench_slot'
      AND COLUMN_NAME = 'kind');
SET @dml_down := IF(@dbs_kind_pre_down = 1,
    'DELETE FROM design_bench_slot WHERE kind <> ''flat''',
    'SELECT 1');
PREPARE stmt FROM @dml_down;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

SET @dbs_view_has_kind_down := (SELECT COUNT(*) FROM information_schema.STATISTICS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_bench_slot'
      AND INDEX_NAME = 'uq_design_bench_view' AND COLUMN_NAME = 'kind');
SET @ddl_down := IF(@dbs_view_has_kind_down = 1,
    'ALTER TABLE design_bench_slot
        DROP INDEX uq_design_bench_view,
        ADD UNIQUE KEY uq_design_bench_view (tech_card_id, exclusive_key)',
    'SELECT 1');
PREPARE stmt FROM @ddl_down;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

SET @dbs_kind_down := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'design_bench_slot'
      AND COLUMN_NAME = 'kind');
SET @ddl_down := IF(@dbs_kind_down = 1,
    'ALTER TABLE design_bench_slot DROP COLUMN kind',
    'SELECT 1');
PREPARE stmt FROM @ddl_down;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
