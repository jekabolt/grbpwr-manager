-- ПРОЕКТ ↔ СТИЛЬ: «КАКИМ ФАЙЛОМ СДЕЛАНА ЭТА ВЕЩЬ».
--
-- Ф0 (0320) научила тему быть ПРОЕКТОМ и разложила файлы внутри него по ролям — это ответ на
-- вопрос «что лежит в этой съёмке». Обратный вопрос остался без ответа вовсе: человек стоит на
-- карточке вещи и спрашивает, каким .zprj она сшита и какая раскладка в неё уехала. Сегодня это
-- знание живёт в чьей-то голове и в имени файла, а имя переживает ровно один переезд.
--
-- ПОЧЕМУ СВЯЗЬ МНОГИЕ-КО-МНОГИМ, А НЕ КОЛОНКА `tech_card_id` В `file_topic`. Не из осторожности —
-- обе стороны множественны ПО СУЩЕСТВУ, и каждую видно на живых данных:
--
--   * ОДИН ПРОЕКТ → МНОГО СТИЛЕЙ. Съёмка снимает капсулу: одна папка исходников покрывает восемь
--     вещей сразу. Колонка заставила бы завести восемь одинаковых проектов-съёмок, и рельс тем
--     (который и так растёт монотонно, см. довод про архив в 0320) забился бы копиями.
--   * ОДИН СТИЛЬ → МНОГО ПРОЕКТОВ. Бекап CLO покрывает ровно одну вещь, но та же вещь попадает и
--     в съёмку, и в лукбук. Колонка на теме выразила бы это, только если у стиля один-единственный
--     проект, а он не один.
--
-- Обратная колонка (`tech_card.project_topic_id`) ломается на первом же примере симметрично.
--
-- РОЛИ ЗДЕСЬ НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ. Роль в 0320 живёт на строке «файл ↔ тема», потому что
-- пара (файл, проект) действительно имеет свойство. У пары (проект, стиль) свойства нет: «этот
-- стиль в этой съёмке — исходник» не значит ничего. Всё, что связь обязана нести, — сам факт и
-- когда он появился.
--
-- СВЯЗЬ ИМЕЕТ СМЫСЛ ТОЛЬКО У ТЕМЫ kind='project', И ПРОВЕРЯЕТСЯ ЭТО В КОДЕ, А НЕ CHECK'ом.
-- Ретроактивный CHECK проверяет ВСЮ историю таблицы и останавливает старт прода (2026-08-08,
-- tech_card_marker). Здесь он к тому же невыразим без денормализации `kind` во вторую таблицу, а
-- денормализация давала бы устаревающие строки при смене типа темы — ровно тот довод, по которому
-- 0320 не потащила `kind` в library_file_topic. Проверка стоит в единственном месте, где связь
-- заводится (fileslibrary.LinkTopicStyle), и отвечает InvalidArgument с фразой, а не 1452 с
-- именем ключа.
--
-- КАСКАДЫ — ОБА, И ОБА ПО РАЗНЫМ ДОВОДАМ:
--
--   * topic_id → file_topic ON DELETE CASCADE. Тема удаляется только пустой (DeleteTopic
--     отказывает, пока её несут файлы), поэтому RESTRICT здесь не защищал бы ничего — он лишь
--     сделал бы ПУСТОЙ проект неудаляемым из-за строки, которой на экране тем не видно, и человек
--     упёрся бы в отказ без объяснения. Связь без темы не значит ничего, и держать её не за что.
--   * tech_card_id → tech_card ON DELETE CASCADE. Стиль удаляют редко и с боем (есть отдельный
--     гейт), но если удалили — «этой вещи больше нет» и связь с ней тоже. RESTRICT превратил бы
--     заметку в библиотеке в блокировку удаления стиля, то есть служебная связь стала бы главнее
--     сущности, ради которой она заведена.
--
-- Файлы при этом не трогаются НИКОГДА: связь соединяет ПРОЕКТ и СТИЛЬ, а бекап .zprj остаётся
-- лежать в библиотеке ровно там же, где лежал.
--
-- ИДЕМПОТЕНТНОСТЬ (CLAUDE.md): MySQL 8 авто-коммитит DDL, поэтому падение в середине файла
-- оставляет схему полуприменённой БЕЗ строки в gorp_migrations, и следующая загрузка перезапускает
-- файл с начала. Здесь ровно ОДИН оператор — создание таблицы с IF NOT EXISTS, — и повтор
-- является no-op целиком, вместе с обоими внешними ключами и обоими индексами: они объявлены
-- ВНУТРИ этого же оператора, а не отдельными ALTER и отдельными индексами (у последних в MySQL
-- нет IF NOT EXISTS вовсе, и им пришлось бы городить гейт по information_schema, как в 0320 п.5).
-- Ни PREPARE, ни multiStatements-ловушки здесь поэтому нет. Ретроактивных CHECK нет ни одного.
-- Разрушительных операций нет: таблица новая и пустая, значит и внешние ключи проверять нечего.
--
-- ПРОВЕРЕНО ДВОЙНЫМ ПРИМЕНЕНИЕМ, А НЕ ЛИНТОМ. migrationlint читает ТЕКСТ и умеет ровно два
-- правила (есть ли IF NOT EXISTS у создания таблицы и не сносится ли CHECK по позиционному
-- имени); голый ALTER он пропустит, а false-positive выдаст на собственное упоминание правила
-- в комментарии — что и случилось при написании этого файла. Доказательство идемпотентности —
-- снять отметку из gorp_migrations и применить файл повторно поверх уже созданной таблицы.
CREATE TABLE IF NOT EXISTS file_topic_tech_card (
  id INT PRIMARY KEY AUTO_INCREMENT,
  topic_id INT NOT NULL COMMENT 'FK file_topic(id); осмысленно только при kind=project — проверяется в сторе, не CHECK''ом',
  tech_card_id INT NOT NULL COMMENT 'FK tech_card(id) — стиль, о котором проект',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'когда связь завели; печатается на карточке вещи как «привязано»',
  -- UNIQUE даёт идемпотентность привязки ДАРОМ: повтор гасится INSERT IGNORE и не доезжает до
  -- 1062. Порядок колонок не косметика — этот же ключ обслуживает «стили проекта».
  UNIQUE KEY uniq_file_topic_tech_card (topic_id, tech_card_id),
  -- А это плечо — под ГЛАВНЫЙ запрос всей фазы: «какие проекты меня касаются» с карточки вещи.
  -- Без него он читался бы полным сканом связей, и лишним его делает только гипотеза, что связей
  -- будет мало; на неё в схеме полагаться нечем.
  INDEX idx_file_topic_tech_card_style (tech_card_id),
  CONSTRAINT fk_file_topic_tech_card_topic FOREIGN KEY (topic_id)
    REFERENCES file_topic (id) ON DELETE CASCADE,
  CONSTRAINT fk_file_topic_tech_card_style FOREIGN KEY (tech_card_id)
    REFERENCES tech_card (id) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4
  COMMENT 'Проект библиотеки файлов ↔ стиль (тех-карта): «каким файлом сделана эта вещь»';

