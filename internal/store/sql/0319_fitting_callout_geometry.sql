-- Геометрия указания на примерке: у выноски на фотографии появляется вид, якоря и цвет.
--
-- До сих пор выноска примерки умела ровно одно — нумерованная точка с запиской. Но примерка это и
-- есть то место, где ЗАМЕРЯЮТ: «здесь на 2 см уже», «вот на этом участке заламывает», «эту зону
-- перекроить». Мерка между двумя точками, скобка над участком и обведённая зона на снимке говорят
-- ровно то, ради чего примерку и снимают, а точка с подписью заставляет описывать словами то, что
-- нарисовано рядом. На эскизе тех-карты эти виды уже есть (0309, 0310) — примерка осталась
-- единственным экраном, где инструмент беднее задачи.
--
-- ПРИМИТИВ УКАЗАНИЯ В СИСТЕМЕ ОДИН, и это здесь главное. Заводить примерке свой словарь видов
-- значило бы развести два способа сказать одно: замечание примерки переносят в тех-карту, и
-- «дуга» обязана остаться той же дугой по обе стороны переноса. Поэтому колонки те же, значения
-- те же (см. TechCardAnnotationKind / TechCardAnnotationColor), и проверяет их тот же Go.
--
-- РАСШИРЕНИЕ АДДИТИВНОЕ. pos_x/pos_y СОХРАНЯЮТ смысл «где стоит нумерованный маркер» — на него
-- ссылается номером fitting_change_request.callout_number, и другой идентичности у выноски нет;
-- points держит якоря фигуры и у пина пуст. Каждая живая выноска читается ровно так, как читалась,
-- и дефолт 'pin' — не заглушка, а её настоящий вид.
--
-- КОЛОНКИ parts ЗДЕСЬ НЕТ, в отличие от 0310. Список деталей у карточной выноски вырос из
-- одиночного `part`; у выноски примерки поля `part` нет вовсе, и списку не на чем стоять. Связь
-- «замечание ↔ деталь» на примерке живёт своей таблицей (fitting_change_request_piece, 0256), и
-- второе место для той же связи развело бы две её половины.
--
-- ПОЧЕМУ ЯКОРЯ JSON-КОЛОНКОЙ, А НЕ ЧЕТВЁРТОЙ ТАБЛИЦЕЙ — тот же довод, что в 0308 и 0309: у точки
-- нет внешних ссылок, она читается и пишется только целиком со своей выноской (примерка сохраняет
-- выноски полной заменой), а отдельные строки дали бы на неё сослаться. Форму проверяет Go рядом с
-- читаемым сообщением, до стора.
--
-- POINTS NULL, А НЕ NOT NULL. Таблица ЖИВАЯ и полна строк, а JSON в MySQL 8 не имеет литерального
-- DEFAULT — NOT NULL пришлось бы дозаполнять UPDATE'ом по всей истории примерок. NULL здесь и
-- означает ровно то, что случилось: «якорей никто не ставил, это записано до 0319».
--
-- CHECK на вид намеренно НЕ ставится: ретроактивный CHECK проверяет ВСЮ историю и роняет старт
-- прода, а словарь вида всё равно проверяется в Go, где отказ называет примерку, выноску и
-- допустимые значения — вместо сырого 3819 с именем колонки. По той же причине нет CHECK и на
-- согласованность пунктира со штриховкой: правило живёт в calloutGeometryFromPb, где
-- бессмысленный флаг приводится к false, а не отвергается.
--
-- ПОЧЕМУ TINYINT(1) С ДЕФОЛТОМ, А НЕ NULL: «не пунктирная» — это факт каждой существующей линии, а
-- не отсутствие сведений. NULL здесь означал бы третье состояние, которого у пунктира нет.
--
-- СУЩЕСТВУЮЩИЕ CHECK НА pos_x/pos_y (0092) НЕ ТРОГАЮТСЯ. Они объявлены инлайном при создании
-- таблицы и потому авто-именованы (fitting_callout_chk_1/_2) — позиционные имена, которые дрейфуют
-- по истории схемы; ADD COLUMN с ними уживается, а снимать или переименовывать их отсюда нельзя.
--
-- Идемпотентно: колонки добавляются одним охраняемым ALTER (MySQL не знает ADD COLUMN IF NOT
-- EXISTS), охрана — по первой из пяти, потому что добавляются они вместе или не добавляются вовсе.

-- +migrate Up

SET @fitting_callout_geom := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'fitting_callout'
      AND COLUMN_NAME = 'kind');
SET @ddl := IF(@fitting_callout_geom = 0,
    'ALTER TABLE fitting_callout
        ADD COLUMN kind VARCHAR(16) NOT NULL DEFAULT ''pin'' COMMENT ''вид указания: pin|label|dim|bracket|multi|arc|polygon|ink (см. TechCardAnnotationKind)'',
        ADD COLUMN color VARCHAR(16) NOT NULL DEFAULT '''' COMMENT ''цвет указания: пусто = чернильный; red|blue|green|orange|white'',
        ADD COLUMN points JSON NULL COMMENT ''якоря геометрии в долях кадра; NULL = записано до 0319, [] = пин, маркер в pos_x/pos_y'',
        ADD COLUMN dashed TINYINT(1) NOT NULL DEFAULT 0 COMMENT ''пунктирная линия вместо сплошной; у pin всегда 0'',
        ADD COLUMN filled TINYINT(1) NOT NULL DEFAULT 0 COMMENT ''штриховка области; только у polygon, у прочих всегда 0''',
    'SELECT 1');
PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- +migrate Down

SET @fitting_callout_geom_down := (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'fitting_callout'
      AND COLUMN_NAME = 'kind');
SET @ddl_down := IF(@fitting_callout_geom_down = 1,
    'ALTER TABLE fitting_callout
        DROP COLUMN filled,
        DROP COLUMN dashed,
        DROP COLUMN points,
        DROP COLUMN color,
        DROP COLUMN kind',
    'SELECT 1');
PREPARE stmt FROM @ddl_down;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
