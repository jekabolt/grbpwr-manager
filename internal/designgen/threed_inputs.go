// ═══ ЧТО ИМЕННО УЕЗЖАЕТ В СБОРКУ 3D — И ПОЧЕМУ ЭТО НЕ «ВСЕ КАРТИНКИ ПРОГОНА» ═══════════════════
//
// Владелец (круг 5, V-14): «в 3д INPUT — RENDERS BY VIEW нельзя никаким образом просунуть
// ПРАВИЛЬНЫЕ референсы». Слово «правильные» — про то, что в сборку уезжали НЕ ТЕ картинки.
//
// ЗАМЕР. `referenceList` собирает картинки прогона из четырёх источников: плиты верстака,
// референсы карточки (`design_reference`), явно названные `extra_input_media_ids` и фото ткани из
// рецепта. Для флэта и рендера это ровно верно — они рисуют ПО этим картинкам. Для 3D неверно
// дважды:
//
//  1. Meshy multi-image-to-3d принимает 1..4 картинки И ЧИТАЕТ КАЖДУЮ КАК ВИД ОДНОГО ПРЕДМЕТА
//     (meshy.MinImages/MaxImages, image_urls[0] = фронт). Пятой картинке там места нет вовсе:
//     `meshy.Submit` отказывает ЛОКАЛЬНО, до сети. То есть на карточке, где у человека есть хоть
//     несколько референсов настроения, КАЖДЫЙ прогон 3D умирал у двери провайдера — не «иногда», а
//     всегда, потому что референсы есть на всякой живой карточке.
//  2. Хуже тихого отказа — тихий успех. Карточка с одним-двумя референсами и незаполненным
//     рендер-верстаком отправляла в сборку РЕФЕРЕНСЫ вместо видов: Meshy получал две фотографии
//     чужой одежды и строил модель по ним. Прогон закрывался `done`, деньги списывались, и по
//     истории отличить это от честной сборки было нечем.
//
// ПОЭТОМУ У 3D СПИСОК КАРТИНОК — ЭТО ЕГО СОБСТВЕННЫЕ ПЛИТЫ, и ничего кроме. Не сужение
// возможностей, а называние того, чем 3D является: поворотный стол крутит ВИДЫ ИЗДЕЛИЯ, и картинка,
// которая не вид этого изделия, в нём не роль, а помеха. Человек по-прежнему решает, ЧТО именно
// стоит в каждом виде — он ставит туда любую картинку рода `render`, свою или сгенерённую, — и
// именно это и есть «просунуть правильные референсы».
//
// ⚠ ФИЛЬТР ЖИВЁТ ЗДЕСЬ, А НЕ ВНУТРИ referenceList, И ЭТО НЕ СТИЛЬ. `referenceList` — общий сборщик
// для всех родов, и его правило дедупликации несущее: плита, названная ещё и референсом, держит
// ПЕРВУЮ позицию (порядок = смысл на маршруте 3D) и ДОПОЛНЯЕТ подпись словами человека. Отбирать
// внутри него значило бы завести четвёртый род внутри одного цикла; отбирать после — значит взять
// уже правильно упорядоченный и правильно подписанный список и оставить в нём свои строки.

// threedPictures — плиты ЭТОГО прогона, в том порядке, в котором их уже поставил referenceList
// (front, back, side_l, side_r — см. viewRank), с их подписями.
//
// ОТБОР ИДЁТ ПО media_id ПЛИТ СНИМКА, а не по «первым N элементам списка»: позиционное правило
// сломалось бы на первом же снимке, где плита названа ещё и референсом, — и сломалось бы молча.
//
// ⚠ ПРОИСХОЖДЕНИЯ МАЛО, НУЖЕН НАБОР ВИДОВ, И ЭТО ДВА РАЗНЫХ УТВЕРЖДЕНИЯ. «Картинка пришла из
// слота» отвечает на вопрос, ЧЬЯ она; провайдер задаёт другой: `image_urls[0]` он читает как
// ПЕРЁД, а весь список — как виды ОДНОГО предмета, числом от одного до четырёх. Поэтому здесь
// стоят ещё два правила, и оба ловят сценарий, который иначе проходит молча:
//
//  1. ТОЛЬКО ЧЕТЫРЕ ОРТОГОНАЛЬНЫЕ СТОРОНЫ (entity.IsDesignCardinalView). Деталь-рендер
//     (`view_key = detail`) — законная плита верстака и законный вход РЕНДЕРА, но виду изделия она
//     не равна: столу она пятая картинка, то есть локальный отказ `meshy.Submit` ДО сети. Карточка,
//     на которой человек сделал рендер манжеты, теряла из-за него КАЖДЫЙ прогон 3D.
//     ⚠ С круга 18 (D-28) у силуэта ШЕСТЬ сторон — добавились три четверти слева и справа, — и
//     фильтр «сторона силуэта» перестал держать потолок: шесть плит это на две больше, чем Meshy
//     принимает, а именной маршрут fal и вовсе не имеет слота для трёх четвертей (только
//     front/back/left/right). Поэтому отбор идёт по КАРДИНАЛЬНЫМ сторонам, и это тот же список у
//     обоих маршрутов: `uq_design_bench_view` (0341) держит по одной плите на сторону в пределах
//     рода — значит после этого фильтра список НЕ МОЖЕТ превысить потолок провайдера. Дверь
//     прогона (designRefuseForeignFixSlots) отказывает 3D, суженному до трёх четвертей, ДО денег,
//     так что сюда такая плита доезжает только неназванной — и молча не теряется ничего из того,
//     что человек просил.
//  2. БЕЗ ПЕРЕДА — НИЧЕГО. Прогон, у которого в верстаке рендера стоит только спина, отправлял
//     СПИНУ первой, и провайдер честно строил модель, считая её лицом изделия. Это тихий успех:
//     `done`, списанные деньги и вещь, повёрнутая задом наперёд, — а по истории такой прогон
//     неотличим от честного.
//
// ПУСТОЙ ОТВЕТ ЗАКОНЕН И ГОВОРИТ ПРАВДУ. Прогон 3D без переда — это прогон, которому нечего
// поставить лицом; провайдер отказывает своим `ErrImageCount` («a turntable needs at least the
// front view»), и такой отказ читается человеком. Подставить вместо переда что попало, лишь бы
// список был непуст, значило бы купить модель неизвестно чего.
func threedPictures(list []refCaption, in runInputs) []refCaption {
	plates := make(map[int]struct{}, len(in.Slots))
	front := false
	for _, s := range in.Slots {
		if s.MediaID <= 0 || !entity.IsDesignCardinalView(s.ViewKey) {
			continue
		}
		plates[s.MediaID] = struct{}{}
		if s.ViewKey == entity.DesignViewFront {
			front = true
		}
	}
	if !front {
		return nil
	}
	out := make([]refCaption, 0, len(plates))
	for _, rc := range list {
		if _, ok := plates[rc.MediaID]; ok {
			out = append(out, rc)
		}
	}
	return out
}

// ═══ РЕЖИМ РЕФЕРЕНСА (PLAYGROUND phase 2, плитка 12 «Image to 3D») ══════════════════════════════
//
// `params.threed.reference_media_ids` — 1..4 картинки, которые человек САМ назвал видами изделия:
// загрузка, файл библиотеки, результат другой плитки, плита верстака через Reuse. Непустой список
// ПЕРЕКЛЮЧАЕТ ИСТОЧНИК ЦЕЛИКОМ: прогон не читает верстак вовсе (дверь не отбирает плит —
// designSelectBench, — и `source_picture_ids` остаётся пустым), и воркер обязан сказать то же самое.
//
// ⚠ ВИДЫ СТАВЯТСЯ ПО ПОЗИЦИИ, И ЭТО ЕДИНСТВЕННОЕ ЧЕСТНОЕ ПРАВИЛО ЗДЕСЬ, а не лень. Контракт поля
// дословно: «ordered front, back, left, right». У названной картинки нет слота, который знал бы
// её сторону, — сторону знает только порядок, в котором человек её поставил. Поэтому первая —
// `front`, и оба маршрута читают её лицом изделия; пятой позиции нет (дверь отказывает
// `too_many_pictures` до денег), а если она всё же доехала в замороженном снимке, она уезжает БЕЗ
// вида: fal-маршрут отказывает неименованной картинке (falViews), прямой Meshy — числом
// (meshy.ErrImageCount). Молча отрезать хвост не может ни один из них.

// threedReferenceViews — сторона каждой позиции `reference_media_ids`.
var threedReferenceViews = []string{
	entity.DesignViewFront, entity.DesignViewBack, entity.DesignViewSideL, entity.DesignViewSideR,
}

// threedReferenceMode — прогон назвал свои картинки сам. Один предикат на воркер; у двери — свой
// (designThreedReferenceMode) над тем же полем того же сообщения.
func threedReferenceMode(p runParams) bool {
	return p.Threed != nil && len(p.Threed.ReferenceMediaIDs) > 0
}

// threedPicturesOf — картинки сборки 3D этого прогона.
//
// В РЕЖИМЕ РЕФЕРЕНСА ОНА НЕ СМОТРИТ НИ В `list`, НИ В `in.Slots`, и это несущее: референсы
// карточки, `extra_input_media_ids` и плиты верстака — не виды того предмета, который человек
// назвал, и любая из них, доехавшая сюда, стала бы «видом» чужой вещи (довод V-14 выше, дословно).
// Без референсов — сегодняшний путь, байт в байт: threedPictures.
func threedPicturesOf(list []refCaption, in runInputs, p runParams) []refCaption {
	if !threedReferenceMode(p) {
		return threedPictures(list, in)
	}
	return threedReferencePictures(p.Threed.ReferenceMediaIDs)
}

// threedReferencePictures — названные картинки в порядке человека, с видом по позиции и подписью
// «reference view N». Номер в подписи — позиция в ЕГО списке, а не в выжившем: подпись описывает
// то, что он назвал.
func threedReferencePictures(ids []int) []refCaption {
	out := make([]refCaption, 0, len(ids))
	for i, id := range ids {
		if id <= 0 {
			// Дверь отказывает такому номеру; замороженный снимок, доехавший сюда иначе, теряет
			// позицию, но НЕ сдвигает виды остальных — сторона принадлежит позиции.
			continue
		}
		view := ""
		if i < len(threedReferenceViews) {
			view = threedReferenceViews[i]
		}
		out = append(out, refCaption{
			MediaID: id,
			Caption: fmt.Sprintf("reference view %d", i+1),
			View:    view,
		})
	}
	return out
}

// threedOptions — три опции сборки этого прогона: texture "" | on | off, pbr "" | on | off,
// quality "" | standard | detailed. ПУСТАЯ СТРОКА — СЕГОДНЯШНЯЯ КОНСТАНТА у каждой (с текстурой, без PBR,
// стандартная геометрия), поэтому прогон верстака и всякий прогон, замороженный до полей, уходит к
// поставщику тем же телом байт в байт. Слова — те же, что у обоих транспортов (fal.Option*,
// meshy.Option*), и едут к ним без перевода.
type threedOptions struct {
	Texture string
	PBR     string
	Quality string
}

// threedOptionsOf — опции из замороженных params.
func threedOptionsOf(p runParams) threedOptions {
	if p.Threed == nil {
		return threedOptions{}
	}
	return threedOptions{
		Texture: strings.TrimSpace(p.Threed.Texture),
		PBR:     strings.TrimSpace(p.Threed.PBR),
		Quality: strings.TrimSpace(p.Threed.Quality),
	}
}

// untextured — сборка без текстуры. Ей нечем читать `texture_prompt` (у обоих поставщиков он
// «Requires should_texture»), поэтому стир не уезжает — и SentPrompt обязан сказать то же самое.
func (o threedOptions) untextured() bool { return o.Texture == "off" }

// threedJobOptions — опции, которые маршрут 3D читает с задания.
//
// ⚠ ИНТЕГРАЦИЯ (B-core, строка 7 брифа B-09). Поля Job.ThreedTexture / ThreedPBR / ThreedQuality
// живут в provider.go и заполняются в buildJob (snapshot.go) — оба файла принадлежат B-core. До
// того, как их добавят, функция отвечает НУЛЁМ, то есть сегодняшними константами, и маршруты
// отправляют сегодняшнее тело. Патч интеграции заменяет тело этой функции на чтение трёх полей.
func threedJobOptions(job Job) threedOptions {
	_ = job
	return threedOptions{}
}

// threedSentSteer — какие слова этот прогон реально кладёт в texture_prompt.
func threedSentSteer(job Job) string {
	return steerFor(job.SurfaceSteer, threedJobOptions(job))
}
