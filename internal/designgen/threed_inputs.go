package designgen

// ═══ ЧТО ИМЕННО УЕЗЖАЕТ В СБОРКУ 3D — И ПОЧЕМУ ЭТО НЕ «ВСЕ КАРТИНКИ ПРОГОНА» ═══════════════════
//
// Владелец (круг 5, V-14): «в 3д INPUT — RENDERS BY VIEW нельзя никаким образом просунуть
// ПРАВИЛЬНЫЕ референсы». Слово «правильные» — про то, что в сборку уезжали НЕ ТЕ картинки.
//
// ЗАМЕР. `referenceList` собирает картинки прогона из четырёх источников: плиты верстака,
// референсы карточки (`design_reference`), явно названные `extra_input_media_ids` и фото ткани из
// рецепта. Для флэта и рендера это ровно верно — они рисуют ПО этим картинкам. Для 3D неверно
// дважды:
//
//  1. Meshy multi-image-to-3d принимает 1..4 картинки И ЧИТАЕТ КАЖДУЮ КАК ВИД ОДНОГО ПРЕДМЕТА
//     (meshy.MinImages/MaxImages, image_urls[0] = фронт). Пятой картинке там места нет вовсе:
//     `meshy.Submit` отказывает ЛОКАЛЬНО, до сети. То есть на карточке, где у человека есть хоть
//     несколько референсов настроения, КАЖДЫЙ прогон 3D умирал у двери провайдера — не «иногда», а
//     всегда, потому что референсы есть на всякой живой карточке.
//  2. Хуже тихого отказа — тихий успех. Карточка с одним-двумя референсами и незаполненным
//     рендер-верстаком отправляла в сборку РЕФЕРЕНСЫ вместо видов: Meshy получал две фотографии
//     чужой одежды и строил модель по ним. Прогон закрывался `done`, деньги списывались, и по
//     истории отличить это от честной сборки было нечем.
//
// ПОЭТОМУ У 3D СПИСОК КАРТИНОК — ЭТО ЕГО СОБСТВЕННЫЕ ПЛИТЫ, и ничего кроме. Не сужение
// возможностей, а называние того, чем 3D является: поворотный стол крутит ВИДЫ ИЗДЕЛИЯ, и картинка,
// которая не вид этого изделия, в нём не роль, а помеха. Человек по-прежнему решает, ЧТО именно
// стоит в каждом виде — он ставит туда любую картинку рода `render`, свою или сгенерённую, — и
// именно это и есть «просунуть правильные референсы».
//
// ⚠ ФИЛЬТР ЖИВЁТ ЗДЕСЬ, А НЕ ВНУТРИ referenceList, И ЭТО НЕ СТИЛЬ. `referenceList` — общий сборщик
// для всех родов, и его правило дедупликации несущее: плита, названная ещё и референсом, держит
// ПЕРВУЮ позицию (порядок = смысл на маршруте 3D) и ДОПОЛНЯЕТ подпись словами человека. Отбирать
// внутри него значило бы завести четвёртый род внутри одного цикла; отбирать после — значит взять
// уже правильно упорядоченный и правильно подписанный список и оставить в нём свои строки.

// threedPictures — плиты ЭТОГО прогона, в том порядке, в котором их уже поставил referenceList
// (front, back, side_l, side_r, detail — см. viewRank), с их подписями.
//
// ОТБОР ИДЁТ ПО media_id ПЛИТ СНИМКА, а не по «первым N элементам списка»: позиционное правило
// сломалось бы на первом же снимке, где плита названа ещё и референсом, — и сломалось бы молча.
//
// ПУСТОЙ ОТВЕТ ЗАКОНЕН И ГОВОРИТ ПРАВДУ. Прогон 3D без единой плиты — это прогон, которому нечего
// крутить; провайдер отказывает своим `ErrImageCount` («a turntable needs at least the front
// view»), и такой отказ читается человеком. Подставить вместо плит что попало, лишь бы список был
// непуст, значило бы купить модель неизвестно чего.
func threedPictures(list []refCaption, in runInputs) []refCaption {
	plates := make(map[int]struct{}, len(in.Slots))
	for _, s := range in.Slots {
		if s.MediaID > 0 {
			plates[s.MediaID] = struct{}{}
		}
	}
	if len(plates) == 0 {
		return nil
	}
	out := make([]refCaption, 0, len(plates))
	for _, rc := range list {
		if _, ok := plates[rc.MediaID]; ok {
			out = append(out, rc)
		}
	}
	return out
}
