package designgen

// ═══ ЧТО ИМЕННО УЕЗЖАЕТ В ПЕРЕКРАС И В ПАТТЕРН — И ПОЧЕМУ ЭТО НЕ «ВСЕ КАРТИНКИ ПРОГОНА» ═════════
//
// Довод здесь ТОТ ЖЕ, что уже записан в threed_inputs.go, и повторяется он потому, что ловушка та
// же и стоит дороже всего именно на этих двух маршрутах.
//
// `referenceList` собирает картинки прогона из четырёх источников: плиты верстака, референсы
// карточки, явно названные `extra_input_media_ids` и фото тканей рецепта. Для флэта и рендера это
// ровно верно: они РИСУЮТ ПО этим картинкам, и чем больше сказано, тем лучше. Для перекраса и для
// паттерна это неверно, причём молча:
//
//  1. ПЕРЕКРАС ОБЯЗАН ВЕРНУТЬ ТУ ЖЕ САМУЮ ФОТОГРАФИЮ. Инструкция «перекрась вещь на этом снимке,
//     сохранив кадр, позу, свет и складки» имеет смысл ровно при ОДНОМ снимке в вызове. Дай модели
//     вторую картинку — плиту флэта, чужой референс настроения, фото ткани — и она законно поймёт
//     её как материал для композиции: вернётся ПОХОЖИЙ кадр вместо ТОГО ЖЕ. Деньги списаны, прогон
//     закрыт `done`, и по истории такой результат не отличить от честного.
//
//  2. У ПАТТЕРНА ВХОД ЕДИНСТВЕННЫЙ ПО ОПРЕДЕЛЕНИЮ. «Заапдоудить картинку и сделать из неё
//     повторяемый паттерн» — из НЕЁ, а не из неё и ещё трёх. Плитка, собранная из двух лоскутов,
//     не стыкуется сама с собой ни при каком раскладе, то есть бесполезна ровно в том смысле, ради
//     которого её заказывали.
//
// ⚠ ОТБОР ЖИВЁТ ЗДЕСЬ, А НЕ ВНУТРИ referenceList, И ЭТО НЕ СТИЛЬ — ровно тот же довод, что у 3D:
// `referenceList` общий сборщик, и его правило дедупликации несущее (первая позиция, склеенные
// подписи). Отбирать внутри него значило бы завести пятый род внутри одного цикла; отбирать после —
// значит взять уже правильно упорядоченный и подписанный список и оставить в нём свои строки.

// sourcePictures — картинки, НАЗВАННЫЕ КЛИЕНТОМ ЯВНО (`params.extra_input_media_ids`), в том
// порядке, в котором их уже поставил referenceList, с их подписями.
//
// ОТБОР ИДЁТ ПО media_id, а не по «последним N элементам списка»: позиционное правило сломалось бы
// на первом же прогоне, где названная картинка стоит ещё и в верстаке, — и сломалось бы молча.
//
// ПУСТОЙ ОТВЕТ ЗАКОНЕН И ГОВОРИТ ПРАВДУ. Прогон перекраса без единого снимка — это прогон, которому
// нечего перекрашивать; маршрут отказывает своим локальным сентинелом ДО сети, то есть бесплатно, и
// такой отказ человек читает. Подставить вместо снимка что попало, лишь бы список был непуст,
// значило бы купить картинку неизвестно чего.
//
// ⚠ ПОЛЕ НАЗЫВАЕТСЯ «EXTRA», А НЕСЁТ ЗДЕСЬ ГЛАВНЫЙ ВХОД, И ЭТО ОСОЗНАННОЕ ПОВТОРНОЕ ИСПОЛЬЗОВАНИЕ,
// А НЕ НЕДОСМОТР. Это ОДИН список «медиа, которые человек дал этому прогону»: он уже проверен
// границей карточки у двери (designRefuseForeignMedia), уже замерзает в параметрах и уже доезжает
// до сборщика ссылок. Второе поле с тем же смыслом означало бы вторую границу карточки, второй путь
// заморозки и второе место, где о проверке забудут, — ровно тот класс дефекта, за который этот
// репозиторий уже платил.
func sourcePictures(list []refCaption, p runParams) []refCaption {
	if len(p.ExtraInputMediaIDs) == 0 {
		return nil
	}
	want := make(map[int]struct{}, len(p.ExtraInputMediaIDs))
	for _, id := range p.ExtraInputMediaIDs {
		if id > 0 {
			want[id] = struct{}{}
		}
	}
	out := make([]refCaption, 0, len(want))
	for _, rc := range list {
		if _, ok := want[rc.MediaID]; ok {
			out = append(out, rc)
		}
	}
	return out
}

// clothPictures — ТКАНИ РЕЦЕПТА, которые уезжают ВМЕСТЕ С КАЖДЫМ снимком перекраса (J-31).
//
// ═══ ПОЧЕМУ ЭТО НЕ ПРОТИВОРЕЧИТ ВСЕМУ, ЧТО НАПИСАНО ВЫШЕ ═══════════════════════════════════════
//
// Довод sourcePictures — «вторая картинка в вызове превращает „верни ТОТ ЖЕ кадр“ в „сочини
// похожий“» — верен ровно про ВТОРУЮ ФОТОГРАФИЮ: чужой референс настроения, плиту флэта, кадр
// другого ракурса. Модель законно поймёт её как материал для КОМПОЗИЦИИ, потому что она
// изображает то же самое, что и первая, — сцену.
//
// Плитка ткани не изображает сцену. Владелец просит именно её: «загрузить несколько фото на модели
// в нашей вещи и выбрать и или паттерн/цвет и результатом должен быть уже то что там вещь поменяла
// цвет ткань». Без картинки ткани «переодень» выражается только словами, а слова о ткани —
// приглашение перерисовать кадр целиком. Разницу держит ПРОМПТ: картинка 1 названа фотографией,
// которую перекрашивают, картинка 2 — тканью, которую на неё кладут (reclothCraft), и весь список
// запретов старого ремесла остаётся в силе.
//
// ⚠ ОТБОР ПО media_id, А НЕ ПО ПОЗИЦИИ — тот же довод, что у sourcePictures: позиционное правило
// сломалось бы на первом же прогоне, где ткань стоит ещё и в верстаке.
//
// ⚠ ЧТО ЭТА ФУНКЦИЯ НЕ ДЕЛАЕТ И ПОЧЕМУ. Она НЕ вычитает из своего ответа фотографии прогона.
// Прежняя редакция этого комментария утверждала, что «после сужения списки пересекаться не
// должны», и не держало это утверждение НИЧТО: медиа, названное и фотографией
// (`extra_input_media_ids`), и тканью, давало вызов `[9.png, 9.png]` — одна картинка дважды в
// одном платном запросе, с просьбой вернуть ТУ ЖЕ ФОТОГРАФИЮ лоскута, переодетую в него же.
//
// Вычесть их ЗДЕСЬ нельзя, и это не осторожность: ремесло ветвится по ЗАМОРОЖЕННЫМ params
// (recolorprompt.go, clothsWithTexture), а вложения строит эта половина. Убрав ткань тут, мы
// получили бы промпт, который говорит «the cloth in image 2» там, где второй картинки нет вовсе, —
// то есть поменяли бы двойную оплату на промпт, указывающий в пустоту. Поэтому гарантия живёт
// ОДНА и живёт у двери: designRefuseUnworkableRecolourCloth (apisrv/admin) отказывает такому
// прогону бесплатно, до резерва, и спрашивает ДЕЙСТВУЮЩИЕ параметры — то есть связывает и реран
// замороженной строки тоже.
//
// ⚠ ТКАНЬ БЕЗ КАРТИНКИ СЮДА НЕ ПОПАДАЕТ ВОВСЕ. Дверь уже отказала такому прогону
// (`cloth_without_picture`), но правило повторено здесь, а не оставлено на дверь: снимок мог быть
// заморожен до неё, а `media_id = 0` — это «ткани не показывали», и подставить вместо неё что
// попало значило бы купить картинку неизвестно чего.
func clothPictures(list []refCaption, p runParams) []refCaption {
	want := make(map[int]struct{}, 2)
	for _, f := range statedCloths(p.Colour) {
		if f.MediaID > 0 {
			want[f.MediaID] = struct{}{}
		}
	}
	if len(want) == 0 {
		return nil
	}
	out := make([]refCaption, 0, len(want))
	for _, rc := range list {
		if _, ok := want[rc.MediaID]; ok {
			out = append(out, rc)
		}
	}
	return out
}
