package entity

import (
	"database/sql"
	"errors"
	"fmt"
	"time"
)

// ГРУППИРОВКА ФАЙЛОВ: ПРОЕКТ × РОЛЬ.
//
// Тема получает ТИП (обычный ярлык или проект), а роль файла В ПРОЕКТЕ живёт на СТРОКЕ СВЯЗИ
// `library_file_topic.role_id` — не второй меткой на файле. Разница не косметическая: плоский
// набор меток теряет ПАРУ. Снимок, лежащий в съёмке как «отобранное» и в лукбуке как «референс»,
// нёс бы {съёмка, лукбук, отобранное, референс}, и пересечение «съёмка × референс» находило бы
// его — молча и ложно, потому что выдача выглядит правдоподобной и проверить её нечем.
//
// «Одна роль на файл в проекте» при этом не правило, а форма данных: UNIQUE(file_id, topic_id)
// (0312) даёт ровно одну строку на пару, у строки ровно одно поле роли. Две роли в одном проекте
// НЕВЫРАЗИМЫ, поэтому и запрещать нечего. Невыразимо и другое — роль БЕЗ проекта; это верное
// поведение, а не потеря: «это исходник ничего» не значит ничего.

// FileTopicKind — тип темы. Закрытое множество, и оно закрыто в схеме (ENUM), а не соглашением:
// неизвестное значение отвергается, а не интерпретируется.
type FileTopicKind string

const (
	// FileTopicKindPlain — обычный ярлык. Значение по умолчанию в схеме, поэтому все темы,
	// заведённые до 0320, остаются им без бэкфилла.
	FileTopicKindPlain FileTopicKind = "plain"
	// FileTopicKindProject — проект: даты, архив, разбивка по ролям.
	FileTopicKindProject FileTopicKind = "project"
)

// ParseFileTopicKind принимает то, что приехало с провода. ПУСТАЯ строка — это «plain», а не
// ошибка: тема, сохранённая до появления поля, приезжает без него, и отказывать на ней значило бы
// уронить переименование обычной темы.
func ParseFileTopicKind(s string) (FileTopicKind, error) {
	switch FileTopicKind(s) {
	case "", FileTopicKindPlain:
		return FileTopicKindPlain, nil
	case FileTopicKindProject:
		return FileTopicKindProject, nil
	default:
		return "", fmt.Errorf("%w: %q", ErrFileTopicKindUnknown, s)
	}
}

var (
	// ErrFileTopicKindUnknown — тип темы, которого нет в схеме. InvalidArgument у вызывающего.
	ErrFileTopicKindUnknown = errors.New("unknown file topic kind")
	// ErrFileTopicKindMismatch запрещает слияние тем РАЗНЫХ типов. Слить проект в обычную тему
	// нечем: у проекта есть даты, архив и роли на строках связи, у ярлыка ничего этого нет, и
	// вопрос «что станет с ролями» не имеет хорошего ответа. Хуже того, роли уехали бы на строки
	// темы, которая проектом не является, — то самое состояние, которое стор нигде больше не
	// допускает.
	ErrFileTopicKindMismatch = errors.New("topics of different kinds cannot be merged")
	// ErrRoleNeedsProjectTopic — попытка поставить роль в теме, которая не проект. Проверяется в
	// одном месте (там, где роль ставится); констрейнтом это не выражается без денормализации
	// `kind` в таблицу связи, а денормализация давала бы устаревающие строки при смене типа.
	ErrRoleNeedsProjectTopic = errors.New("roles can only be set inside a project topic")
	// ErrFileRoleArchived — назначить заархивированную роль нельзя (снять — можно). Иначе архив
	// был бы пожеланием: роль пропала бы из пикеров и продолжила бы появляться на файлах.
	ErrFileRoleArchived = errors.New("archived role cannot be assigned")
	// ErrStyleNeedsProjectTopic — попытка привязать стиль к теме, которая не проект. По тому же
	// доводу, что ErrRoleNeedsProjectTopic: проверка в коде, а не CHECK'ом. Ретроактивный CHECK
	// проверяет ВСЮ историю и останавливает старт прода, а денормализация `kind` во вторую
	// таблицу давала бы устаревающие строки при смене типа темы.
	//
	// Отдельная ошибка, а не переиспользованная ErrRoleNeedsProjectTopic: у них разные фразы и
	// разные экраны, и слепить их значило бы получить «roles can only be set…» в диалоге,
	// который про роли не говорит ни слова.
	ErrStyleNeedsProjectTopic = errors.New("styles can only be linked to a project topic")
	// ErrTaskNeedsProjectTopic — попытка привязать карточку канбана к теме, которая не проект
	// (0322). Третий член одной семьи, и живёт он здесь, а не в task.go, ровно поэтому: правило
	// «проектное свойство бывает только у проекта» одно, и три его случая обязаны читаться рядом.
	//
	// НЕСУЩЕСТВУЮЩАЯ ТЕМА СЮДА НЕ ПОПАДАЕТ — на неё отвечает внешний ключ, как на остальных семи
	// глубоких ссылках задачи. Разница существенная: несуществующий id это опечатка, одинаковая
	// для всех восьми типов, а ярлык вместо проекта — осмысленный выбор не той сущности, и о нём
	// надо сказать фразой.
	ErrTaskNeedsProjectTopic = errors.New("tasks can only be linked to a project topic")
)

// FileRole — одна запись ЗАКРЫТОГО словаря ролей.
//
// Закрытость держится на форме данных, а не на дисциплине: роли лежат в СВОЕЙ таблице, поэтому ни
// `new_topics` при загрузке, ни модалка вставки, ни массовое проставление тем создать роль не
// могут — они пишут в file_topic. Единственная точка создания — UpsertRole.
//
// Отдельная таблица, а не третье значение `kind`, ещё и потому, что иначе каждый уже отгруженный
// путь, перечисляющий темы со счётчиками (рельс, чипы, четыре пикера), пришлось бы учить
// «исключай роли».
type FileRole struct {
	Id   int    `db:"id"`
	Name string `db:"name"`
	// SortOrder — порядок секций на странице проекта. Равные значения сортируются по имени,
	// чтобы порядок был полным и не зависел от порядка вставки.
	SortOrder int `db:"sort_order"`
	// ArchivedAt — invalid/NULL значит «не в архиве». Архив прячет роль из чипов и пикеров,
	// оставляя её на экране тем и на уже проставленных файлах.
	ArchivedAt sql.NullTime `db:"archived_at"`
	CreatedAt  time.Time    `db:"created_at"`
}

// FileRoleWithCount — роль плюс СКВОЗНОЙ счётчик: сколько файлов несут её в любом проекте.
// Счётчик всегда выводится запросом; колонки-счётчика нет, потому что ей было бы с чем разойтись.
type FileRoleWithCount struct {
	FileRole
	FilesCount int `db:"files_count"`
}

// FileRoleUpsert — запись словаря. Id = 0 создаёт, иначе правит существующую.
type FileRoleUpsert struct {
	Id        int
	Name      string
	SortOrder int
	Archived  bool
}

// LibraryFileRoleRef — «чем этот файл является В ЭТОМ проекте»: ПАРА, а не ярлык.
//
// Именно пара едет на провод и рисуется на плитке («осень 2026 · исходники»). Плоский список
// ролей на файле был бы той самой моделью, ради ухода от которой всё это писалось.
type LibraryFileRoleRef struct {
	ProjectTopicId   int    `db:"project_topic_id"`
	ProjectTopicName string `db:"project_topic_name"`
	RoleId           int    `db:"role_id"`
	RoleName         string `db:"role_name"`
}

// FileTopicMetaUpdate — ПОЛНАЯ замена метаданных темы: тип, даты, архив.
//
// Замена безопасна ровно потому, что RPC новый и старого клиента у него нет — форма всегда
// приезжает целиком. Дописать эти поля в уже отгруженный RenameFileTopic было бы дешевле на один
// RPC и опаснее по существу: клиент, не знающий про `kind`, прислал бы пустой тип и молча понизил
// бы проект до обычной темы при первом же переименовании.
type FileTopicMetaUpdate struct {
	TopicId  int
	Kind     FileTopicKind
	StartsAt sql.NullTime
	EndsAt   sql.NullTime
	Archived bool
}

// FileTopicMetaResult — ЧТО ПОНИЖЕНИЕ ПРОЕКТА УНЕСЛО С СОБОЙ. ТРИ числа, а не одно, потому что
// проектных свойств у темы стало три: роли на строках связи (0320), привязанные стили (0321) и
// задачи, которые в этом проекте делаются (0322).
//
// СТРУКТУРА, А НЕ ТРИ int В ВОЗВРАТЕ, И ЭТО НЕ СТИЛЬ. Безымянные `(int, int, int, error)`
// читаются на месте вызова как «cleared, something, something, err», и следующее проектное
// свойство поедет четвёртым числом в том же порядке — перепутать их будет нечем, кроме
// внимательности. Поле с именем перепутать нельзя. Третье число и написано ради этой проверки:
// набор тестов ставит РАЗНЫЕ количества ролей, стилей и задач и сверяет, что каждое приехало в
// своё поле, — подмена одного другим на равных количествах была бы невидима.
//
// ЗАЧЕМ ВООБЩЕ СЧИТАТЬ. Понижение необратимо по содержанию: обратное повышение вернёт тип, но не
// вернёт ни ролей, ни привязок. Молчаливое понижение, снявшее сорок связей, снаружи неотличимо от
// понижения, не снявшего ни одной, — и человек узнаёт о потере в тот день, когда придёт искать
// «каким файлом сделана эта вещь» и не найдёт ничего.
type FileTopicMetaResult struct {
	// ClearedRoles — сколько ВИДИМЫХ строк связи потеряли роль (0320).
	ClearedRoles int
	// ClearedStyles — сколько привязок к стилям снято. Предиката видимости у этого числа нет и
	// быть не может: стиль — не файл библиотеки, он живёт под собственным RBAC секции techcards,
	// и прятать его от того, кто и так правит проект, было бы придумыванием несуществующей
	// границы. Число здесь ТОЧНОЕ, в отличие от соседнего.
	ClearedStyles int
	// ClearedTasks — сколько карточек канбана потеряли ссылку на проект (0322). Считается ТОЧНО,
	// по тому же доводу, что и стили: задача не файл библиотеки, она живёт под собственным RBAC
	// секции tasks, и предикат видимости файлов к ней неприменим. Сами карточки при этом целы —
	// понижение снимает ссылку, а не работу.
	ClearedTasks int
}

// FileTopicDeleteResult — ЧТО УДАЛЕНИЕ ТЕМЫ УНЕСЛО С СОБОЙ.
//
// Появилась ровно тогда, когда чисел стало два: раньше DeleteTopic возвращал голый int, и второе
// число пришлось бы дописать к нему безымянной парой — той самой формой, от которой ушёл
// FileTopicMetaResult выше. Оба числа ТОЧНЫЕ: ни стиль, ни задача не являются файлом библиотеки.
//
// Ни то, ни другое удаление НЕ ЗАПРЕЩАЕТ. Отказ был бы тупиком: счётчик на экране тем показывает
// ФАЙЛЫ и ни о привязках, ни о задачах не знает, поэтому человек упёрся бы в «нельзя» без единого
// способа увидеть, во что именно. Но названы они быть обязаны — иначе «убрал законченную съёмку с
// глаз» и «у двенадцати карточек пропал контекст» станут двумя событиями, между которыми месяц.
type FileTopicDeleteResult struct {
	// UnlinkedStyles — сколько вещей потеряли ответ на «каким файлом меня сделали» (0321).
	UnlinkedStyles int
	// UnlinkedTasks — сколько карточек канбана потеряли ссылку на проект (0322). Ключ стоит с
	// ON DELETE SET NULL, поэтому задачи остаются: они про работу, а не про съёмку.
	UnlinkedTasks int
}

// FileTopicStyleRef — СТИЛЬ ГЛАЗАМИ СТРАНИЦЫ ПРОЕКТА: то, чем вещь опознают на экране.
//
// Не вся тех-карта и даже не её краткая форма: страница проекта показывает список привязанных
// вещей, и всё, что ей нужно, — номер (артикул), имя, стадия и картинка. Тянуть сюда entity.TechCard
// значило бы возить полсотни полей ради четырёх и завести второй путь чтения стиля, который
// разойдётся с настоящим.
type FileTopicStyleRef struct {
	TechCardId  int    `db:"tech_card_id"`
	StyleNumber string `db:"style_number"`
	Name        string `db:"name"`
	// Stage — стадия разработки. Она здесь не для красоты: «бекап CLO» у идеи и у стиля в
	// производстве значат разное, и без стадии список выглядит плоским перечнем имён.
	Stage TechCardStage `db:"stage"`
	// LinkedAt — когда привязали. Порядок списка строится по нему.
	LinkedAt time.Time `db:"linked_at"`
	// PreviewURL — миниатюра для плитки. Заполняется НЕ этим запросом: правило выбора картинки
	// (стадия × категория медиа × вид) живёт в сторе тех-карт, и вторая его реализация здесь
	// разошлась бы с первой молча. Пустая строка — законное значение: у стиля может не быть ни
	// одного медиа, и плитка рисует табличку с артикулом.
	PreviewURL string `db:"-"`
}

// StyleProjectLink — ПРОЕКТ ГЛАЗАМИ КАРТОЧКИ ВЕЩИ. Главный ответ всей фазы: «какие проекты меня
// касаются».
//
// Внутри — обычная тема со счётчиком, тот же FileTopicWithCount, что едет в рельс. Своей усечённой
// формы у проекта здесь нет намеренно: карточка вещи печатает имя, тип, даты, архивность и число
// файлов — ровно то, что рельс уже умеет, — и вторая форма тех же полей означала бы второй набор
// правил их заполнения.
//
// FilesCount СЧИТАЕТСЯ ПОД ПРЕДИКАТОМ ВИДИМОСТИ. Это не аккуратность, а граница: иначе карточка
// вещи стала бы боковым каналом, через который видно, что в проекте есть файлы, которых
// спрашивающему не показывают. Число у разных людей поэтому разное — то же принятое следствие,
// что у счётчиков тем и ролей.
type StyleProjectLink struct {
	FileTopicWithCount
	// LinkedAt — когда стиль привязали к проекту.
	LinkedAt time.Time `db:"linked_at"`
}
