package entity

import "strings"

// КАК АДРЕСУЕТСЯ УКАЗАНИЕ НА ЭСКИЗЕ — ОДНО ПРАВИЛО НА ВСЕХ, КТО СПРАШИВАЕТ.
//
// НОМЕР ВЫНОСКИ НЕ УНИКАЛЕН ПО КАРТОЧКЕ, И ЭТО НЕ ПОРЧА ДАННЫХ. Эскиз и мудборд — два разных
// документа, и клиент нумерует их НЕЗАВИСИМО, намеренно: «The sketch and the moodboard number
// INDEPENDENTLY … a moodboard reference note has no business pushing the next sketch callout to 7»
// (admin-client, sketch-tab.tsx, isMine/nextNumber). Схема дубли тоже не запрещает: у
// tech_card_callout нет ни одного UNIQUE, а сам номер — `callout_number INT NOT NULL DEFAULT 0`
// (0067_add_tech_card_core.sql:113). Значит «выноска номер 3» на карточке с мудбордом — вопрос без
// ответа, пока не назван ЭСКИЗ, на котором она стоит.
//
// ПОЧЕМУ ПРАВИЛО ЖИВЁТ ЗДЕСЬ, А НЕ У КАЖДОГО ПОТРЕБИТЕЛЯ. Потому что записанное дважды оно
// разошлось — и разошлось В РАЗНЫЕ СТОРОНЫ. Индекс детали кроя писался в карту без условия, то
// есть ПОСЛЕДНИЙ выигрывал; перенос геометрии брал ПЕРВОГО. На одной и той же карточке мудбордная
// выноска с номером технической молча помечала живую деталь кроя detached (у неё пропадал
// технический источник имени), а перенос геометрии в том же сохранении смотрел при этом на ДРУГУЮ
// выноску. Ни один из двух ответов не был неправильным сам по себе — неправильным было то, что
// ответов два.
//
// ГРАНИЦА ОДНА: поиск по номеру НИКОГДА не пересекает эскизы. Деталь кроя спрашивает про
// ТЕХНИЧЕСКИЙ лист (S7: мудбордное указание не несёт смысла детали), перенос геометрии — про тот
// самый эскиз, на котором стоит присланное указание. Остаточная неоднозначность — два указания с
// ОДНОЙ идентичностью — решается ПО МЕСТУ, и по-разному, потому что цена ошибки разная:
// у ПЕРЕНОСА содержания неоднозначный ключ ВЫБРАСЫВАЕТСЯ (принести чужую мерку хуже, чем не
// принести своей), у ИНДЕКСА ДЕТАЛИ выигрывает первый (там дубль — уже испорченные данные, и от
// выбора требуется только детерминированность).

// TechCardCalloutKey — идентичность указания на карточке: эскиз, на котором оно стоит, и его
// номер. Номера самого недостаточно (см. выше), поэтому пары нет и быть не может отдельно от
// картинки.
type TechCardCalloutKey struct {
	MediaId int // 0 — указание ни на чём не запинено
	Number  int
}

// CalloutKey — идентичность ЭТОГО указания.
func (c TechCardCallout) CalloutKey() TechCardCalloutKey {
	id := 0
	if c.MediaId.Valid {
		id = int(c.MediaId.Int32)
	}
	return TechCardCalloutKey{MediaId: id, Number: c.Number}
}

// TechCardCalloutIndex — разрешение ссылки «деталь кроя → выноска» (S6/S7/S8). Держит ТОЛЬКО
// указания, запиненные на ТЕХНИЧЕСКИЕ эскизы этой карточки: только они несут смысл детали, и
// только их номера деталь и имеет в виду.
type TechCardCalloutIndex struct {
	byNumber map[int]TechCardCallout
}

// NewTechCardCalloutIndex индексирует технические указания карточки по номеру. Медиа и указания
// приезжают ОДНИМ payload'ом вместе с деталями, поэтому чтения из базы здесь не нужно.
//
// В индекс не попадает ничто, кроме указаний на технических эскизах, — ровно то, что ApplyToPiece
// и так требовало. Пока в него писались все подряд, мудбордный двойник ВЫТЕСНЯЛ техническую
// выноску из карты, и деталь, у которой источник имени никуда не девался, объявлялась оторванной.
func NewTechCardCalloutIndex(media []TechCardMediaItem, callouts []TechCardCallout) TechCardCalloutIndex {
	technical := TechCardTechnicalMedia(media)
	ix := TechCardCalloutIndex{byNumber: make(map[int]TechCardCallout, len(callouts))}
	for _, c := range callouts {
		// Незапиненное указание в индекс не идёт: по нумерации оно принадлежит техническому листу
		// (клиентское isMine), но стоит НЕ НА ЭСКИЗЕ, а значит источником имени детали быть не
		// может (S7). Незнакомая картинка — тоже мимо: technical[…] по ней ложно.
		if !c.MediaId.Valid || !technical[int(c.MediaId.Int32)] {
			continue
		}
		if _, seen := ix.byNumber[c.Number]; seen {
			// Здесь первый ВЫИГРЫВАЕТ — и это осознанное расхождение с ПОЗИЦИОННЫМ переносом
			// (TechCardCalloutPositional). Индекс строится по номеру и только по ТЕХНИЧЕСКИМ
			// эскизам, где два указания с одним номером — испорченные данные; ответив «никак», мы
			// объявили бы живую деталь кроя оторванной, то есть создали бы потерю на ровном месте.
			// Там переносится СОДЕРЖАНИЕ и порядок значим; здесь разрешается ССЫЛКА, и от ответа
			// требуется только быть.
			continue
		}
		ix.byNumber[c.Number] = c
	}
	return ix
}

// TechnicalCallout — техническое указание с этим номером, если оно есть.
func (ix TechCardCalloutIndex) TechnicalCallout(number int) (TechCardCallout, bool) {
	c, ok := ix.byNumber[number]
	return c, ok
}

// ApplyToPiece сводит имя детали кроя с её технической выноски и выставляет detached (S7/S8):
// деталь, привязанная к техническому указанию, берёт его `part` своим каноническим именем (имя
// детали живёт ОДИН раз, на выноске); деталь, чьё указание удалили или чьё указание мудбордное
// либо незапиненное, СВОЁ имя сохраняет, но помечается detached — живого технического источника у
// неё нет. Оторванную деталь orphan-control сохраняет, а не удаляет.
func (ix TechCardCalloutIndex) ApplyToPiece(p *TechCardPiece) {
	if !p.CalloutNumber.Valid {
		p.Detached = false
		return
	}
	c, ok := ix.TechnicalCallout(int(p.CalloutNumber.Int32))
	if !ok {
		p.Detached = true
		return
	}
	if part := strings.TrimSpace(c.Part.String); part != "" {
		p.Name = part
	}
	p.Detached = false
}

// TechCardTechnicalMedia — ЛИСТ карточки: её ТЕХНИЧЕСКИЕ эскизы, по media(id).
//
// ЖИВЁТ ЗДЕСЬ, ПОТОМУ ЧТО «ЧТО ТАКОЕ ЛИСТ» — ЧАСТЬ ПРАВИЛА АДРЕСАЦИИ, а не деталь одного
// потребителя. Ровно это множество отделяет эскиз от мудборда в индексе детали кроя, и ровно оно
// решает, чья выноска берёт номер листа. Написанное дважды, оно разъедется — как уже разъехалось
// правило «выноска по номеру», пока его не свели в этот файл.
//
// ОСЬ — CATEGORY, А НЕ KIND, и это не придирка. category это и есть «в каком из двух списков лежит
// картинка» (moodboard против technical), а kind — подклассификатор ВНУТРИ списка (front, back,
// swatch, reference…). Решать по kind значило бы завести вторую ось там, где первая уже есть, и
// первая же картинка с kind='reference' в техническом списке разошлась бы с индексом детали кроя.
func TechCardTechnicalMedia(media []TechCardMediaItem) map[int]bool {
	technical := make(map[int]bool, len(media))
	for _, m := range media {
		if m.Category == TechCardMediaCategoryTechnical {
			technical[m.MediaId] = true
		}
	}
	return technical
}

// TechCardMoodboardMedia — МУДБОРД карточки, по media(id). Вторая половина той же оси, что и
// TechCardTechnicalMedia, и живёт рядом с ней по той же причине.
func TechCardMoodboardMedia(media []TechCardMediaItem) map[int]bool {
	mood := make(map[int]bool, len(media))
	for _, m := range media {
		if m.Category == TechCardMediaCategoryMoodboard {
			mood[m.MediaId] = true
		}
	}
	return mood
}

// CalloutTakesSheetNumber — БЕРЁТ ЛИ ЭТО УКАЗАНИЕ НОМЕР ЛИСТА.
//
// Номер выноски — это адрес НА ЛИСТЕ: на него ссылаются деталь кроя, операция, дефект и печатный
// тех-пак. Мудбордная заметка ни для кого из них адресом не является — эскиз и мудборд нумеруются
// НЕЗАВИСИМО (см. шапку файла), — поэтому номер листа она брать не имеет права. Без этого предиката
// мудбордная заметка, назвавшая себя client_ref (а F-4 обязывает её это делать, иначе она станет
// новым легаси-нулём), СЪЕЛА бы очередной номер листа: нумерация листа поехала бы дырами, а сам
// номер перестал бы означать «выноска номер N на эскизе».
//
// МУДБОРДНАЯ ЗАМЕТКА ОСТАЁТСЯ С НУЛЁМ, И ЭТО ЕЁ ЧЕСТНОЕ СОСТОЯНИЕ, а не легаси-ноль: её личность
// несёт client_ref, по нему её и адресуют форма и «отказ ведёт в место». Легаси-ноль — это ноль БЕЗ
// ключа, и он остаётся неотличим и нетронут, как и был.
//
// И ЭТУ ЛИЧНОСТЬ СЕРВЕР ДЕЙСТВИТЕЛЬНО ЗАЩИЩАЕТ, а не только обещает: CarryOmittedCalloutClientRef
// возвращает ключ строке с нулевым номером, если он на её картинке ОДИН. Первая версия предиката
// этого не делала — перенос отказывался трогать нули, — и утверждение выше было ложным: заметка
// теряла ключ при каждом сохранении из вкладки со старым бандлом, молча и без сдвига подписи, ведь
// ключ в дайджест не входит. Оговорка «если он один» существенна: несколько нулей на одной картинке
// неразличимы, и там адрес не выдаётся никому — довод целиком у TechCardCalloutPositional.Unique.
//
// ⚠ ПРЕДИКАТ ОТКАЗЫВАЕТ ПО ПОЛОЖИТЕЛЬНОМУ ПРИЗНАКУ МУДБОРДА, А НЕ ПО ОТСУТСТВИЮ ТЕХНИЧЕСКОГО, и
// это НЕ то же самое, что делает TechCardCalloutIndex. Асимметрия намеренная, потому что цена
// ошибки у двух вопросов разная и направлена в разные стороны:
//
//   - индекс спрашивает «может ли эта выноска ДАТЬ ИМЯ детали кроя» — и требует положительного
//     доказательства технического эскиза, потому что ЧУЖОЕ ИМЯ на детали хуже, чем флаг detached;
//   - здесь спрашивают «дать ли выноске АДРЕС» — и отказ требует положительного доказательства
//     мудборда, потому что невыданный адрес это тоже молчаливая потеря: выноска остаётся нулём с
//     ключом навсегда, то есть ровно тем состоянием, которое ключ и заведён устранить.
//
// Значит незнакомая картинка (медиа, которого payload не перечисляет вовсе) номер БЕРЁТ. Ось при
// этом одна — category, — и обе половины читают её из одного payload'а функциями из этого файла.
//
// НЕЗАПИНЕННОЕ УКАЗАНИЕ НОМЕР БЕРЁТ. Оно не мудбордное: мудбордная заметка запинена на мудбордную
// картинку (второго дома у указаний нет — они все живут в одном массиве callouts и различаются
// картинкой). Незапиненное — это либо указание, которое ещё не поставили на эскиз, либо неякорная
// заметка листа, и печать сегодня считает неякорные ТЕХНИЧЕСКИМИ.
func CalloutTakesSheetNumber(c TechCardCallout, moodboardMedia map[int]bool) bool {
	if !c.MediaId.Valid || c.MediaId.Int32 == 0 {
		return true
	}
	return !moodboardMedia[int(c.MediaId.Int32)]
}

// TechCardCalloutPrintedLine — ПЕЧАТНАЯ СТРОКА УКАЗАНИЯ, собранная в одном месте.
//
// У выноски карточки нет одного текстового поля: смысл разложен на `part` (о какой детали),
// `description` (что с ней) и `dimensions` (мерка). Читателю — на экране и на бумаге — идёт
// СОСТАВНАЯ строка: три поля порознь это не указание, а три ячейки.
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ТРИ СТРОЧКИ НА МЕСТЕ. Собиравший её на месте читатель брал
// одно `description`, и указание-мерка (`part` заполнен, `description` пуст, `dimensions` = «6 мм»
// — самая обычная форма на чертеже) выходило БЕЗ ЕДИНОГО СИМВОЛА текста: номерная плашка, под
// которой ничего не написано. Пробы этого не видели, потому что во всех фикстурах текстовые поля
// были пусты. Одно написание на всех читателей — единственное, что этот класс расхождения
// закрывает.
//
// Форма совпадает с той, что клиент показывает на экране, — «полочка: обтачка, разрез (6 мм)», —
// потому что экран и бумага под одной подписью обязаны читаться одинаково.
func TechCardCalloutPrintedLine(c TechCardCallout) string {
	// ВСЕ детали, а не первая, и СПИСОК БЕРЁТСЯ У PartList — второго написания «какие детали у
	// указания» заводить нельзя. Свой цикл здесь отличался от PartList отсутствием дедупа, то есть
	// `parts = ["полочка","полочка"]` печаталось бы как «полочка, полочка», а хешировалось
	// (designProjection) как одна: бумага и подпись расходились бы на ровном месте.
	part := strings.Join(c.PartList(), ", ")
	desc := strings.TrimSpace(c.Description.String)
	dims := strings.TrimSpace(c.Dimensions.String)

	head := desc
	if part != "" {
		if desc != "" {
			head = part + ": " + desc
		} else {
			head = part
		}
	}
	// Мерка идёт В СКОБКАХ И В КОНЦЕ, чтобы никому не пришлось гадать, к чему она относится —
	// к детали или к тому, что с ней делают.
	if dims != "" {
		if head != "" {
			return head + " (" + dims + ")"
		}
		return dims
	}
	return head
}

// TechCardCalloutGroups — указания, сгруппированные по идентичности, В ИСХОДНОМ ПОРЯДКЕ.
//
// СУЩЕСТВУЕТ РАДИ ПЕРЕНОСА СОДЕРЖАНИЯ, И ТОЛЬКО РАДИ НЕГО. Когда идентичность делят несколько
// строк (две заметки на одной мудбордной картинке; легаси-нули на одном эскизе), «один ответ на
// ключ» неизбежно неправ: отдать первому — значит подменить второму, выбросить ключ — значит
// стереть обоим. Правильный ответ — n-я входящая строка берёт содержание у n-й хранимой: при
// полной замене клиент пересылает строки в исходном порядке, поэтому каждая получает своё, и
// чужое не едет никому.
//
// Порядок здесь — единственное, чем дубли различимы, поэтому он значащий, а не побочный.
func TechCardCalloutGroups(callouts []TechCardCallout) map[TechCardCalloutKey][]TechCardCallout {
	out := make(map[TechCardCalloutKey][]TechCardCallout, len(callouts))
	for _, c := range callouts {
		k := c.CalloutKey()
		out[k] = append(out[k], c)
	}
	return out
}

// TechCardCalloutPositional — счётчик «какая по счёту строка с этим ключом уже прошла».
//
// Next живёт на УКАЗАТЕЛЕ намеренно: он двигает счётчик, и копия структуры молча делила бы его с
// оригиналом. Подпись обязана говорить, что вызов меняет состояние.
// Живёт рядом с группами, потому что без него они бесполезны: сопоставление позиционное, и
// позицию надо где-то считать, пока идёшь по входящему списку.
type TechCardCalloutPositional struct {
	groups   map[TechCardCalloutKey][]TechCardCallout
	incoming map[TechCardCalloutKey]int
	seen     map[TechCardCalloutKey]int
}

// NewTechCardCalloutPositional берёт ОБЕ стороны пары: хранимые строки и входящие.
//
// Входящие нужны не для сопоставления, а для Unique: риск, ради которого Unique существует
// («выдать строке ЧУЖОЙ адрес»), — свойство ПАРЫ, а у пары две стороны. Две входящие безадресные
// строки против одной хранимой дают однозначность со стороны хранимого и неоднозначность со
// стороны входящего: первая по порядку забрала бы адрес, и если по порядку первой оказалась не та
// строка, адрес уехал бы чужой — ровно вопреки доводу.
func NewTechCardCalloutPositional(stored, incoming []TechCardCallout) TechCardCalloutPositional {
	counts := make(map[TechCardCalloutKey]int, len(incoming))
	for _, c := range incoming {
		counts[c.CalloutKey()]++
	}
	return TechCardCalloutPositional{
		groups:   TechCardCalloutGroups(stored),
		incoming: counts,
		seen:     make(map[TechCardCalloutKey]int, len(stored)),
	}
}

// Unique — единственная ли хранимая строка носит этот ключ. Нужен там, где позиционного
// сопоставления МАЛО: адрес строки (client_ref) при неоднозначном ключе лучше не выдавать вовсе,
// потому что позиция держится на порядке, а порядок держится на честности клиента. Ошибиться
// адресом — значит подсветить человеку ЧУЖУЮ строку, то есть ровно тот дефект, ради которого адрес
// и заведён. Геометрии это не касается: там позиционного сопоставления достаточно, потому что
// потеря фигуры видна, а её подмена при первом-победившем была бы не видна.
func (p TechCardCalloutPositional) Unique(k TechCardCalloutKey) bool {
	return len(p.groups[k]) == 1 && p.incoming[k] == 1
}

// Next — хранимая строка, соответствующая ОЧЕРЕДНОЙ входящей с этим ключом. Второй вызов с тем же
// ключом отдаёт вторую хранимую, и так далее; когда хранимые кончились, отдаёт false.
func (p *TechCardCalloutPositional) Next(k TechCardCalloutKey) (TechCardCallout, bool) {
	n := p.seen[k]
	p.seen[k] = n + 1
	group := p.groups[k]
	if n >= len(group) {
		return TechCardCallout{}, false
	}
	return group[n], true
}
